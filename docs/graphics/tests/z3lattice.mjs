import assert from 'node:assert/strict';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
const page = await context.newPage();
const errors = [];
page.on('pageerror', e => errors.push(e.message));
page.on('console', e => { if (e.type() === 'error' && !e.text().includes('404')) errors.push(e.text()); });
page.on('response', response => { if (response.status() >= 400 && !response.url().endsWith('/favicon.ico')) errors.push(`${response.status()} ${response.url()}`); });
const base = process.env.GRAPHICS_TEST_URL || 'http://localhost:8124/docs/graphics/';
try {
  await page.goto(`${base}stage.html?viz=z3lattice`);
  await page.frameLocator('#viz').locator('canvas[data-draw-calls]').waitFor();
  const canvas = page.frameLocator('#viz').locator('canvas');
  assert.equal(await canvas.getAttribute('data-point-count'), '3375');
  await page.getByRole('tab', { name: /^Advanced/ }).click();
  await page.locator('#controls details.cv-group').evaluateAll(cards => cards.forEach(card => { card.open = true; }));
  await page.getByRole('checkbox', { name: 'Animate waves', exact: true }).uncheck();
  await page.getByRole('checkbox', { name: 'Slow camera orbit', exact: true }).uncheck();
  await page.waitForTimeout(350);
  await page.screenshot({ path: '/tmp/z3lattice-sidebar.png' });
  const room = new URL(page.url()).searchParams.get('room');
  const remote = await context.newPage();
  await remote.goto(`${base}remote.html?room=${room}`);
  await remote.getByRole('combobox', { name: 'Scene', exact: true }).waitFor();
  await page.waitForFunction(() => document.body.classList.contains('presentation'));
  await page.waitForTimeout(400);
  await page.screenshot({ path: '/tmp/z3lattice-aurora.png' });
  await remote.getByRole('combobox', { name: 'Scene', exact: true }).selectOption('pearl');
  await page.waitForFunction(() => document.querySelector('#viz').contentDocument.querySelector('#palette').value === 'pearl');
  assert(Number(await canvas.getAttribute('data-point-count')) < 17**3);
  await page.waitForTimeout(350);
  await page.screenshot({ path: '/tmp/z3lattice-pearl.png' });
  await remote.getByRole('tab', { name: /^Advanced/ }).click();
  await remote.locator('#controls .cv-group > summary').filter({ hasText: 'Crystal & light' }).evaluate(s => { s.parentElement.open = true; });
  await remote.getByRole('combobox', { name: 'Reveal the lattice', exact: true }).selectOption('2');
  await page.waitForFunction(() => document.querySelector('#viz').contentDocument.querySelector('canvas').dataset.pointCount === '289');
  await remote.getByRole('tab', { name: 'Playlist' }).click();
  await remote.getByRole('textbox', { name: 'Current visualization JSON payload', exact: true }).fill('{"#nSlider":12,"#volume":"0","#aSlider":0.8,"#rSlider":0.14}');
  await remote.getByRole('button', { name: 'Apply payload', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('#viz').contentDocument.querySelector('canvas').dataset.pointCount === '15625');
  await page.waitForTimeout(1000);
  assert(Number(await canvas.getAttribute('data-draw-calls')) < 12, 'GPU draw count stays small at maximum density');
  await remote.getByRole('tab', { name: 'Simple' }).click();
  await remote.getByRole('combobox', { name: 'Scene', exact: true }).selectOption('architect');
  await page.waitForFunction(() => document.querySelector('#viz').contentDocument.querySelector('#palette').value === 'blueprint');
  await page.waitForTimeout(350);
  await page.screenshot({ path: '/tmp/z3lattice-blueprint.png' });
  const mobileContext = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, reducedMotion: 'reduce' });
  const mobile = await mobileContext.newPage();
  mobile.on('pageerror', e => errors.push(e.message));
  await mobile.goto(`${base}stage.html?viz=z3lattice`);
  await mobile.frameLocator('#viz').locator('canvas[data-draw-calls]').waitFor();
  assert.equal(await mobile.frameLocator('#viz').locator('#playToggle').isChecked(), false);
  assert.equal(await mobile.frameLocator('#viz').locator('#orbitToggle').isChecked(), false);
  const frameBounds = await mobile.locator('#viz').boundingBox();
  assert.equal(frameBounds.width, 390);
  assert(Math.abs(frameBounds.height - 844 * 0.44) < 1, 'phone display keeps the visualization above the control sheet');
  await mobile.screenshot({ path: '/tmp/z3lattice-mobile.png' });
  await mobileContext.close();
  assert.deepEqual(errors, []);
  console.log('PASS: Z³ shader rendering, grouped accessible controls, remote scene presets, cutaways, legacy payload IDs, 15,625-point GPU rendering.');
} finally { await browser.close(); }
