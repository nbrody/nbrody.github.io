/**
 * elementary.js — presentations of the groups Γ = ⟨g₁, …, g_k⟩ ⊂ PGL₂(F) that are not Zariski dense,
 * on "nice" generators, each written as a word in the gᵢ, and the gᵢ written in them. Everything is
 * exact (numfield.js), and every relation is checked on the matrices before it is returned.
 *
 * The Zariski closure (the Zariski Closure engine's kind) says which case:
 *
 *   finite      cyclic, dihedral, A₄, S₄ or A₅: enumerated, with the classical presentation on
 *               generators found in the group (von Dyck: a quotient of the triangle group of the
 *               same order is the whole group).
 *   torus       Γ is abelian and lies in the torus K[g₀]^× / F^× of a regular element g₀; the
 *               eigenvalue ratio λ embeds it in a field (F, or the quadratic field ℚ(√disc) over ℚ),
 *               so Γ ≅ ℤ^k / L with L the multiplicative relations among the λᵢ: ℤ^r × ℤ/m.
 *   normalizer  Γ = A ⋊ ⟨s⟩ with A = Γ ∩ T as above and s an involution inverting A.
 *   unipotent, unipotent-ext, borel
 *               Γ fixes a point c ∈ P¹(F) (of a nontrivial commutator, or of a parabolic). Moving c
 *               to ∞, Γ acts by z ↦ λz + b. The multipliers λ form D ≅ ℤ^r × ℤ/m (as above), with
 *               lifts X₁ … X_r, Z; the translations form M = Γ ∩ U, the ℤ[D]-module generated by the
 *               translations of gᵢ·(lift of its multiplier)⁻¹ and of the commutators of the lifts
 *               (Γ/⟨⟨those⟩⟩ is a quotient of ℤ^r × ℤ/m mapping onto D). Over ℚ, ℤ[D] = ℤ[1/N] with N
 *               the primes in the multipliers, and M = ℤ[1/N]·u. Then
 *                   Γ = ⟨u, X, Z | X u X⁻¹ = u^λ, Z u Z⁻¹ = u^ζ, Z^m, [X_a, X_b] = u^c, …⟩
 *               as a ℤ[1/N]-group: u^c, c ∈ ℤ[1/N], is the c-th power in ⟨⟨u⟩⟩ ≅ ℤ[1/N]. With
 *               r = 0 this is a finite presentation of the virtually abelian M ⋊ ℤ/m. With r = 1 it
 *               is BS(1, n) (and a P. Hall extension by Z) when λ^{±1} = n is an integer, and
 *               otherwise the infinite presentation ⟨u, t | t u^b t⁻¹ = u^a, [u, t^k u t^{−k}]⟩.
 *               Bieri–Strebel: M ⋊ D is finitely presented iff no two primes of N restrict to
 *               opposite characters v_p: D → ℤ.
 */
import { numberField, multRelations, rootOrder, factorInt, ratTex, cabs } from './numfield.js';
import { babs, bgcd, blcm, egcd, hnf, quotient, unimodularInverse } from './intlin.js';

// ───────────────────────── words ─────────────────────────

/** An expression: a product of powers of words in the given generators, [{ w: [±(i+1)], e: BigInt }]. */
const E = {
    word: (w) => (w.length ? [{ w: w.slice(), e: 1n }] : []),
    gen: (i, e = 1n) => (BigInt(e) ? [{ w: [i + 1], e: BigInt(e) }] : []),
    mul: (...xs) => xs.flat(),
    inv: (x) => x.slice().reverse().map((f) => ({ ...f, e: -f.e })),
    pow: (x, e) => {
        e = BigInt(e);
        if (!e || !x.length) return [];
        const w = flatten(x, 2000);
        if (w) return [{ w, e }];
        return e === 1n ? x : [{ w: null, sub: x, e }];
    },
    conj: (y, x) => E.mul(y, x, E.inv(y)),          // y x y⁻¹
};
const freeReduce = (w) => { const o = []; for (const x of w) { if (o.length && o[o.length - 1] === -x) o.pop(); else o.push(x); } return o; };
const invWord = (w) => w.slice().reverse().map((x) => -x);
/** The expression as one freely reduced word, or null when longer than cap. */
function flatten(x, cap = 20000) {
    const out = [];
    for (const f of x) {
        const base = f.w ? f.w : flatten(f.sub, cap);
        if (!base) return null;
        const b = f.e < 0n ? invWord(base) : base;
        const n = babs(f.e);
        if (BigInt(b.length) * n + BigInt(out.length) > BigInt(cap)) return null;
        for (let k = 0n; k < n; k++) out.push(...b);
    }
    return freeReduce(out);
}
/** simplify: flatten when short, merge adjacent powers of the same word */
function tidy(x) {
    const w = flatten(x, 4000);
    if (w) return E.word(w);
    const out = [];
    for (const f of x) {
        if (!f.e) continue;
        const last = out[out.length - 1];
        if (last && last.w && f.w && last.w.join() === f.w.join()) { last.e += f.e; if (!last.e) out.pop(); }
        else out.push({ ...f });
    }
    return out;
}

/** TeX of a word in named letters, with powers collected. */
export function wordTex(w, names) {
    if (!w.length) return '1';
    const out = [];
    for (let i = 0; i < w.length;) {
        let j = i;
        while (j < w.length && w[j] === w[i]) j++;
        const e = (j - i) * Math.sign(w[i]), nm = names[Math.abs(w[i]) - 1];
        out.push(e === 1 ? nm : `${nm}^{${e}}`);
        i = j;
    }
    return out.join(' ');
}
function exprTex(x, names) {
    if (!x.length) return '1';
    const w = flatten(x, 4000);
    if (w) return wordTex(w, names);
    return x.map((f) => {
        const inner = f.w ? wordTex(f.w, names) : exprTex(f.sub, names);
        if (f.e === 1n) return inner;
        if (f.w && f.w.length === 1) return `${names[Math.abs(f.w[0]) - 1]}^{${f.w[0] < 0 ? -f.e : f.e}}`;
        return `\\left(${inner}\\right)^{${f.e}}`;
    }).join(' ');
}
function exprLength(x) {
    let n = 0n;
    for (const f of x) n += babs(f.e) * BigInt(f.w ? f.w.length : exprLength(f.sub));
    return n;
}

// ───────────────────────── matrices over F ─────────────────────────

function mats(F) {
    const { add, sub, mul, neg, isZero, eq, div } = F;
    const mm = (A, B) => [add(mul(A[0], B[0]), mul(A[1], B[2])), add(mul(A[0], B[1]), mul(A[1], B[3])), add(mul(A[2], B[0]), mul(A[3], B[2])), add(mul(A[2], B[1]), mul(A[3], B[3]))];
    const adj = (A) => [A[3], neg(A[1]), neg(A[2]), A[0]];
    const det = (A) => sub(mul(A[0], A[3]), mul(A[1], A[2]));
    const tr = (A) => add(A[0], A[3]);
    const isScalar = (A) => isZero(A[1]) && isZero(A[2]) && eq(A[0], A[3]);
    const projEq = (A, B) => { for (let i = 0; i < 4; i++) for (let j = i + 1; j < 4; j++) if (!eq(mul(A[i], B[j]), mul(A[j], B[i]))) return false; return true; };
    const pnorm = (A) => { const f = A.find((x) => !isZero(x)); return A.map((x) => div(x, f)); };
    const key = (A) => pnorm(A).map(F.key).join(';');
    const I = [F.one, F.zero, F.zero, F.one];
    const pow = (A, e) => {
        e = BigInt(e);
        if (e < 0n) { A = adj(A); e = -e; }
        let r = I, b = A;
        while (e > 0n) { if (e & 1n) r = pnorm(mm(r, b)); e >>= 1n; if (e) b = pnorm(mm(b, b)); }
        return r;
    };
    const comm = (a, b) => isScalar(pnorm(mm(mm(a, b), adj(mm(b, a)))));
    return { mm, adj, det, tr, isScalar, projEq, pnorm, key, I, pow, comm };
}

// ───────────────────────── the affine group z ↦ λz + b ─────────────────────────

function affine(F) {
    const comp = (x, y) => ({ l: F.mul(x.l, y.l), b: F.add(F.mul(x.l, y.b), x.b) });
    const inv = (x) => { const li = F.inv(x.l); return { l: li, b: F.neg(F.mul(li, x.b)) }; };
    const id = { l: F.one, b: F.zero };
    const pow = (x, e) => {
        e = BigInt(e);
        if (e < 0n) { x = inv(x); e = -e; }
        let r = id, s = x;
        while (e > 0n) { if (e & 1n) r = comp(r, s); e >>= 1n; if (e) s = comp(s, s); }
        return r;
    };
    return { comp, inv, id, pow };
}

// ───────────────────────── TeX ─────────────────────────

const ZZ = '\\mathbb{Z}';
const zPow = (r) => (r === 1 ? ZZ : `${ZZ}^{${r}}`);
const ringTex = (N) => (N.length ? `${ZZ}[\\tfrac{1}{${N.reduce((a, b) => a * b, 1n)}}]` : ZZ);
/** ℤ^r × ℤ/m₁ × … as TeX */
function abelianTex(orders) {
    const free = orders.filter((d) => d === 0n).length, tors = orders.filter((d) => d > 1n);
    const parts = [];
    if (free) parts.push(zPow(free));
    for (const d of tors) parts.push(`${ZZ}/${d}`);
    return parts.join(' \\times ') || '1';
}
const matTex = (F, A) => `\\left(\\begin{smallmatrix}${F.tex(A[0])}&${F.tex(A[1])}\\\\${F.tex(A[2])}&${F.tex(A[3])}\\end{smallmatrix}\\right)`;
const gNames = (k) => Array.from({ length: k }, (_, i) => `g_{${i + 1}}`);
const sym = (name, i, n) => (n === 1 ? name : `${name}_{${i + 1}}`);
/** an R-power u^c of a module generator, c rational */
function powTex(name, c) {
    if (c.n === 0n) return '1';
    if (c.q === 1n && c.n === 1n) return name;
    return `${name}^{${c.q === 1n ? c.n : `${c.n < 0n ? '-' : ''}${babs(c.n)}/${c.q}`}}`;
}
/** ∏ u_l^{c_l} with field-element exponents (rationals) */
function modTex(names, cs, F) {
    const parts = cs.map((c, l) => (F.isZero(c) ? null : F.isRat(c) ? powTex(names[l], { n: c.n[0], q: c.q }) : `${names[l]}^{${F.tex(c)}}`)).filter(Boolean);
    return parts.join(' ') || '1';
}

// ───────────────────────── nice bases of ℤ^r × ℤ/m ─────────────────────────

/**
 * Γ ≅ ℤ^k / L (k user generators). Returns { orders, basis (exponent vectors), coordsOf (user
 * generator i in the basis) }, preferring user generators as basis elements where possible.
 */
function niceQuotient(L, k) {
    const Q = quotient(L, k);
    const free = Q.orders.map((d, j) => (d === 0n ? j : -1)).filter((j) => j >= 0);
    const tors = Q.orders.map((d, j) => (d > 1n ? j : -1)).filter((j) => j >= 0);
    const r = free.length;
    const unit = (i) => Array.from({ length: k }, (_, t) => (t === i ? 1n : 0n));
    // the free part: r user generators whose free coordinates form a unimodular matrix
    if (r && r <= k) {
        const subsets = (n, s, start = 0) => (s === 0 ? [[]] : Array.from({ length: n - start }, (_, i) => start + i).flatMap((i) => subsets(n, s - 1, i + 1).map((rest) => [i, ...rest])));
        for (const S of subsets(k, r)) {
            const Cm = S.map((i) => free.map((j) => Q.coordsOf[i][j]));
            let Ci;
            try { Ci = unimodularInverse(Cm); } catch (e) { continue; }
            // new free basis: g_{S[a]}; a user generator with free coords c is ∏ g_{S}^{c·C⁻¹} · torsion
            const newCoords = Q.coordsOf.map((co) => {
                const c = free.map((j) => co[j]);
                const y = free.map((_, a) => c.reduce((s, x, b) => s + x * Ci[b][a], 0n));
                const t = tors.map((j, ti) => {
                    const m = Q.orders[j];
                    const v = co[j] - S.reduce((s, i, a) => s + y[a] * Q.coordsOf[i][j], 0n);
                    return ((v % m) + m) % m;
                });
                return { y, t };
            });
            const basisFree = S.map(unit);
            return finishTorsion(Q, tors, basisFree, newCoords, k);
        }
    }
    return { orders: Q.orders, basis: Q.basis, coordsOf: Q.coordsOf };
}
function finishTorsion(Q, tors, basisFree, newCoords, k) {
    // a torsion generator: a user generator with no free part whose torsion coordinate is a unit
    let torBasis = tors.map((j) => Q.basis[j]);
    let tcoords = newCoords.map((c) => c.t);
    if (tors.length === 1) {
        const m = Q.orders[tors[0]];
        const i = newCoords.findIndex((c) => c.y.every((x) => !x) && bgcd(c.t[0], m) === 1n);
        if (i >= 0) {
            const u = newCoords[i].t[0];
            const [, ui] = egcd(u, m);
            torBasis = [Array.from({ length: k }, (_, t) => (t === i ? 1n : 0n))];
            tcoords = newCoords.map((c) => [(((c.t[0] * ui) % m) + m) % m]);
        }
    }
    return {
        orders: basisFree.map(() => 0n).concat(tors.map((j) => Q.orders[j])),
        basis: basisFree.concat(torBasis),
        coordsOf: newCoords.map((c, i) => c.y.concat(tcoords[i])),
    };
}
const exprOfExponents = (e) => e.flatMap((c, i) => E.gen(i, c));

// ───────────────────────── the entry point ─────────────────────────

/**
 * rows: the generators as rows of entry strings (ringEngine text in w); poly: the field polynomial
 * (BigInt or strings, low → high, monic; [0, 1] for ℚ); root: the embedding to prefer (display);
 * kind: the Zariski closure (trivial, finite, unipotent, torus, normalizer, unipotent-ext, borel).
 */
export function elementaryPresentation({ rows, poly = [0n, 1n], root = null, kind }) {
    const t0 = Date.now();
    const F = numberField(poly.map(BigInt), root);
    const X = mats(F);
    const G0 = rows.map((row) => row.map((s) => F.fromSrc(String(s))));
    G0.forEach((A, i) => { if (F.isZero(X.det(A))) throw new Error(`g${i + 1} is singular`); });
    const G = G0.map(X.pnorm);
    const k = G.length;
    const ctx = { F, X, G, G0: G0.map((A) => contentReduce(F, A)), k, names: gNames(k) };
    let out;
    if (kind === 'trivial' || G.every(X.isScalar)) out = trivialCase(ctx);
    else if (kind === 'finite') out = finiteCase(ctx);
    else if (kind === 'torus') out = torusCase(ctx);
    else if (kind === 'normalizer') out = normalizerCase(ctx);
    else if (kind === 'unipotent' || kind === 'unipotent-ext' || kind === 'borel') out = reducibleCase(ctx, kind);
    else throw new Error(`no presentation for closure ${kind}`);
    out.kind = kind;
    out.ms = Date.now() - t0;
    out.degree = F.d;
    return out;
}

/** evaluate an expression in the user generators */
function evalExpr(ctx, x) {
    const { X, G } = ctx;
    let A = X.I;
    for (const f of x) {
        const B = f.w ? f.w.reduce((M, l) => X.pnorm(X.mm(M, l > 0 ? G[l - 1] : X.adj(G[-l - 1]))), X.I) : evalExpr(ctx, f.sub);
        A = X.pnorm(X.mm(A, X.pow(B, f.e)));
    }
    return A;
}
/**
 * A matrix up to scalars, scaled to have entries in ℤ[w] with no common rational integer factor
 * (for display: products of the given matrices look like products).
 */
function contentReduce(F, A) {
    const L = A.reduce((l, x) => blcm(l, x.q), 1n);
    const ints = A.map((x) => x.n.map((c) => c * (L / x.q)));
    const g = ints.flat().reduce((t, c) => bgcd(t, c), 0n) || 1n;
    let B = ints.map((v) => F.el(v.map((c) => c / g), 1n));
    // the first nonzero coefficient positive
    const first = B.flatMap((x) => x.n).find((c) => c !== 0n);
    if (first < 0n) B = B.map(F.neg);
    return B;
}
/** the expression multiplied out on the given matrices, content removed at every step (display) */
function displayMatrix(ctx, x) {
    const { X, G0, F } = ctx;
    const red = (A) => contentReduce(F, A);
    const pw = (A, e) => { e = BigInt(e); if (e < 0n) { A = X.adj(A); e = -e; } let r = X.I, b = A; while (e > 0n) { if (e & 1n) r = red(X.mm(r, b)); e >>= 1n; if (e) b = red(X.mm(b, b)); } return r; };
    let A = X.I;
    for (const f of x) {
        const B = f.w ? f.w.reduce((M, l) => red(X.mm(M, l > 0 ? G0[l - 1] : X.adj(G0[-l - 1]))), X.I) : displayMatrix(ctx, f.sub);
        A = red(X.mm(A, pw(B, f.e)));
    }
    return red(A);
}
/** a nice generator: name, its expression in the gᵢ, its matrix */
function niceGen(ctx, name, expr) {
    const x = tidy(expr);
    const M = evalExpr(ctx, x);
    // the product as it comes, or scaled to a 1 in the first nonzero entry: whichever is smaller
    const size = (A) => A.reduce((t, e) => t + e.n.reduce((u, c) => u + babs(c).toString(2).length, 0) + e.q.toString(2).length, 0);
    const P = contentReduce(ctx.F, M);
    const D0 = exprLength(x) <= 4000n ? displayMatrix(ctx, x) : P;
    const single = x.length === 1 && x[0].w && x[0].w.length === 1 && x[0].e === 1n && x[0].w[0] > 0;
    const D = single ? ctx.G0[x[0].w[0] - 1] : size(P) <= size(D0) ? P : D0;
    return { name, expr: x, M, matTex: matTex(ctx.F, D), wordTex: exprTex(x, ctx.names), length: Number(exprLength(x)) };
}
function serialGens(gens) {
    return gens.map(({ name, matTex: m, wordTex: w, length }) => ({ name, matTex: m, wordTex: w, length }));
}

// ───────────────────────── trivial and finite ─────────────────────────

function trivialCase(ctx) {
    return {
        structure: '1', gens: [], relations: [], complete: true, finite: true,
        given: ctx.names.map((n) => `${n} = 1`),
        summary: 'Every generator is scalar, so Γ is trivial in PGL₂.',
    };
}

function finiteCase(ctx) {
    const { X, G, k, F } = ctx;
    // the group, with a shortest word for each element
    const elems = new Map();
    const idKey = X.key(X.I);
    elems.set(idKey, { M: X.I, w: [] });
    let frontier = [idKey];
    while (frontier.length) {
        const next = [];
        for (const key of frontier) {
            const { M, w } = elems.get(key);
            for (let i = 0; i < k; i++) for (const s of [1, -1]) {
                const N = X.pnorm(X.mm(M, s > 0 ? G[i] : X.adj(G[i])));
                const nk = X.key(N);
                if (elems.has(nk)) continue;
                elems.set(nk, { M: N, w: w.concat([s * (i + 1)]) });
                next.push(nk);
                if (elems.size > 20000) throw new Error('the group has more than 20000 elements');
            }
        }
        frontier = next;
    }
    const n = elems.size;
    const list = [...elems.values()];
    const orderOf = (M) => { let A = M, o = 1; while (!X.isScalar(A)) { A = X.pnorm(X.mm(A, M)); o++; if (o > n) return Infinity; } return o; };
    list.forEach((e) => { e.order = orderOf(e.M); });
    list.sort((a, b) => a.w.length - b.w.length);
    const genBy = (ms) => {
        const seen = new Set([idKey]), q = [X.I];
        while (q.length) { const A = q.pop(); for (const g of ms) { const B = X.pnorm(X.mm(A, g)); const kk = X.key(B); if (!seen.has(kk)) { seen.add(kk); q.push(B); } } }
        return seen.size;
    };
    let gens, rels, structure, names;
    const cyc = list.find((e) => e.order === n);
    if (cyc) {
        names = ['a'];
        gens = [cyc];
        rels = [{ tex: `a^{${n}}`, check: (A) => [X.pow(A[0], n)] }];
        structure = n === 1 ? '1' : `${ZZ}/${n}`;
    } else if (n % 2 === 0 && list.some((e) => e.order === n / 2)) {
        const m = n / 2;
        const r = n === 4 ? list.find((e) => e.order === 2) : list.find((e) => e.order === m);
        const inR = new Set([idKey]);
        for (let A = r.M; !X.isScalar(A); A = X.pnorm(X.mm(A, r.M))) inR.add(X.key(A));
        const s = list.find((e) => e.order === 2 && !inR.has(X.key(e.M)));
        if (!s) throw new Error('internal: a dihedral group without a reflection');
        names = ['r', 's'];
        gens = [r, s];
        rels = [
            { tex: `r^{${m}}`, check: (A) => [X.pow(A[0], m)] },
            { tex: 's^{2}', check: (A) => [X.pow(A[1], 2)] },
            { tex: '(rs)^{2}', check: (A) => [X.pow(X.mm(A[0], A[1]), 2)] },
        ];
        structure = n === 4 ? `(${ZZ}/2)^{2}` : `D_{${m}}`;
    } else if (n === 12 || n === 24 || n === 60) {
        const c = { 12: 3, 24: 4, 60: 5 }[n];
        let pair = null;
        outer: for (const a of list.filter((e) => e.order === 2)) for (const b of list.filter((e) => e.order === 3)) {
            if (orderOf(X.pnorm(X.mm(a.M, b.M))) !== c) continue;
            if (genBy([a.M, b.M]) === n) { pair = [a, b]; break outer; }
        }
        if (!pair) throw new Error('internal: no (2, 3, c) generators');
        names = ['a', 'b'];
        gens = pair;
        rels = [
            { tex: 'a^{2}', check: (A) => [X.pow(A[0], 2)] },
            { tex: 'b^{3}', check: (A) => [X.pow(A[1], 3)] },
            { tex: `(ab)^{${c}}`, check: (A) => [X.pow(X.mm(A[0], A[1]), c)] },
        ];
        structure = { 12: 'A_{4}', 24: 'S_{4}', 60: 'A_{5}' }[n];
    } else throw new Error(`a finite group of order ${n} that is not cyclic, dihedral, A₄, S₄ or A₅`);
    const mats = gens.map((g) => g.M);
    for (const r of rels) for (const A of r.check(mats)) if (!X.isScalar(A)) throw new Error('internal: a relation fails');
    if (genBy(mats) !== n) throw new Error('internal: the generators found do not generate');
    const nice = gens.map((g, j) => niceGen(ctx, names[j], E.word(g.w)));
    // the given generators in the nice ones: a breadth-first search over the group from them
    const back = new Map([[idKey, []]]);
    let fr = [X.I];
    while (fr.length) {
        const next = [];
        for (const A of fr) {
            const wA = back.get(X.key(A));
            mats.forEach((g, j) => {
                for (const s of [1, -1]) {
                    const B = X.pnorm(X.mm(A, s > 0 ? g : X.adj(g)));
                    const kk = X.key(B);
                    if (back.has(kk)) continue;
                    back.set(kk, wA.concat([s * (j + 1)]));
                    next.push(B);
                }
            });
        }
        fr = next;
    }
    const given = G.map((A, i) => `${ctx.names[i]} = ${wordTex(back.get(X.key(A)), names)}`);
    return {
        structure, order: n, gens: serialGens(nice), relations: rels.map((r) => r.tex), relationsAreRelators: true,
        complete: true, finite: true, finitelyPresented: true, given,
        summary: `Γ is finite of order ${n}.`,
    };
}

// ───────────────────────── tori ─────────────────────────

/**
 * Elements commuting with a regular g₀ are α + β·g₀; their eigenvalue ratios λ = x/x̄ (x = α + βX in
 * F[X]/(X² − tX + n)) lie in F when the discriminant is a square in F, and in a quadratic field
 * over ℚ otherwise (F = ℚ). Returns { L: the field, lam(A) → λ }.
 */
function torusField(ctx, g0) {
    const { F, X } = ctx;
    const t = X.tr(g0), n = X.det(g0);
    const disc = F.sub(F.mul(t, t), F.mul(F.rat(4n), n));
    const coeffs = (A) => {
        // A = α + β g₀
        let beta;
        if (!F.isZero(g0[1])) beta = F.div(A[1], g0[1]);
        else if (!F.isZero(g0[2])) beta = F.div(A[2], g0[2]);
        else beta = F.div(F.sub(A[0], A[3]), F.sub(g0[0], g0[3]));
        const alpha = F.sub(A[0], F.mul(beta, g0[0]));
        const back = [F.add(alpha, F.mul(beta, g0[0])), F.mul(beta, g0[1]), F.mul(beta, g0[2]), F.add(alpha, F.mul(beta, g0[3]))];
        if (!X.projEq(back, A)) throw new Error('internal: an element does not commute with the torus');
        return { alpha, beta };
    };
    const sq = sqrtIn(F, disc);
    if (sq) {
        const ep = F.div(F.add(t, sq), F.rat(2n)), em = F.div(F.sub(t, sq), F.rat(2n));
        return {
            L: F, split: true,
            lam: (A) => { const { alpha, beta } = coeffs(A); return F.div(F.add(alpha, F.mul(beta, ep)), F.add(alpha, F.mul(beta, em))); },
        };
    }
    if (F.d > 1) throw new Error('Γ lies in a torus that splits only over a quadratic extension of the field; its relations are not computed there');
    // disc = p/q ∉ ℚ²: √disc = c·√D₀ / q with p·q = c²·D₀, D₀ squarefree
    const p = disc.n[0], q = disc.q;
    let D0 = p * q, c = 1n;
    for (const [pr, e] of factorInt(D0)) { const h = BigInt(Math.floor(e / 2)); if (h) { c *= pr ** h; D0 /= (pr * pr) ** h; } }
    const Lf = numberField([-D0, 0n, 1n], D0 > 0n ? { re: Math.sqrt(Number(D0)), im: 0 } : { re: 0, im: Math.sqrt(-Number(D0)) });
    // X = (t ± c√D₀/q)/2: x = α + β t/2 ± β c/(2q)·y
    const tq = t.n[0], tqq = t.q;
    const lam = (A) => {
        const { alpha, beta } = coeffs(A);
        const a = { n: alpha.n[0], q: alpha.q }, b = { n: beta.n[0], q: beta.q };
        const re = F.add(alpha, F.mul(beta, F.rat(tq, 2n * tqq)));
        const im = F.mul(beta, F.rat(c, 2n * q));
        void a; void b;
        const x = Lf.el([re.n[0] * im.q, im.n[0] * re.q], re.q * im.q);
        const xb = Lf.el([re.n[0] * im.q, -im.n[0] * re.q], re.q * im.q);
        return Lf.div(x, xb);
    };
    return { L: Lf, split: false, D0, lam };
}
/** √x in F, or null (exact over ℚ; over a number field by recognizing a numerical root). */
function sqrtIn(F, x) {
    if (F.isZero(x)) return F.zero;
    if (F.d === 1 || F.isRat(x)) {
        const n = x.n[0], q = x.q;
        if (n < 0n && F.d === 1) return null;
        const isq = (m) => { if (m < 0n) return null; let r = BigInt(Math.floor(Math.sqrt(Number(m)))); while (r * r > m) r--; while ((r + 1n) * (r + 1n) <= m) r++; return r * r === m ? r : null; };
        const a = isq(babs(n)), b = isq(q);
        if (a !== null && b !== null && n > 0n) return F.rat(a, b);
        if (F.d === 1) return null;
    }
    // over a number field: try y = Σ cⱼ wʲ with σ(y) = ±√σ(x) at every embedding
    if (F.d > 8) return null;
    const vals = F.roots.map((_, j) => F.emb(x, j));
    const sqrtC = (z) => { const r = Math.sqrt(cabs(z)), th = Math.atan2(z.im, z.re) / 2; return { re: r * Math.cos(th), im: r * Math.sin(th) }; };
    const base = vals.map(sqrtC);
    for (let mask = 0; mask < 1 << F.d; mask++) {
        const target = base.map((z, j) => ((mask >> j) & 1 ? { re: -z.re, im: -z.im } : z));
        const c = solveVandermonde(F.roots, target);
        if (!c) continue;
        const y = recognize(F, c);
        if (y && F.eq(F.mul(y, y), x)) return y;
    }
    return null;
}
function solveVandermonde(roots, target) {
    const n = roots.length;
    // complex Gaussian elimination on V c = target
    const A = roots.map((z, i) => { const row = []; let p = { re: 1, im: 0 }; for (let j = 0; j < n; j++) { row.push(p); p = { re: p.re * z.re - p.im * z.im, im: p.re * z.im + p.im * z.re }; } return row.concat([target[i]]); });
    for (let col = 0; col < n; col++) {
        let piv = col; for (let r = col + 1; r < n; r++) if (cabs(A[r][col]) > cabs(A[piv][col])) piv = r;
        [A[col], A[piv]] = [A[piv], A[col]];
        const pv = A[col][col]; if (cabs(pv) < 1e-14) return null;
        for (let r = 0; r < n; r++) {
            if (r === col) continue;
            const f = cdivN(A[r][col], pv);
            for (let c = col; c <= n; c++) A[r][c] = { re: A[r][c].re - (f.re * A[col][c].re - f.im * A[col][c].im), im: A[r][c].im - (f.re * A[col][c].im + f.im * A[col][c].re) };
        }
    }
    return A.map((row, i) => cdivN(row[n], row[i]));
}
const cdivN = (a, b) => { const d = b.re * b.re + b.im * b.im; return { re: (a.re * b.re + a.im * b.im) / d, im: (a.im * b.re - a.re * b.im) / d }; };
function recognize(F, c) {
    if (c.some((z) => Math.abs(z.im) > 1e-6)) return null;
    const rats = c.map((z) => ratApprox(z.re));
    if (rats.some((r) => !r)) return null;
    const q = rats.reduce((l, r) => blcm(l, r.q), 1n);
    return F.el(rats.map((r) => r.n * (q / r.q)), q);
}
function ratApprox(x, maxQ = 1000000) {
    // continued fractions
    let [h0, h1, k0, k1] = [0n, 1n, 1n, 0n];
    let y = x;
    for (let i = 0; i < 40; i++) {
        const a = Math.floor(y);
        [h0, h1] = [h1, BigInt(a) * h1 + h0];
        [k0, k1] = [k1, BigInt(a) * k1 + k0];
        if (k1 > BigInt(maxQ)) return null;
        if (Math.abs(Number(h1) / Number(k1) - x) < 1e-9 * Math.max(1, Math.abs(x))) return { n: h1, q: k1 };
        const fr = y - a;
        if (fr < 1e-12) break;
        y = 1 / fr;
    }
    return k1 ? { n: h1, q: k1 } : null;
}

/** Γ ≅ ℤ^k/L on the given expressions (one per element xs[i]) with multipliers lams. */
function abelianPart(ctx, Lf, lams, exprs, prefix = ['t', 'z']) {
    const rel = multRelations(Lf, lams);
    const kk = lams.length;
    const Q = niceQuotient(rel.L, kk);
    const free = Q.orders.filter((d) => d === 0n).length;
    const nice = Q.basis.map((e, j) => {
        const nm = Q.orders[j] === 0n ? sym(prefix[0], j, free) : (Q.orders.filter((d) => d > 1n).length === 1 ? prefix[1] : `${prefix[1]}_{${j - free + 1}}`);
        return niceGen(ctx, nm, e.flatMap((c, i) => (c ? E.pow(exprs[i], c) : [])));
    });
    return { rel, Q, nice, free };
}

function torusCase(ctx) {
    const { X, G, k } = ctx;
    const g0 = G.find((A) => !X.isScalar(A));
    const T = torusField(ctx, g0);
    const lams = G.map((A) => (X.isScalar(A) ? T.L.one : T.lam(A)));
    const { Q, nice, rel } = abelianPart(ctx, T.L, lams, G.map((_, i) => E.gen(i)));
    // check: commuting (Γ is abelian), orders
    for (const g of nice) for (const h of nice) if (!X.comm(g.M, h.M)) throw new Error('internal: the torus is not abelian');
    nice.forEach((g, j) => { if (Q.orders[j] > 0n && !X.isScalar(X.pow(g.M, Q.orders[j]))) throw new Error('internal: a torsion generator has the wrong order'); });
    const names = nice.map((g) => g.name);
    const relations = [];
    Q.orders.forEach((d, j) => { if (d > 0n) relations.push(`${names[j]}^{${d}}`); });
    for (let a = 0; a < names.length; a++) for (let b = a + 1; b < names.length; b++) relations.push(`[${names[a]}, ${names[b]}]`);
    const given = G.map((_, i) => `${ctx.names[i]} = ${coordTex(Q.coordsOf[i], names)}`);
    return {
        structure: abelianTex(Q.orders), gens: serialGens(nice), relations, relationsAreRelators: true,
        complete: true, finitelyPresented: true, given, unitGap: rel.unitGap,
        summary: `Γ lies in a ${T.split ? 'split' : 'non-split'} torus${T.split ? '' : ` (it splits over ℚ(√${T.D0}))`}, and the eigenvalue ratios of its generators satisfy ${rel.L.length} independent multiplicative relation${rel.L.length === 1 ? '' : 's'}.`,
    };
}
const coordTex = (c, names) => c.map((x, j) => (x ? (x === 1n ? names[j] : `${names[j]}^{${x}}`) : null)).filter(Boolean).join(' ') || '1';

// ───────────────────────── normalizers of tori ─────────────────────────

function normalizerCase(ctx) {
    const { X, G, k, F } = ctx;
    const live = G.map((A, i) => i).filter((i) => !X.isScalar(G[i]));
    // a regular element of Γ ∩ T: a short word that is not an involution
    const words = [];
    for (const i of live) words.push([i + 1]);
    for (const i of live) for (const j of live) words.push([i + 1, j + 1]);
    for (const i of live) for (const j of live) for (const l of live) words.push([i + 1, j + 1, l + 1]);
    let g0 = null;
    for (const w of words) {
        const A = evalExpr(ctx, E.word(w));
        if (!X.isScalar(A) && !F.isZero(X.tr(A))) { g0 = A; break; }
    }
    if (!g0) throw new Error('internal: no regular element in the torus');
    const isT = (A) => X.comm(A, g0);
    const sIdx = live.filter((i) => !isT(G[i]));
    for (const i of sIdx) {
        if (!F.isZero(X.tr(G[i]))) throw new Error('internal: an element outside the torus is not an involution');
        if (!X.projEq(X.mm(X.mm(G[i], g0), X.adj(G[i])), X.adj(g0))) throw new Error('internal: an element does not normalize the torus');
    }
    if (!sIdx.length) return torusCase(ctx);
    const s = sIdx[0];
    // A = Γ ∩ T: the generators in T and s·gᵢ for the other involutions
    const aExprs = [], aMats = [];
    G.forEach((A, i) => {
        if (i === s) return;
        if (sIdx.includes(i)) { aExprs.push(E.word([s + 1, i + 1])); aMats.push(X.pnorm(X.mm(G[s], A))); }
        else { aExprs.push(E.gen(i)); aMats.push(A); }
    });
    let nice = [], Q = { orders: [], coordsOf: [] }, rel = { L: [], unitGap: null }, Tsplit = true, D0 = null;
    if (aMats.length) {
        const T = torusField(ctx, g0);
        Tsplit = T.split; D0 = T.D0;
        const lams = aMats.map((A) => (X.isScalar(A) ? T.L.one : T.lam(A)));
        ({ Q, nice, rel } = abelianPart(ctx, T.L, lams, aExprs));
    }
    const sg = niceGen(ctx, 's', E.gen(s));
    for (const g of nice) if (!X.isScalar(X.pow(X.mm(sg.M, g.M), 2))) throw new Error('internal: s does not invert A');
    const names = nice.map((g) => g.name);
    const relations = [];
    Q.orders.forEach((d, j) => { if (d > 0n) relations.push(`${names[j]}^{${d}}`); });
    for (let a = 0; a < names.length; a++) for (let b = a + 1; b < names.length; b++) relations.push(`[${names[a]}, ${names[b]}]`);
    relations.push('s^{2}');
    for (const nm of names) relations.push(`(s\\,${nm})^{2}`);
    // the given generators: gᵢ ∈ A, or gᵢ = s·(s gᵢ)
    let a = 0;
    const given = G.map((_, i) => {
        if (i === s) return `${ctx.names[i]} = s`;
        const c = coordTex(Q.coordsOf[a++] || [], names);
        return `${ctx.names[i]} = ${sIdx.includes(i) ? `s${c === '1' ? '' : `\\,${c}`}` : c}`;
    });
    const Atex = abelianTex(Q.orders);
    const structure = Atex === ZZ ? 'D_{\\infty}' : `${Atex} \\rtimes ${ZZ}/2`;
    return {
        structure, gens: serialGens(nice.concat([sg])), relations, relationsAreRelators: true,
        complete: true, finitelyPresented: true, given, unitGap: rel.unitGap,
        summary: `Γ preserves a pair of points${Tsplit ? '' : ` (conjugate over ℚ(√${D0}))`}: its elements fixing both form A ≅ ${texPlain(Atex)}, of index 2, and the involution s swaps them, inverting A.`,
    };
}
const texPlain = (t) => t.replace(/\\tfrac\{(\d+)\}\{(\d+)\}/g, '$1/$2').replace(/\\mathbb\{Z\}/g, 'ℤ').replace(/\\times/g, '×').replace(/\\rtimes/g, '⋊').replace(/\^\{(\d+)\}/g, (_, d) => d.split('').map((c) => '⁰¹²³⁴⁵⁶⁷⁸⁹'[+c]).join('')).replace(/[{}\\]/g, '').replace(/\s+/g, ' ').trim();

// ───────────────────────── groups with a fixed point ─────────────────────────

function reducibleCase(ctx, kind) {
    const { F, X, G, k } = ctx;
    const A = affine(F);
    // the common fixed point: of a nontrivial commutator, else of a parabolic generator
    let P = null;
    outer: for (let i = 0; i < k; i++) for (let j = i + 1; j < k; j++) {
        if (!X.comm(G[i], G[j])) { P = X.pnorm(X.mm(X.mm(G[i], G[j]), X.adj(X.mm(G[j], G[i])))); break outer; }
    }
    if (!P) P = G.find((M) => !X.isScalar(M));
    // fixed point of a parabolic (a b; c d): (a − d)/2c, or ∞
    let h = X.I;
    if (!F.isZero(P[2])) {
        const z = F.div(F.sub(P[0], P[3]), F.mul(F.rat(2n), P[2]));
        h = [z, F.one, F.one, F.zero];
    }
    const hi = X.adj(h);
    const aff = G.map((M) => {
        const N = X.mm(X.mm(hi, M), h);
        if (!F.isZero(N[2])) throw new Error('internal: Γ does not fix the point');
        return { l: F.div(N[0], N[3]), b: F.div(N[1], N[3]) };
    });
    const evalAff = (x) => x.reduce((acc, f) => A.comp(acc, A.pow(f.w ? f.w.reduce((a, l) => A.comp(a, l > 0 ? aff[l - 1] : A.inv(aff[-l - 1])), A.id) : evalAff(f.sub), f.e)), A.id);

    // the multipliers: D ≅ ℤ^r × ℤ/m
    const rel = multRelations(F, aff.map((x) => x.l));
    const Q = niceQuotient(rel.L, k);
    const r = Q.orders.filter((d) => d === 0n).length;
    const tIdx = Q.orders.findIndex((d) => d > 1n);
    const m = tIdx >= 0 ? Number(Q.orders[tIdx]) : 1;
    const liftNames = Q.orders.map((d, j) => (d === 0n ? sym('t', j, r) : 'z'));
    const lifts = Q.basis.map((e, j) => niceGen(ctx, liftNames[j], exprOfExponents(e)));
    const shiftBy = (sh) => (x) => ({ l: x.l, b: F.add(x.b, F.mul(F.sub(x.l, F.one), sh)) });
    const fixedPt = (x) => F.div(x.b, F.sub(F.one, x.l));
    // the base point: fixed by z if there is torsion, else by t₁ (so z or t₁ is linear)
    const fixer = tIdx >= 0 ? tIdx : (r ? 0 : -1);
    let shift = fixer >= 0 ? fixedPt(evalAff(lifts[fixer].expr)) : F.zero;
    let S = shiftBy(shift);
    let evalS = (x) => S(evalAff(x));
    const liftOf = (co) => co.flatMap((c, j) => (c ? E.pow(lifts[j].expr, c) : []));

    // kernel elements: gᵢ·(lift of its multiplier)⁻¹, and the commutators of the lifts; their
    // translations generate M = Γ ∩ U as a ℤ[D]-module (independent of the lifts and base point)
    const kernelOf = () => {
        const ker = G.map((_, i) => {
            const x = E.mul(E.gen(i), E.inv(liftOf(Q.coordsOf[i])));
            return { expr: x, b: checkTranslation(F, evalS(x)) };
        });
        const comms = [];
        for (let a = 0; a < lifts.length; a++) for (let b = a + 1; b < lifts.length; b++) {
            const x = E.mul(lifts[a].expr, lifts[b].expr, E.inv(lifts[a].expr), E.inv(lifts[b].expr));
            comms.push({ a, b, expr: x, c: checkTranslation(F, evalS(x)) });
        }
        return { ker, comms };
    };
    let { ker: kernel, comms: commPairs } = kernelOf();
    const gens = kernel.map((x) => x).concat(commPairs.map((c) => ({ expr: c.expr, b: c.c }))).filter((x) => !F.isZero(x.b));
    if (!gens.length) throw new Error('internal: Γ has no translations, so it is abelian');

    // the module M: over ℚ-rational multipliers, a ℤ[1/N]-lattice with basis that of the ℤ[ζ]-span
    const freeIdx = Q.orders.map((d, j) => (d === 0n ? j : -1)).filter((j) => j >= 0);
    const lamOf = (j) => evalAff(lifts[j].expr).l;
    const freeL = freeIdx.map(lamOf);
    const rational = freeL.every((l) => F.isRat(l));
    const zeta = tIdx >= 0 ? lamOf(tIdx) : F.one;
    const zetaRational = F.isRat(zeta);
    const N = [];
    if (rational) for (const l of freeL) for (const p of [...factorInt(l.n[0]).keys(), ...factorInt(l.q).keys()]) if (!N.includes(p)) N.push(p);
    N.sort((a, b) => (a < b ? -1 : 1));
    if (!rational) return partialBorel(ctx, { kind, Q, lifts, gens, r, m, rel });
    // ℤ-span of ζ^a·b over the generators (a < m when ζ ∉ ℚ)
    const reps = zetaRational ? 1 : m;
    const vecs = [];
    for (const g of gens) for (let a = 0; a < reps; a++) {
        const z = tIdx >= 0 && a ? E.pow(lifts[tIdx].expr, a) : [];
        vecs.push({ v: F.mul(F.pow(zeta, a), g.b), expr: a ? E.conj(z, g.expr) : g.expr });
    }
    const den = vecs.reduce((l, x) => blcm(l, x.v.q), 1n);
    const B = vecs.map((x) => x.v.n.map((c) => c * (den / x.v.q)));
    const H = hnf(B);
    const s = H.rank;
    let basis = H.H.slice(0, s).map((row, l) => ({
        v: F.el(row, den),
        expr: tidy(H.U[l].flatMap((c, t) => (c ? E.pow(vecs[t].expr, c) : []))),
    }));
    // each basis vector: the shortest expression among the generators with that translation (or its negative)
    basis = basis.map((bv) => {
        let best = bv;
        for (const x of vecs) {
            const e = F.eq(x.v, bv.v) ? x.expr : F.eq(x.v, F.neg(bv.v)) ? E.inv(x.expr) : null;
            if (e && exprLength(e) < exprLength(best.expr)) best = { v: bv.v, expr: e };
        }
        return best;
    });
    const isNUnit = (x) => x.n[0] !== 0n && [...factorInt(x.n[0]).keys(), ...factorInt(x.q).keys()].every((p) => N.includes(p));
    // one generator: prefer a kernel element that is a ℤ[1/N]-unit multiple of the basis vector
    if (s === 1 && F.d === 1) {
        const cands = vecs.filter((x) => isNUnit(F.div(x.v, basis[0].v))).sort((a, b) => Number(exprLength(a.expr) - exprLength(b.expr)));
        if (cands.length) basis = [{ v: cands[0].v, expr: cands[0].expr }];
    }
    const uNames = basis.map((_, l) => sym('u', l, s));
    const us = basis.map((x, l) => niceGen(ctx, uNames[l], x.expr));
    us.forEach((u, l) => { if (!F.eq(evalS(u.expr).b, basis[l].v) || !F.eq(evalS(u.expr).l, F.one)) throw new Error('internal: a module generator is not its translation'); });
    // coordinates of a translation in the basis (rational; in ℤ[1/N] for elements of M)
    const coordsIn = (v) => solveRational(F, basis.map((x) => x.v), v);
    const inM = (v) => {
        let co;
        try { co = coordsIn(v); } catch (e) { return false; }
        return co.every((c) => F.isZero(c) || (r ? isNUnit(F.rat(c.q, 1n)) || c.q === 1n : c.q === 1n));
    };
    // an element of M as an expression: c = Σ n_e λ^e is a Laurent polynomial in the multipliers,
    // and conjugating by a lift of λ^e multiplies a translation by λ^e
    const lamAB = freeL.map((l) => ({ a: l.n[0], b: l.q }));
    const mExpr = (v) => coordsIn(v).flatMap((c, l) => {
        if (F.isZero(c)) return [];
        if (!r) return E.pow(us[l].expr, c.n[0]);
        const P = laurentMulti({ n: c.n[0], q: c.q }, lamAB);
        return [...P.entries()].flatMap(([key, n]) => {
            const e = key.split(',').map(BigInt);
            const y = e.flatMap((x, t) => (x ? E.pow(lifts[freeIdx[t]].expr, x) : []));
            return E.pow(E.conj(y, us[l].expr), n);
        });
    });

    // a split extension: a base point s at which every lift's translation lies in M; the lifts moved
    // by those elements of M then fix s, and commute. Such an s lies in s₀ + ℓ⁻¹M (s₀ fixed by the
    // lift f, ℓ = λ_f − 1), and only s mod M matters (b_j(s + m) = b_j(s) + (λ_j − 1)m). For an
    // integer c ∈ ℓ·ℤ[D], ℓ⁻¹M/M is a quotient of ℓ⁻¹(M/cM): the points s₀ + ℓ⁻¹·Σ k_l β_l,
    // 0 ≤ k_l < c, decide it.
    let splitDecided = true;
    if (lifts.length > 1 || tIdx >= 0) {
        const f = fixer, Lf = evalAff(lifts[f].expr), s0 = fixedPt(Lf), ell = F.sub(Lf.l, F.one);
        const nFree = (x) => { x = babs(x); for (const p of N) while (x % p === 0n) x /= p; return x; };
        const c = F.isRat(ell) ? nFree(ell.n[0]) : babs(F.normOf(ell).n);
        const total = c ** BigInt(s);
        const tryPoint = (sh) => {
            const at = lifts.map((L) => shiftBy(sh)(evalAff(L.expr)).b);
            if (!at.every((b) => F.isZero(b) || inM(b))) return false;
            shift = sh; S = shiftBy(shift); evalS = (x) => S(evalAff(x));
            lifts.forEach((L, i) => {
                if (F.isZero(at[i])) return;
                const moved = niceGen(ctx, L.name, E.mul(mExpr(F.neg(at[i])), L.expr));
                if (!F.isZero(evalS(moved.expr).b)) throw new Error('internal: a moved lift does not fix the base point');
                lifts[i] = moved;
            });
            ({ ker: kernel, comms: commPairs } = kernelOf());
            return true;
        };
        let found = false;
        if (total <= 4096n) {
            const ellInv = F.inv(ell);
            const ks = new Array(s).fill(0n);
            for (let t = 0n; t < total && !found; t++) {
                let rest = t;
                for (let l = 0; l < s; l++) { ks[l] = rest % c; rest /= c; }
                const y = ks.reduce((acc, kk, l) => F.add(acc, F.mul(F.rat(kk), basis[l].v)), F.zero);
                found = tryPoint(F.add(s0, F.mul(ellInv, y)));
            }
        } else {
            splitDecided = false;
            for (const j of [fixer, ...lifts.map((_, jj) => jj).filter((jj) => jj !== fixer)]) if (!found) found = tryPoint(fixedPt(evalAff(lifts[j].expr)));
            if (found) splitDecided = true;
        }
    }
    const liftS = lifts.map((L) => evalS(L.expr));

    // relations, each checked on the affine maps
    const relations = [];
    for (const j of freeIdx) {
        const lam = liftS[j].l;
        for (let l = 0; l < s; l++) relations.push(`${liftNames[j]}\\, ${uNames[l]}\\, ${liftNames[j]}^{-1} = ${powTex(uNames[l], { n: lam.n[0], q: lam.q })}`);
    }
    let zetaMatrix = null;
    if (tIdx >= 0) {
        zetaMatrix = basis.map((x) => coordsIn(F.mul(zeta, x.v)));
        for (let l = 0; l < s; l++) relations.push(`z\\, ${uNames[l]}\\, z^{-1} = ${modTex(uNames, zetaMatrix[l], F)}`);
        relations.push(`z^{${m}} = 1`);
    }
    const commRels = [];
    for (const c of commPairs) {
        const co = coordsIn(c.c);
        const lhs = `[${liftNames[c.a]}, ${liftNames[c.b]}]`;
        commRels.push({ ...c, co });
        relations.push(`${lhs} = ${modTex(uNames, co, F)}`);
    }
    for (let a = 0; a < s; a++) for (let b = a + 1; b < s; b++) relations.push(`[${uNames[a]}, ${uNames[b]}] = 1`);
    // the given generators in the nice ones: gᵢ = (translation)·(lift)
    const given = G.map((_, i) => {
        const kb = kernel[i].b;
        const tr = F.isZero(kb) ? '' : modTex(uNames, coordsIn(kb), F);
        const lift = coordTex(Q.coordsOf[i], liftNames);
        const parts = [tr, lift === '1' ? '' : lift].filter(Boolean);
        return `${ctx.names[i]} = ${parts.join('\\, ') || '1'}`;
    });
    // checks: the relations hold on the affine maps
    for (const j of freeIdx) for (const u of us) {
        const lhs = A.comp(A.comp(liftS[j], evalS(u.expr)), A.inv(liftS[j]));
        if (!F.eq(lhs.b, F.mul(liftS[j].l, evalS(u.expr).b))) throw new Error('internal: a lift does not act by its multiplier');
    }
    if (tIdx >= 0 && !F.eq(A.pow(liftS[tIdx], m).l, F.one)) throw new Error('internal: z has the wrong order');
    if (tIdx >= 0 && !F.isZero(A.pow(liftS[tIdx], m).b)) throw new Error('internal: z^m is not 1');

    // the structure, finite presentability, ordinary presentations
    const Rtex = ringTex(N);
    const Mtex = r ? (s === 1 ? Rtex : `${Rtex}^{${s}}`) : zPow(s);
    const Dtex = abelianTex(Q.orders);
    const split = commRels.every((c) => c.co.every((x) => F.isZero(x)));
    const Dp = Dtex.includes('\\times') ? `(${Dtex})` : Dtex;
    const structure = Dtex === '1' ? Mtex : split ? `${Mtex} \\rtimes ${Dp}` : `${Mtex} \\,.\\, ${Dp}`;
    const splitNote = Dtex === '1' || split ? null : splitDecided
        ? 'The extension does not split: no point of P¹ is fixed, modulo M, by lifts of every multiplier, so no choice of lifts commutes.'
        : 'Lifts that commute were not found; whether the extension splits was not decided.';
    const out = {
        structure, gens: serialGens(us.concat(lifts.filter((_, j) => j !== tIdx), tIdx >= 0 ? [lifts[tIdx]] : [])),
        relations, relationsAreRelators: false, given, unitGap: rel.unitGap,
        module: { tex: Mtex, rank: s, N: N.map(String), ringTex: Rtex, zetaOrder: tIdx >= 0 ? m : 1 },
        D: { tex: Dtex, free: r, torsion: m, multipliers: freeIdx.map((j) => ({ name: liftNames[j], tex: F.tex(liftS[j].l) })), zeta: tIdx >= 0 ? F.tex(zeta) : null },
        split, splitNote,
    };
    if (!r) {
        // virtually abelian: a finite presentation as it stands
        out.complete = true; out.finitelyPresented = true; out.relationsAreRelators = false;
        out.ringNote = null;
        out.summary = Dtex === '1'
            ? `Γ consists of translations fixing one point of P¹: Γ ≅ ${texPlain(Mtex)}.`
            : `Γ fixes a point of P¹; its translations form M ≅ ${texPlain(Mtex)}, and its multipliers the finite group ${texPlain(Dtex)}, lifted to the elliptic element z of order ${m}.`;
        return out;
    }
    out.complete = true;
    out.ringNote = `$u^{c}$ for $c \\in ${Rtex}$ is the $c$-th power in $M = \\langle\\!\\langle ${uNames.join(', ')} \\rangle\\!\\rangle \\cong ${Mtex}$ (unique, since $M$ is uniquely divisible by the primes ${N.map(String).join(', ')}).`;
    // Bieri–Strebel
    const charOf = (p) => freeIdx.map((j) => { const l = liftS[j].l; const fn = factorInt(l.n[0]).get(p) || 0, fq = factorInt(l.q).get(p) || 0; return fn - fq; });
    let antipodal = null;
    for (let a = 0; a < N.length && !antipodal; a++) for (let b = a + 1; b < N.length; b++) {
        const u = charOf(N[a]), v = charOf(N[b]);
        // v = −c·u with c > 0
        const i0 = u.findIndex((x) => x !== 0);
        if (i0 < 0 || v[i0] === 0 || Math.sign(v[i0]) === Math.sign(u[i0])) continue;
        if (u.every((x, i) => x * v[i0] === v[i] * u[i0])) { antipodal = [N[a], N[b]]; break; }
    }
    out.finitelyPresented = !antipodal;
    out.fpReason = antipodal
        ? `$v_{${antipodal[0]}}$ and $v_{${antipodal[1]}}$ restrict to opposite characters of $D$, so by Bieri–Strebel $\\Gamma$ is not finitely presented.`
        : `No two of the valuations $v_p$, $p \\in \\{${N.join(', ')}\\}$, restrict to opposite characters of $D$, so by Bieri–Strebel $\\Gamma$ is finitely presented.`;
    // an ordinary presentation for one free multiplier
    if (r === 1) out.ordinary = ordinaryOneMultiplier(ctx, { F, A, liftS, lifts, freeIdx, tIdx, m, us, uNames, basis, coordsIn, evalS, s, N, finitelyPresented: !antipodal });
    out.summary = `Γ fixes a point of P¹. Its translations form M ≅ ${texPlain(Mtex)}, a module over ℤ[D], and its multipliers D ≅ ${texPlain(Dtex)}${split ? ', which lifts to Γ' : ''}.`;
    return out;
}

function checkTranslation(F, x) {
    if (!F.eq(x.l, F.one)) throw new Error('internal: a kernel element has a nontrivial multiplier');
    return x.b;
}
function commutators(F, A, xs) {
    const out = [];
    for (let a = 0; a < xs.length; a++) for (let b = a + 1; b < xs.length; b++) out.push(A.comp(A.comp(xs[a], xs[b]), A.inv(A.comp(xs[b], xs[a]))));
    return out;
}
/** coordinates of v in the ℚ-independent vectors bs (rational, exact), or throws */
function solveRational(F, bs, v) {
    const s = bs.length, d = F.d;
    // columns bs; solve Σ c_l b_l = v over ℚ by Gaussian elimination on the d×(s+1) system
    const rows = Array.from({ length: d }, (_, i) => bs.map((b) => ({ n: b.n[i], q: b.q })).concat([{ n: v.n[i], q: v.q }]));
    const R = { add: (x, y) => nr(x.n * y.q + y.n * x.q, x.q * y.q), mul: (x, y) => nr(x.n * y.n, x.q * y.q), div: (x, y) => nr(x.n * y.q, x.q * y.n), neg: (x) => ({ n: -x.n, q: x.q }) };
    const piv = [];
    let r = 0;
    for (let c = 0; c < s && r < d; c++) {
        let p = r; while (p < d && rows[p][c].n === 0n) p++;
        if (p === d) continue;
        [rows[r], rows[p]] = [rows[p], rows[r]];
        for (let i = 0; i < d; i++) {
            if (i === r || rows[i][c].n === 0n) continue;
            const f = R.div(rows[i][c], rows[r][c]);
            rows[i] = rows[i].map((x, j) => R.add(x, R.neg(R.mul(f, rows[r][j]))));
        }
        piv.push(c); r++;
    }
    for (let i = r; i < d; i++) if (rows[i][s].n !== 0n) throw new Error('internal: a translation outside the module');
    const out = Array.from({ length: s }, () => F.zero);
    piv.forEach((c, i) => { const x = R.div(rows[i][s], rows[i][c]); out[c] = F.rat(x.n, x.q); });
    return out;
}
function nr(n, q) { if (q < 0n) { n = -n; q = -q; } const g = bgcd(n, q) || 1n; return { n: n / g, q: q / g }; }

/**
 * One free multiplier λ = a/b (and maybe z): Γ = N ⋊ ⟨z⟩, N = M ⋊ ⟨t⟩. When λ^{±1} = n ∈ ℤ,
 * N = ⟨u, t | t u t⁻¹ = u^n⟩ (BS(1, n), or its ℤ[1/n]^s-version); otherwise the infinite presentation
 * ⟨u, t | t u^b t⁻¹ = u^a, [t^i u t^{−i}, u]⟩. Then P. Hall's presentation of the extension by z.
 */
function ordinaryOneMultiplier(ctx, o) {
    const { F, A, liftS, lifts, freeIdx, tIdx, m, uNames, coordsIn, s, finitelyPresented } = o;
    const j = freeIdx[0];
    let lam = liftS[j].l;
    let tName = lifts[j].name;
    const tAff = liftS[j];
    let inverted = false;
    const isInt = (x) => x.q === 1n;
    if (!isInt(lam) && isInt(F.inv(lam))) { lam = F.inv(lam); inverted = true; }
    const a = lam.n[0], b = lam.q;
    const T = inverted ? `${tName}^{-1}` : tName, Ti = inverted ? tName : `${tName}^{-1}`;
    const rels = [];
    const infinite = [];
    if (b === 1n) {
        for (let l = 0; l < s; l++) rels.push(`${T}\\, ${uNames[l]}\\, ${Ti} = ${uNames[l]}^{${a}}`);
        for (let l = 0; l < s; l++) for (let l2 = l + 1; l2 < s; l2++) rels.push(`[${uNames[l]}, ${uNames[l2]}]`);
    } else {
        for (let l = 0; l < s; l++) rels.push(`${T}\\, ${uNames[l]}^{${b}}\\, ${Ti} = ${uNames[l]}^{${a}}`);
        infinite.push(`[${T}^{i}\\, ${s === 1 ? uNames[0] : 'u_l'}\\, ${T}^{-i},\\ ${s === 1 ? uNames[0] : 'u_{l\'}'}] \\quad (i \\ge 1${s === 1 ? '' : ',\\ 1 \\le l, l\' \\le ' + s})`);
    }
    // z: z² (or z^m) and z's action on u and t, written in N
    if (tIdx >= 0) {
        const zAff = liftS[tIdx];
        rels.push(`z^{${m}}`);
        const zeta = zAff.l;
        for (let l = 0; l < s; l++) {
            const co = coordsIn(F.mul(zeta, o.basis[l].v));
            rels.push(`z\\, ${uNames[l]}\\, z^{-1} = ${mWord(F, co, uNames, tName, inverted ? -1 : 1, a, b)}`);
        }
        // z t z⁻¹ = c·t with c a translation
        const c = A.comp(A.comp(zAff, tAff), A.inv(zAff));
        const tr = A.comp(c, A.inv(tAff));
        if (!F.eq(tr.l, F.one)) throw new Error('internal: z t z⁻¹ t⁻¹ is not a translation');
        const co = coordsIn(tr.b);
        const w = mWord(F, co, uNames, tName, inverted ? -1 : 1, a, b);
        rels.push(`z\\, ${tName}\\, z^{-1} = ${w === '1' ? '' : `${w}\\, `}${tName}`);
    }
    return {
        finite: b === 1n, relators: rels, infinite,
        note: b === 1n
            ? (s === 1 ? `This is the Baumslag–Solitar group BS(1, ${a})${tIdx >= 0 ? ', extended by z' : ''}.` : `An ascending HNN extension of $\\mathbb{Z}^{${s}}$.`)
            : `The relation alone gives BS(${b}, ${a}); the commutators make the normal closure of $${uNames[0]}$ abelian, and infinitely many of them are needed${finitelyPresented ? '' : ' (Γ is not finitely presented)'}.`,
    };
}
/**
 * An element ∏ u_l^{c_l} of M (c_l ∈ ℤ[1/ab]) as a word in u and t: c = Σ n_e λ^e is a Laurent
 * polynomial in λ = a/b, and t^e u t^{−e} = u^{λ^e}.
 */
function mWord(F, co, uNames, tName, sigma, a, b) {
    const tp = (x) => (x === 1 ? tName : `${tName}^{${x}}`);
    const parts = [];
    co.forEach((c, l) => {
        if (F.isZero(c)) return;
        const poly = laurent({ n: c.n[0], q: c.q }, a, b);
        for (const [e, n] of [...poly.entries()].sort((x, y) => x[0] - y[0])) {
            if (!n) continue;
            const u = n === 1n ? uNames[l] : `${uNames[l]}^{${n}}`;
            parts.push(e === 0 ? u : `${tp(sigma * e)}\\,${u}\\,${tp(-sigma * e)}`);
        }
    });
    return parts.join('\\, ') || '1';
}
/** c ∈ ℤ[1/ab] as a Laurent polynomial in λ = a/b with integer coefficients: Map e → n */
function laurent(c, a, b) {
    // 1/b = σλ + τ and 1/a = σ + τλ⁻¹, from σa + τb = 1
    const [g, sg, tg] = egcd(a, b);
    if (g !== 1n && g !== -1n) throw new Error('internal: λ not in lowest terms');
    const mulP = (P, Qm) => { const R = new Map(); for (const [e1, n1] of P) for (const [e2, n2] of Qm) R.set(e1 + e2, (R.get(e1 + e2) || 0n) + n1 * n2); for (const [e, n] of R) if (!n) R.delete(e); return R; };
    let P = new Map([[0, c.n]]);
    let q = c.q;
    const invB = new Map([[1, sg * g], [0, tg * g]]), invA = new Map([[0, sg * g], [-1, tg * g]]);
    for (const [p, e] of factorInt(q)) {
        for (let i = 0; i < e; i++) {
            if (b % p === 0n) P = mulP(P, new Map([...invB].map(([x, n]) => [x, n * (b / p)])));
            else if (a % p === 0n) P = mulP(P, new Map([...invA].map(([x, n]) => [x, n * (a / p)])));
            else throw new Error('internal: a denominator outside ℤ[1/ab]');
        }
    }
    return P;
}

/**
 * c ∈ ℤ[1/N] as a Laurent polynomial with integer coefficients in multipliers λⱼ = aⱼ/bⱼ (lowest terms)
 * whose primes cover N: Map 'e₁,…,e_r' → n. For p | bⱼ, 1/p = (bⱼ/p)(σλⱼ + τ); for p | aⱼ,
 * 1/p = (aⱼ/p)(σ + τλⱼ⁻¹), with σaⱼ + τbⱼ = 1.
 */
function laurentMulti(c, lams) {
    const r = lams.length;
    const key = (e) => e.join(',');
    const mulP = (P, Qm) => {
        const R = new Map();
        for (const [k1, n1] of P) for (const [k2, n2] of Qm) {
            const e = k1.split(',').map(Number).map((x, i) => x + Number(k2.split(',')[i]));
            const kk = key(e);
            R.set(kk, (R.get(kk) || 0n) + n1 * n2);
        }
        for (const [kk, n] of R) if (!n) R.delete(kk);
        return R;
    };
    const unit = (j, x) => { const e = new Array(r).fill(0); e[j] = x; return key(e); };
    let P = new Map([[key(new Array(r).fill(0)), c.n]]);
    for (const [p, mult] of factorInt(c.q)) {
        const j = lams.findIndex(({ a, b }) => a % p === 0n || b % p === 0n);
        if (j < 0) throw new Error('internal: a denominator outside ℤ[1/N]');
        const { a, b } = lams[j];
        const [g, sg, tg] = egcd(a, b);
        const sgn = g < 0n ? -1n : 1n;
        const f = b % p === 0n
            ? new Map([[unit(j, 1), sgn * sg * (b / p)], [unit(j, 0), sgn * tg * (b / p)]])
            : new Map([[unit(j, 0), sgn * sg * (a / p)], [unit(j, -1), sgn * tg * (a / p)]]);
        for (const [kk, n] of f) if (!n) f.delete(kk);
        for (let i = 0; i < mult; i++) P = mulP(P, f);
    }
    return P;
}

/** multipliers that are not rational over a number field: the structure, without the module relations */
function partialBorel(ctx, { kind, Q, lifts, gens, r, m }) {
    const Dtex = abelianTex(Q.orders);
    const us = gens.map((g, l) => niceGen(ctx, sym('m', l, gens.length), g.expr));
    return {
        structure: `M \\rtimes ${Dtex}`, gens: serialGens(us.concat(lifts)), relations: [], relationsAreRelators: false,
        complete: false, given: [],
        summary: `Γ fixes a point of P¹, with multipliers D ≅ ${texPlain(Dtex)} that are not all rational. Its translations M are the ℤ[D]-module generated by ${us.length} element${us.length === 1 ? '' : 's'}; the relations of that module are not computed.`,
        D: { tex: Dtex, free: r, torsion: m },
        kindNote: kind,
    };
}

