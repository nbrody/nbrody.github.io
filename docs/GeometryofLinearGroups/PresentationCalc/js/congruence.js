/**
 * congruence.js — the congruence closure Δ of Γ ⊂ Λ = PGL₂(ℤ[1/S]) over ℚ, as one joint image.
 *
 * Λ has the congruence subgroup property (S ≠ ∅), so every finite-index subgroup contains a
 * principal congruence subgroup: Γ is S-arithmetic exactly when Γ = Δ, and always
 * [Λ : Γ] ≥ [Λ : Δ]. The computation goes through Λ₀ = PSL₂(ℤ[1/S]), the elements whose
 * determinant is a square of an S-unit:
 *   · Λ/Λ₀ ≅ C = {±1} × ∏_{p∈S} ℤ/2 (sign of det, parities of v_p(det)), quadratic characters of
 *     det and so congruence too; Γ meets |C_Γ| of these classes, and Γ₀ = Γ ∩ Λ₀ has index |C_Γ|
 *     in Γ, generated by Schreier generators;
 *   · an element of Λ₀ is a matrix of SL₂(ℤ[1/S]) up to sign, so its image modulo N (coprime to S)
 *     lies in SL₂(ℤ/N)/±1, and Λ₀ maps onto it (strong approximation).
 * So [Λ : Δ] = |C|/|C_Γ| · |SL₂(ℤ/N)/±1| / |im Γ₀| for N deep enough. (Working in PGL₂(ℤ/N) instead
 * would lose information: the scalars of Λ are only the ±S-units, and they act on all the primes
 * of N at once.)
 *
 * The levels start from the Zariski engine's (pgl2Engine.js congruenceClosure): it finds the finite
 * set of primes where the closure can be smaller than the maximal compact subgroup (Dickson,
 * Serre's lifting lemma) and a level at each. At a prime ℓ ≥ 5 where the closure is full it
 * contains SL₂(ℤ_ℓ), which is perfect and so shares no quotient with the other primes. At 2 and 3
 * the closure is prosolvable, so those primes are always included. Every level is then followed
 * up its powers until the index stops growing: for k ≥ 1 (k ≥ 2 at 2), ℓ-th powers carry the
 * kernel at level k onto the one at k + 1, so one step without growth means none after.
 *
 * A level the engine could not certify, or one that could not be followed (the image too large),
 * makes Δ larger than the true closure: the index is then a lower bound, and is reported as one.
 */

const babs = (x) => (x < 0n ? -x : x);
const bgcd = (a, b) => { a = babs(a); b = babs(b); while (b) [a, b] = [b, a % b]; return a; };
const bdet = (A) => A[0] * A[3] - A[1] * A[2];
const md = (x, q) => ((x % q) + q) % q;
const gcdn = (a, b) => { a = Math.abs(a); b = Math.abs(b); while (b) [a, b] = [b, a % b]; return a; };
function invmod(x, q) {
    let [a, b, s, t] = [md(x, q), q, 1, 0];
    while (b) { const k = Math.floor(a / b); [a, b] = [b, a - k * b]; [s, t] = [t, s - k * t]; }
    return md(s, q);
}
const primeOf = (q) => { for (let p = 2; p * p <= q; p++) if (q % p === 0) return p; return q; };

/** The primitive integer matrix of a row of rationals (strings 'a' or 'a/b'), or null. */
export function primitiveRow(row) {
    const q = row.map((e) => /^\s*(-?\d+)\s*(?:\/\s*(\d+))?\s*$/.exec(String(e)));
    if (q.some((x) => !x)) return null;
    const num = q.map((x) => BigInt(x[1])), den = q.map((x) => BigInt(x[2] || '1'));
    const L = den.reduce((l, d) => (l / bgcd(l, d)) * d, 1n);
    const A = num.map((n, i) => n * (L / den[i]));
    const g = A.reduce((s, x) => bgcd(s, x), 0n);
    return A.map((x) => x / g);
}

/**
 * The starting levels from the engine's congruence closure: { start: Map p → k, certified, notes }.
 * The engine's levels are for the image in PGL₂(ℤ_ℓ) (all units as scalars) and for the part of Γ
 * with square determinant; here only ±S-units are scalars, so each level is then followed up its
 * powers (congruenceClosure).
 */
export function engineLevels(C, S) {
    const start = new Map();
    const notes = [];
    let certified = true;
    for (const c of C.checked || []) {
        const p = Number(c.p);
        if (S.includes(p) || c.status === 'full') continue;
        if (c.status === 'full-partial') { certified = false; notes.push(`${p}: full modulo ${p}^${c.fullThrough}, deeper levels not certified`); continue; }
        if (c.status === 'deficient' && c.index && c.level) { start.set(p, c.level); continue; }
        // deficient but not certified, or unknown: the deepest level enumerated
        const m = c.levels && c.levels.length ? c.levels[c.levels.length - 1].m : 1;
        start.set(p, m);
        notes.push(`${p}: the engine's local index is ${c.indexAtLeast ? `≥ ${c.indexAtLeast}` : 'not determined'}${c.note ? ` (${c.note})` : ''}`);
    }
    if (C.complete === false) { certified = false; notes.push('some norms could not be factored, so the list of primes may be incomplete'); }
    // the prosolvable primes, always: 2 from 2³, 3 from 3
    if (!S.includes(2)) start.set(2, Math.max(start.get(2) || 0, 3));
    if (!S.includes(3)) start.set(3, Math.max(start.get(3) || 0, 1));
    return { start, certified, notes };
}

/** The class of det(M) in C: bit 0 the sign, bit i+1 the parity of v_{S[i]}. */
function detClass(M, S) {
    let d = bdet(M), c = d < 0n ? 1 : 0;
    d = babs(d);
    S.forEach((p, i) => { let v = 0; const P = BigInt(p); while (d % P === 0n) { d /= P; v++; } if (v & 1) c |= 2 << i; });
    return c;
}
const bmul = (A, B) => {
    const C = [A[0] * B[0] + A[1] * B[2], A[0] * B[1] + A[1] * B[3], A[2] * B[0] + A[3] * B[2], A[2] * B[1] + A[3] * B[3]];
    const g = C.reduce((s, x) => bgcd(s, x), 0n);
    return C.map((x) => x / g);
};
const badj = (A) => [A[3], -A[1], -A[2], A[0]];

/**
 * Γ₀ = Γ ∩ Λ₀ by Schreier generators over the classes Γ meets: { gens, classes }. Every generator
 * has det = (an S-unit)², so it is s·A with A ∈ SL₂(ℤ[1/S]): returned as { M, s } (M primitive).
 */
function kernelZero(gens, S) {
    const reps = new Map([[0, [1n, 0n, 0n, 1n]]]), queue = [0];
    while (queue.length) {
        const c = queue.shift();
        for (const g of gens) { const d = c ^ detClass(g, S); if (!reps.has(d)) { reps.set(d, bmul(reps.get(c), g)); queue.push(d); } }
    }
    const out = [], seen = new Set();
    for (const [c, t] of reps) for (const g of gens) {
        const d = c ^ detClass(g, S);
        const x = bmul(bmul(t, g), badj(reps.get(d)));
        const k = x.join(',');
        if (seen.has(k) || (x[1] === 0n && x[2] === 0n && x[0] === x[3])) continue;
        seen.add(k);
        // det x = u², u = ∏ p^{v_p/2}
        let d2 = bdet(x), u = 1n;
        if (d2 < 0n) throw new Error('internal: a class-0 element with negative determinant');
        for (const p of S) { const P = BigInt(p); let v = 0; while (d2 % P === 0n) { d2 /= P; v++; } if (v & 1) throw new Error('internal: odd valuation in Γ₀'); u *= P ** BigInt(v / 2); }
        if (d2 !== 1n) throw new Error('internal: a determinant that is not an S-unit');
        out.push({ M: x, u });
    }
    return { gens: out, classes: reps.size, reps };
}

/** SL₂(ℤ/q) for one level: matrices as four residues, keyed by a number. */
function levelOps(q) {
    const mul = (A, B) => [(A[0] * B[0] + A[1] * B[2]) % q, (A[0] * B[1] + A[1] * B[3]) % q, (A[2] * B[0] + A[3] * B[2]) % q, (A[2] * B[1] + A[3] * B[3]) % q];
    const inv = (A) => [A[3], (q - A[1]) % q, (q - A[2]) % q, A[0]];
    const key = (A) => ((A[0] * q + A[1]) * q + A[2]) * q + A[3];
    return { q, mul, inv, key, one: [1 % q, 0, 0, 1 % q] };
}
const slOrder = (q) => { if (q === 1) return 1; const p = primeOf(q); return (q / p) ** 3 * p * (p * p - 1); };

/**
 * |⟨gens⟩| in ∏ SL₂(ℤ/q_i), level by level (Goursat): the image H₁ in the first level by
 * breadth-first search, with a transversal; the Schreier generators of the kernel of H → H₁ lie in
 * the other levels, and |H| = |H₁| · |kernel|, by recursion. Every search is the size of one
 * level's image. gens: arrays of per-level matrices. Returns the order, or null past the cap/deadline.
 */
function productOrder(gens, ops, cap, deadline) {
    if (!ops.length) return 1;
    const [A, ...rest] = ops;
    const seen = new Map();                   // key → index into states
    const states = [A.one], trans = [rest.map((o) => o.one)];
    seen.set(A.key(A.one), 0);
    const kernel = new Map();                 // Schreier generators in the other levels, by key
    const restKey = (xs) => xs.map((x, i) => rest[i].key(x)).join('|');
    const isOne = (xs) => xs.every((x, j) => x[1] === 0 && x[2] === 0 && x[0] === rest[j].one[0] && x[3] === rest[j].one[3]);
    for (let i = 0; i < states.length; i++) {
        if ((i & 4095) === 4095 && Date.now() > deadline) return null;
        for (const g of gens) {
            const y = A.mul(states[i], g[0]);
            const ty = trans[i].map((x, j) => rest[j].mul(x, g[j + 1]));
            const k = A.key(y);
            const at = seen.get(k);
            if (at === undefined) {
                if (states.length >= cap) return null;
                seen.set(k, states.length); states.push(y); trans.push(ty);
            } else if (rest.length) {
                // Schreier: t_x · g · t_{xg}⁻¹ is trivial in the first level, and these generate the
                // kernel (the conjugates t_{xg}⁻¹ · t_x g need not)
                const s = trans[at].map((x, j) => rest[j].mul(ty[j], rest[j].inv(x)));
                if (isOne(s)) continue;
                const sk = restKey(s);
                if (!kernel.has(sk)) { if (kernel.size >= cap) return null; kernel.set(sk, s); }
            }
        }
    }
    if (!rest.length) return states.length;
    const k = productOrder([...kernel.values()], rest, cap, deadline);
    return k === null ? null : states.length * k;
}

/**
 * |im Γ₀| in SL₂(ℤ/N)/±1 (N = ∏ levels): lift every generator to SL₂ with either sign, add −1, and
 * halve. The levels go largest group first, so the searches after the first stay small.
 */
function imageOrder(K, levels, cap, deadline) {
    if (levels.reduce((s, q) => s * q, 1) <= 2) return 1;
    const ops = levels.slice().sort((x, y) => slOrder(y) - slOrder(x)).map(levelOps);
    const lift = ({ M, u }) => ops.map(({ q }) => {
        const ui = invmod(Number(md(u, BigInt(q))), q);
        return M.map((x) => (Number(md(x, BigInt(q))) * ui) % q);
    });
    const gens = K.gens.map(lift).concat([ops.map(({ q }) => [q - 1, 0, 0, q - 1])]);
    const order = productOrder(gens, ops, cap, deadline);
    return order === null ? null : order / 2;
}
const ambientOrder = (levels) => { const N = levels.reduce((s, q) => s * q, 1); return levels.reduce((s, q) => s * slOrder(q), 1) / (N > 2 ? 2 : 1); };

/**
 * The congruence closure of Γ = ⟨rows⟩ in PGL₂(ℤ[1/S]), from the engine's congruence data C.
 * Returns { status: 'exact' | 'lower' | 'na' | 'too-large', index, levels, image, ambient,
 *           classes: { gamma, lambda }, notes, ms, reason }.
 */
export function congruenceClosure(rows, S, C, { cap = 4000000, seconds = 20 } = {}) {
    const t0 = Date.now();
    S = S.map(Number);
    if (!S.length) return { status: 'na', reason: 'Γ is bounded at every prime: there is no congruence subgroup property to use.' };
    if (!C || C.error) return { status: 'na', reason: C && C.error ? `the engine's congruence closure failed: ${C.error}` : 'no congruence data' };
    const gens = rows.map(primitiveRow);
    if (gens.some((g) => !g)) return { status: 'na', reason: 'an entry is not rational' };
    // Γ must lie in PGL₂(ℤ[1/S]) as written: every determinant an S-unit
    for (const g of gens) {
        let d = babs(bdet(g));
        for (const p of S) while (d % BigInt(p) === 0n) d /= BigInt(p);
        if (d !== 1n) return { status: 'na', reason: `a generator's determinant has a prime factor outside S (${d}): Γ is not in PGL₂(ℤ[1/S]) as written` };
    }
    const { start, certified: engineCertified, notes } = engineLevels(C, S);
    const deadline = t0 + 1000 * seconds;
    const K = kernelZero(gens, S);
    const lambdaClasses = 2 ** (S.length + 1), classFactor = lambdaClasses / K.classes;
    const exps = new Map(start);
    const levelsOf = () => [...exps.entries()].sort((x, y) => x[0] - y[0]).map(([p, k]) => p ** k);
    const measure = () => {
        const levels = levelsOf();
        if (levels.some((q) => q > 2 ** 13)) return null;                  // residues multiply exactly; keys fit
        const im = imageOrder(K, levels, cap, deadline), ambient = ambientOrder(levels);
        return im === null ? null : { levels, image: im, ambient, index: classFactor * Math.round(ambient / im) };
    };
    let cur = measure();
    if (!cur) return { status: 'too-large', levels: levelsOf(), notes, ms: Date.now() - t0, reason: `the image has more than ${cap.toLocaleString()} elements` };
    // follow every level up its powers until one more step adds nothing (then the closure is
    // stable there: ℓ-th powers carry the next kernel onto the one after, for k ≥ 1, or k ≥ 2 at 2)
    let stable = true;
    for (let round = 0, grew = true; grew && round < 8; round++) {
        grew = false;
        for (const p of [...exps.keys()].sort((x, y) => x - y)) {
            for (;;) {
                exps.set(p, exps.get(p) + 1);
                const next = measure();
                if (!next) { exps.set(p, exps.get(p) - 1); stable = false; notes.push(`the level at ${p} could not be followed past ${p}^${exps.get(p)} (the image is too large)`); break; }
                if (next.index > cur.index) { cur = next; grew = true; continue; }
                exps.set(p, exps.get(p) - 1);
                break;
            }
        }
    }
    return {
        status: engineCertified && stable ? 'exact' : 'lower', index: cur.index, levels: cur.levels, image: cur.image, ambient: cur.ambient,
        classes: { gamma: K.classes, lambda: lambdaClasses }, notes, ms: Date.now() - t0,
    };
}

/** (testing) the index at the given levels, without following them */
export function _index(rows, S, levels, cap = 8000000) {
    S = S.map(Number);
    const K = kernelZero(rows.map(primitiveRow), S);
    const im = imageOrder(K, levels, cap, Infinity), ambient = ambientOrder(levels);
    return im === null ? null : { image: im, ambient, classes: K.classes, index: (2 ** (S.length + 1) / K.classes) * ambient / im };
}

/**
 * The congruence description of Γ = ⟨rows⟩ from the levels of its closure Δ (congruenceClosure):
 * the least level N at which Δ is already cut out — each prime power is lowered while the index
 * stays — and Γ₀'s image H₀ in SL₂(ℤ/N)/±1, with its shape when it is a standard one. So
 *     Δ ∩ Λ₀ = { g ∈ PSL₂(ℤ[1/S]) : g mod N ∈ H₀ },  Δ = that, in the det classes C_Γ;
 * and Δ = Γ when Γ is S-arithmetic (S ≠ ∅, by the congruence subgroup property).
 * Returns { N, levels, index, image, ambient, shape, classes: { gamma, lambda, basis } } or null.
 */
export function congruenceDescription(rows, S, levels, { cap = 4000000 } = {}) {
    S = S.map(Number);
    const gens = rows.map(primitiveRow);
    if (gens.some((g) => !g)) return null;
    const K = kernelZero(gens, S);
    const classFactor = 2 ** (S.length + 1) / K.classes;
    const at = (lv) => { const im = imageOrder(K, lv, cap, Infinity); return im === null ? null : { image: im, ambient: ambientOrder(lv), index: classFactor * Math.round(ambientOrder(lv) / im) }; };
    const exps = new Map(levels.map((q) => { const p = primeOf(q); let k = 0; for (let x = q; x > 1; x /= p) k++; return [p, k]; }));
    const lv = () => [...exps].filter(([, k]) => k > 0).sort((x, y) => x[0] - y[0]).map(([p, k]) => p ** k);
    const full = at(lv());
    if (!full) return null;
    for (const p of [...exps.keys()]) {
        while (exps.get(p) > 0) {
            exps.set(p, exps.get(p) - 1);
            const t = at(lv());
            if (!t || t.index !== full.index) { exps.set(p, exps.get(p) + 1); break; }
        }
    }
    const L = lv(), N = L.reduce((s, q) => s * q, 1), here = at(L);
    // the shape of H₀: every generator's lift mod N tested against the standard subgroups, and the
    // order compared with theirs (in SL₂(ℤ/N)/±1)
    const lifts = K.gens.map(({ M, u }) => {
        const ui = invmod(Number(md(u, BigInt(N))), N);
        return M.map((x) => (Number(md(x, BigInt(N))) * ui) % N);
    });
    const pm1 = (x) => x === 1 % N || x === (N - 1) % N;
    const all = (f) => lifts.every(f);
    const phi = (n) => { let r = n; for (let p = 2, m = n; p <= m; p++) if (m % p === 0) { r = r / p * (p - 1); while (m % p === 0) m /= p; } return r; };
    const half = N > 2 ? 2 : 1;
    let shape = null;
    if (N === 1) shape = 'full';
    else if (all((A) => A[1] === 0 && A[2] === 0 && pm1(A[0]) && A[0] === A[3]) && here.image === 1) shape = 'Γ(N)';
    else if (all((A) => A[2] === 0 && pm1(A[0]) && A[0] === A[3]) && here.image === N / (N > 2 ? 1 : 1)) shape = 'Γ₁(N)';
    else if (all((A) => A[1] === 0 && pm1(A[0]) && A[0] === A[3]) && here.image === N) shape = 'Γ¹(N)';
    else if (all((A) => A[2] === 0) && here.image === N * phi(N) / half) shape = 'Γ₀(N)';
    else if (all((A) => A[1] === 0) && here.image === N * phi(N) / half) shape = 'Γ⁰(N)';
    // the determinant classes Γ meets, as a basis of signed products of primes of S (mod squares)
    const cls = gens.map((g) => detClass(g, S)).filter((c) => c);
    const basis = [];
    for (let c of cls) { for (const b of basis) if ((c ^ b) < c) c ^= b; if (c) { basis.push(c); basis.sort((x, y) => y - x); } }
    const classText = (c) => { const f = []; if (c & 1) f.push('−1'); S.forEach((p, i) => { if (c & (2 << i)) f.push(String(p)); }); return f.join('·'); };
    return {
        N, levels: L, index: here.index, image: here.image, ambient: here.ambient, shape,
        classes: { gamma: K.classes, lambda: 2 ** (S.length + 1), basis: basis.map(classText) },
    };
}

/**
 * The action of Λ = PGL₂(ℤ[1/S]) on the cosets Γ\Λ of a congruence subgroup Γ, from its
 * description alone: Γ ∩ Λ₀ = { g : g mod N ∈ H₀ } and the classes C_Γ (congruenceDescription).
 * A coset Γg is labelled by the least class d in [det g]·C_Γ and by the coset H₀·π(t g r_d⁻¹), with
 * t ∈ Γ moving g into class d and r_d a fixed element of Λ of class d (products of J, D_p); π is
 * reduction mod N after dividing by √det. Everything is computed mod N, so no entry grows.
 * letters: Λ's generators as integer matrices (BigInt); rows: Γ's generators. Returns
 * { index, table: table[i][x] = coset i·x } or { error }. Valid when Γ is its own congruence
 * closure at these levels (S-arithmetic, S ≠ ∅); the caller re-checks the table.
 */
export function congruenceCosetAction(rows, S, levels, letters, { maxCosets = 200000, maxH = 4000000 } = {}) {
    S = S.map(Number);
    const N = levels.reduce((s, q) => s * q, 1);
    if (N ** 4 * 2 ** (S.length + 1) > 2 ** 52) return { error: `the level ${N} is too large for exact keys` };
    const gens = rows.map(primitiveRow);
    if (gens.some((g) => !g)) return { error: 'an entry is not rational' };
    const K = kernelZero(gens, S);
    const Nb = BigInt(N);
    // elements as { m: four residues mod N, sign, e: exponents at S } (an exact lift's determinant)
    const elt = (M) => {
        let d = bdet(M); const sign = d < 0n ? -1 : 1; d = babs(d);
        const e = S.map((p) => { let v = 0; const P = BigInt(p); while (d % P === 0n) { d /= P; v++; } return v; });
        if (d !== 1n) throw new Error('a determinant is not an S-unit');
        return { m: M.map((x) => Number(md(x, Nb))), sign, e };
    };
    const mulE = (A, B) => ({
        m: [(A.m[0] * B.m[0] + A.m[1] * B.m[2]) % N, (A.m[0] * B.m[1] + A.m[1] * B.m[3]) % N, (A.m[2] * B.m[0] + A.m[3] * B.m[2]) % N, (A.m[2] * B.m[1] + A.m[3] * B.m[3]) % N],
        sign: A.sign * B.sign, e: A.e.map((x, i) => x + B.e[i]),
    });
    const adjE = (A) => ({ m: [A.m[3], (N - A.m[1]) % N, (N - A.m[2]) % N, A.m[0]], sign: A.sign, e: A.e.slice() });
    const classOf = (A) => (A.sign < 0 ? 1 : 0) | A.e.reduce((c, x, i) => c | ((x & 1) << (i + 1)), 0);
    // C_Γ, representatives t_γ ∈ Γ, the least class in each coset of C_Γ, and r_d ∈ Λ
    const t = new Map([...K.reps].map(([c, M]) => [c, elt(M)]));
    const nC = 2 ** (S.length + 1);
    const least = new Array(nC).fill(0).map((_, c) => Math.min(...[...t.keys()].map((g) => c ^ g)));
    const J = elt([-1n, 0n, 0n, 1n]), D = S.map((p) => elt([BigInt(p), 0n, 0n, 1n]));
    const r = new Array(nC).fill(null).map((_, d) => {
        let A = elt([1n, 0n, 0n, 1n]);
        if (d & 1) A = mulE(A, J);
        S.forEach((p, i) => { if (d & (2 << i)) A = mulE(A, D[i]); });
        return adjE(A);                                  // r_d⁻¹ up to a scalar
    });
    // H₀ ⊂ SL₂(ℤ/N) with −1: the lifts of Γ₀'s generators, closed under products
    const key4 = (m) => ((m[0] * N + m[1]) * N + m[2]) * N + m[3];
    const mul4 = (A, B) => [(A[0] * B[0] + A[1] * B[2]) % N, (A[0] * B[1] + A[1] * B[3]) % N, (A[2] * B[0] + A[3] * B[2]) % N, (A[2] * B[1] + A[3] * B[3]) % N];
    const hg = K.gens.map(({ M, u }) => { const ui = invmod(Number(md(u, Nb)), N); return M.map((x) => (Number(md(x, Nb)) * ui) % N); });
    hg.push([(N - 1) % N, 0, 0, (N - 1) % N]);
    const one = [1 % N, 0, 0, 1 % N];
    const H = [one], Hk = new Set([key4(one)]);
    for (let i = 0; i < H.length; i++) for (const g of hg) {
        const y = mul4(H[i], g), k = key4(y);
        if (!Hk.has(k)) { if (H.length >= maxH) return { error: `H₀ has more than ${maxH} elements` }; Hk.add(k); H.push(y); }
    }
    // the label of Γg: (d, A) with A ∈ SL₂(ℤ/N) a representative of H₀·π(t g r_d⁻¹)
    const label = (g) => {
        const c = classOf(g), d = least[c];
        const x = mulE(mulE(t.get(c ^ d), g), r[d]);
        if (classOf(x) !== 0) throw new Error('internal: not in Λ₀');
        let u = 1;
        S.forEach((p, i) => { for (let k = 0; k < x.e[i] / 2; k++) u = (u * p) % N; });
        const ui = invmod(u % N, N);
        return { d, A: x.m.map((v) => (v * ui) % N) };
    };
    const base = d => d * N ** 4;
    const reg = new Map(), reps = [], table = [];
    const register = (g) => {
        const { d, A } = label(g);
        const id = reps.length;
        for (const h of H) reg.set(base(d) + key4(mul4(h, A)), id);
        reps.push(g);
        return id;
    };
    const L = letters.map((M) => elt(M.map(BigInt)));
    register(elt([1n, 0n, 0n, 1n]));
    for (let i = 0; i < reps.length; i++) {
        const row = [];
        for (const X of L) {
            const g = mulE(reps[i], X);
            const { d, A } = label(g);
            let id = reg.get(base(d) + key4(A));
            if (id === undefined) {
                if (reps.length >= maxCosets) return { error: `more than ${maxCosets} cosets` };
                id = register(g);
            }
            row.push(id);
        }
        table.push(row);
    }
    return { index: reps.length, table };
}

/**
 * Levels for Γ = ⟨rows⟩ found without the Zariski engine, given [Λ : Γ] (a coset table): prime
 * powers ℓ^k (ℓ ∉ S, ℓ ≤ maxPrime) are added while they raise the index of the closure, until it
 * reaches [Λ : Γ]. Then Γ = Δ is cut out at these levels, whatever the engine would say; if the
 * target is not reached, null.
 */
export function findLevels(rows, S, target, { maxPrime = 60, cap = 2000000, seconds = 20 } = {}) {
    S = S.map(Number);
    const gens = rows.map(primitiveRow);
    if (gens.some((g) => !g)) return null;
    const K = kernelZero(gens, S);
    const classFactor = 2 ** (S.length + 1) / K.classes;
    const deadline = Date.now() + 1000 * seconds;
    const index = (lv) => { if (!lv.length) return classFactor; const im = imageOrder(K, lv, cap, deadline); return im === null ? null : classFactor * Math.round(ambientOrder(lv) / im); };
    const exps = new Map();
    const lv = () => [...exps].sort((x, y) => x[0] - y[0]).map(([p, k]) => p ** k);
    let cur = index([]);
    if (cur === target) return [];
    const primes = [];
    for (let p = 2; p <= maxPrime; p++) if (primeOf(p) === p && !S.includes(p)) primes.push(p);
    // passes over the primes until one adds nothing: a level can matter only next to another
    // (a common quotient of the images at two primes, Goursat)
    for (let pass = 0, grew = true; grew && pass < 6 && Date.now() < deadline; pass++) {
        grew = false;
        for (const p of primes) {
            if (Date.now() > deadline) break;
            // a proper subgroup of PSL₂(F_ℓ), ℓ ≥ 5, has index ≥ ℓ + 1 (ℓ for 5, 7, 11), and the index
            // of the closure divides [Λ : Γ]: a new prime that cannot fit is skipped
            if (p >= 5 && !exps.has(p) && ([5, 7, 11].includes(p) ? p : p + 1) > target / cur) continue;
            // ℓ-th powers carry the kernel at level k onto k + 1 for k ≥ 1 (k ≥ 2 at 2): one step
            // without growth past that means none after
            for (let k = (exps.get(p) || 0) + 1; ; k++) {
                exps.set(p, k);
                const t = index(lv());
                if (t === null) { exps.set(p, k - 1); if (!exps.get(p)) exps.delete(p); return null; }
                if (t > cur) { cur = t; grew = true; if (cur === target) return lv(); continue; }
                if (k === 1 && p === 2) continue;                    // level 2 can be full while 4 is not
                exps.set(p, k - 1);
                if (!exps.get(p)) exps.delete(p);
                break;
            }
            if (cur > target) return null;
        }
    }
    return cur === target ? lv() : null;
}
