/**
 * graphOfGroups.js — an S-arithmetic Γ ⊆ Λ = PGL₂(ℤ[1/S]) as the fundamental group of its quotient
 * graph of groups on the tree T_p of the last prime p of S, from the closed coset table of Γ in Λ
 * (Bass–Serre). The vertex groups are the "integral" subgroups Γ ∩ h·Λ′·h⁻¹, Λ′ = PGL₂(ℤ[1/S∖p])
 * — finite-index subgroups of PGL₂(ℤ) when S = {p}, and decomposed the same way along the next
 * prime otherwise — and the presentation is on their generators, stable letters t (HNN) and edge
 * inversions σ. The same over O = ℤ[i], ℤ[√−2], ℤ[ω] (bianchi.js): Λ = PGL₂(O[1/S]) on the trees
 * T_{N(π)+1}, with vertex group PGL₂(O) at the bottom; its letters come with inverses (alg below).
 *
 * Λ acts on T_p with vertex stabilizer Λ′ (the letters before w = w_p) and edge stabilizer
 * E = Λ′ ∩ Γ₀(p)± (generated by the words egens, with φ(e) = w e w⁻¹ given as words ephi), and w
 * inverts the edge [o, w·o]. For the right cosets Γg (the table, coset 0 = Γ):
 *   • vertex orbits of Γ on T_p = orbits of Λ′ on the cosets; the vertex of coset i is T_i·o for the
 *     transversal T_i = T_root·λ_i (λ_i a word in Λ′), and its stabilizer is T_root·Stab_Λ′(root)·T_root⁻¹;
 *   • the roots are reached along w from earlier orbits (a spanning tree of the quotient graph), so
 *     the lifted vertices T_root·o span a subtree of T_p;
 *   • edge orbits of Γ = orbits of ⟨E, w⟩ on the cosets: an E-orbit H and its image H·w. H·w = H
 *     means some element of Γ inverts the edge (σ = T_i w e₀⁻¹ T_i⁻¹, i·w = i·e₀).
 * The generators of an edge group Stab_E(i) are its Schreier generators on H. Relations: those of
 * the vertex groups; t⁻¹·h·t = φ(h) across every edge (t = 1 on the spanning tree, a stable letter
 * T_i w T_{i·w}⁻¹ off it, σ·γ⁻¹ on an inverted edge), and σ² ∈ G_v. This presents Γ (Serre, Trees,
 * §I.5): a generating set of each edge group is enough, its relations follow from the vertex group's.
 *
 * Any element of Γ, as a word in Λ's letters, is rewritten in the new generators by walking its
 * cosets: a letter of Λ′ stays at a vertex (rewritten in that vertex group, recursively), and w
 * crosses an edge: T_i w T_j⁻¹ = γ₁·t_H·γ₂⁻¹ with γ₁, γ₂ in the vertex groups at the ends.
 *
 * Γ ⊄ Λ over ℚ (odd valuations at primes outside S): its subgroup K = Γ ∩ Λ of even valuations is
 * normal with Γ/K = (ℤ/2)^r, and hallExtension adds coset representatives u₁ … u_r to K's graph of
 * groups (P. Hall's presentation of an extension).
 */
import { reidemeisterSchreier, tietze, findWords } from './presentation.js';

const babs = (x) => (x < 0n ? -x : x);
const bgcd = (a, b) => { a = babs(a); b = babs(b); while (b) [a, b] = [b, a % b]; return a; };
const mul = (A, B) => [A[0] * B[0] + A[1] * B[2], A[0] * B[1] + A[1] * B[3], A[2] * B[0] + A[3] * B[2], A[2] * B[1] + A[3] * B[3]];
const prim = (A) => {
    const g = A.reduce((s, x) => bgcd(s, x), 0n);
    const B = g > 1n ? A.map((x) => x / g) : A.slice();
    return (B.find((x) => x !== 0n) ?? 1n) < 0n ? B.map((x) => -x) : B;
};
const isScalarQ = (A) => A[1] === 0n && A[2] === 0n && A[0] === A[3];
const ONE = [1n, 0n, 0n, 1n];
const adjM = (A) => [A[3], -A[1], -A[2], A[0]];
function projEqM(A, B) { for (let a = 0; a < 4; a++) for (let b = a + 1; b < 4; b++) if (A[a] * B[b] !== A[b] * B[a]) return false; return true; }
const invWord = (w) => w.slice().reverse().map((x) => -x);
const freeReduce = (w) => { const o = []; for (const x of w) { if (o.length && o[o.length - 1] === -x) o.pop(); else o.push(x); } return o; };
function cyclic(w) { let i = 0, j = w.length; while (j - i > 1 && w[i] === -w[j - 1]) { i++; j--; } return w.slice(i, j); }

/**
 * The letters of Λ and their matrices: over ℚ (sarithIndex.js presentationPGL2ZS) every letter is an
 * involution and the matrices are integral. alg = { inv(letter), letterM(letter), mul, adj,
 * isScalar, projEq, one, letterName(letter) (a name for a letter that is a generator of the vertex
 * group at the bottom, or null) }; mul returns a normalized representative.
 */
export function rationalAlgebra(P) {
    return {
        inv: (x) => x, letterM: (x) => P.gens[x],
        mul: (A, B) => prim(mul(A, B)), adj: adjM, isScalar: isScalarQ, projEq: projEqM, one: ONE,
        letterName: (x) => 'abc'[x] ?? null,
    };
}

/**
 * P: presentationPGL2ZS (or bianchi.js presentationPGL2OS, with alg) with P.levels = [{ q, letter,
 * relCount, egens, ephi }], letter the column of w_q; table: the coset table of Γ in Λ. Returns
 * { gens: [{ name, kind, elt (word in Λ's letters), M }], relators (words in ±(k+1)), rewrite(word
 * in Λ's letters, in Γ) → word in gens, tree (the nested description), evalWord, evalNice }, or throws.
 */
/** The largest index [Λ : Γ] for which the graph of groups is computed. */
export const GRAPH_MAX_COSETS = 4000;

export function graphOfGroups(P, table, { maxCosets = GRAPH_MAX_COSETS, seconds = 20, alg = null } = {}) {
    if (table.length > maxCosets) throw new Error(`[Λ : Γ] = ${table.length} is above ${maxCosets} for the graph of groups`);
    const A = alg || rationalAlgebra(P);
    const inv = A.inv;
    const invL = (w) => w.slice().reverse().map(inv);                   // the inverse of a word in Λ's letters
    const reduceL = (w) => { const o = []; for (const x of w) { if (o.length && o[o.length - 1] === inv(x)) o.pop(); else o.push(x); } return o; };
    const deadline = Date.now() + 1000 * seconds;
    const levels = P.levels || [];
    if (!levels.length) throw new Error('internal: no prime to decompose along');
    const all = [], relators = [];
    const addGen = (g) => { all.push(g); return all.length; };
    const tree = decompose(levels.length, table, []);
    // matrices, and every relator checked
    const evalWord = (w) => w.reduce((M, x) => A.mul(M, A.letterM(x)), A.one);
    for (const g of all) g.M = evalWord(g.elt);
    const evalAll = (w) => w.reduce((M, x) => A.mul(M, x > 0 ? all[x - 1].M : A.adj(all[-x - 1].M)), A.one);
    const rels = [];
    const seen = new Set();
    for (const r of relators) {
        const w = cyclic(freeReduce(r));
        if (!w.length) continue;
        if (!A.isScalar(evalAll(w))) throw new Error('internal: a relator of the graph of groups is not the identity');
        const key = w.join(',');
        if (!seen.has(key)) { seen.add(key); rels.push(w); }
    }
    // tidy the relators; a vertex generator that a relator of length ≤ 2 makes trivial or equal to
    // another (an edge relation can) goes, and the stable letters and inversions all stay
    const structural = new Set(all.map((g, i) => (g.kind === 'vertex' ? 0 : i + 1)).filter(Boolean));
    const T = tietze(all.length, rels, { maxLen: 2, prefer: structural, keepPreferred: true, seconds: 2 });
    if ([...structural].some((k) => !T.keep.includes(k))) throw new Error('internal: Tietze removed a stable letter');
    const num = new Map(T.keep.map((k, i) => [k, i + 1]));
    const gens = T.keep.map((k) => all[k - 1]);
    (function renumber(node) {
        if (node.leaf) { node.gens = node.gens.filter((k) => num.has(k)).map((k) => num.get(k)); return; }
        for (const e of node.edges) if (e.gen) e.gen = num.get(e.gen);
        node.vertices.forEach((v) => renumber(v.sub));
    })(tree);
    // names: x for the integral generators (named by their letters for a single copy of the bottom
    // vertex group: a, b, c for PGL₂(ℤ)), t for stable letters, σ for inversions
    const count = (k) => gens.filter((g) => g.kind === k).length;
    const leafs = [];
    (function walk(node) { if (node.leaf) leafs.push(node); else node.vertices.forEach((v) => walk(v.sub)); })(tree);
    const byLetter = leafs.length === 1 && leafs[0].index === 1
        && leafs[0].gens.every((k) => gens[k - 1].elt.length === 1 && A.letterName(gens[k - 1].elt[0]));
    let nx = 0, nt = 0, ns = 0;
    const nX = count('vertex'), nT = count('stable'), nS = count('inversion');
    for (const g of gens) {
        if (g.kind === 'vertex') g.name = byLetter ? A.letterName(g.elt[0]) : nX === 1 ? 'x' : `x_{${++nx}}`;
        else if (g.kind === 'stable') g.name = nT === 1 ? 't' : `t_{${++nt}}`;
        else g.name = nS === 1 ? '\\sigma' : `\\sigma_{${++ns}}`;
    }
    const evalNice = (w) => w.reduce((M, x) => A.mul(M, x > 0 ? gens[x - 1].M : A.adj(gens[-x - 1].M)), A.one);
    for (const r of T.relators) if (!A.isScalar(evalNice(r))) throw new Error('internal: a tidied relator is not the identity');
    return {
        gens, relators: T.relators, tree,
        evalWord,
        rewrite: (w) => {
            const out = freeReduce(tree.rewrite(w).flatMap((x) => (x > 0 ? T.express(x) : invWord(T.express(-x)))));
            if (!A.projEq(evalNice(out), evalWord(w))) throw new Error('internal: rewriting changed the element');
            return out;
        },
        evalNice,
    };

    /** the graph of groups at a level (number of primes left), on a local table rooted at 0 */
    function decompose(level, tab, prefix) {
        if (Date.now() > deadline) throw new Error('out of time for the graph of groups');
        if (!level) return leaf(tab, prefix);
        const lv = levels[level - 1], w = lv.letter, Lp = Array.from({ length: w }, (_, x) => x);
        // the letters crossing an edge: w, and w⁻¹ when it is a letter of its own (both give w·o)
        const crosses = (x) => x === w || x === inv(w);
        const n = tab.length;
        // vertex orbits (Λ′-orbits), reached along w
        const orbitOf = new Array(n).fill(-1), lam = new Array(n).fill(null);
        const orbits = [], treeCos = new Set();
        const newOrbit = (root, Troot) => {
            const v = orbits.length, cos = [root];
            orbitOf[root] = v; lam[root] = [];
            for (let q = 0; q < cos.length; q++) {
                const i = cos[q];
                for (const x of Lp) { const j = tab[i][x]; if (orbitOf[j] < 0) { orbitOf[j] = v; lam[j] = lam[i].concat([x]); cos.push(j); } }
            }
            orbits.push({ root, Troot, cos });
        };
        newOrbit(0, []);
        for (let v = 0; v < orbits.length; v++) for (const i of orbits[v].cos) {
            const j = tab[i][w];
            if (orbitOf[j] < 0) { treeCos.add(i); newOrbit(j, Tof(i).concat([w])); }
        }
        function Tof(i) { return orbits[orbitOf[i]].Troot.concat(lam[i]); }
        // each vertex group, on its orbit's own table
        const vertices = orbits.map((O) => {
            const idx = new Map(O.cos.map((c, k) => [c, k]));
            const sub = O.cos.map((c) => Lp.map((x) => idx.get(tab[c][x])));
            return { index: O.cos.length, Troot: O.Troot, hWord: reduceL(prefix.concat(O.Troot)), sub: decompose(level - 1, sub, prefix.concat(O.Troot)) };
        });
        // vertexWord(v, μ): μ a word in Λ′ fixing the root of orbit v
        const vw = (v, mu) => vertices[v].sub.rewrite(reduceL(mu));
        // E on the cosets
        const walk = (i, word) => word.reduce((c, x) => tab[c][x], i);
        const egens = lv.egens, ephi = lv.ephi;
        const Lword = (eps) => eps.flatMap((e) => (e > 0 ? egens[e - 1] : invL(egens[-e - 1])));
        const Pword = (eps) => eps.flatMap((e) => (e > 0 ? ephi[e - 1] : invL(ephi[-e - 1])));
        const moves = egens.flatMap((_, e) => [e + 1, -(e + 1)]);
        const step = (i, e) => walk(i, e > 0 ? egens[e - 1] : invL(egens[-e - 1]));
        // E-orbits, with representatives: tree cosets c and c·w first, then pairs (i, i·w)
        const eorb = new Array(n).fill(-1), Hs = [];
        const labelOrbit = (start) => {
            const h = Hs.length, cos = [start];
            eorb[start] = h;
            for (let q = 0; q < cos.length; q++) for (const e of moves) { const j = step(cos[q], e); if (eorb[j] < 0) { eorb[j] = h; cos.push(j); } }
            Hs.push({ cos, rep: null });
            return h;
        };
        for (let i = 0; i < n; i++) if (eorb[i] < 0) labelOrbit(i);
        const setRep = (h, i) => { if (Hs[h].rep === null) Hs[h].rep = i; };
        for (const c of treeCos) { setRep(eorb[c], c); setRep(eorb[tab[c][w]], tab[c][w]); }
        for (const H of Hs) if (H.rep === null) { const i = H.cos[0]; setRep(eorb[i], i); setRep(eorb[tab[i][w]], tab[i][w]); }
        // E-paths from each representative
        const epath = new Array(n).fill(null), etree = new Set();
        for (const H of Hs) {
            epath[H.rep] = [];
            const q = [H.rep];
            for (let k = 0; k < q.length; k++) for (const e of moves) {
                const j = step(q[k], e);
                if (epath[j] === null) { epath[j] = epath[q[k]].concat([e]); etree.add(`${q[k]},${e}`); q.push(j); }
            }
        }
        // the edge classes
        const tWord = new Array(Hs.length).fill(null);
        const edges = [];
        Hs.forEach((H, h) => {
            if (tWord[h]) return;
            const i = H.rep, j = tab[i][w], h2 = eorb[j];
            const v = orbitOf[i], v2 = orbitOf[j];
            if (h2 === h) {
                // inverted: i·w = i·e₀
                const e0 = epath[j];
                const k = addGen({ kind: 'inversion', elt: reduceL(prefix.concat(Tof(i), [w], invL(Lword(e0)), invL(Tof(i)), invL(prefix))) });
                tWord[h] = [k].concat(vw(v, lam[i].concat(Lword(e0), invL(lam[j]))));
                edges.push({ kind: 'inversion', from: v, to: v, gen: k, h, index: H.cos.length });
                return;
            }
            const isTree = treeCos.has(i) || treeCos.has(j);
            if (isTree) { tWord[h] = []; tWord[h2] = []; edges.push({ kind: 'tree', from: v, to: v2, h, index: H.cos.length }); return; }
            const k = addGen({ kind: 'stable', elt: reduceL(prefix.concat(Tof(i), [w], invL(Tof(j)), invL(prefix))) });
            tWord[h] = [k]; tWord[h2] = [-k];
            edges.push({ kind: 'stable', from: v, to: v2, gen: k, h, index: H.cos.length });
        });
        // relations across each edge: t⁻¹·h·t = φ(h) for the Schreier generators h of Stab_E(rep)
        for (const ed of edges) {
            if (Date.now() > deadline) throw new Error('out of time for the graph of groups');
            const H = Hs[ed.h], i = H.rep, j = tab[i][w];
            const v = orbitOf[i], v2 = orbitOf[j];
            const t = tWord[ed.h];
            const hs = [], hk = new Set();
            for (const c of H.cos) for (const e of moves) {
                if (etree.has(`${c},${e}`)) continue;
                const d = step(c, e);
                if (etree.has(`${d},${-e}`)) continue;
                const hw = freeReduce(epath[c].concat([e], invWord(epath[d])));
                if (!hw.length) continue;
                const key = hw.join(','), ikey = invWord(hw).join(',');
                if (hk.has(key) || hk.has(ikey)) continue;
                hk.add(key); hs.push(hw);
            }
            ed.edgeGens = hs.length;
            for (const hw of hs) {
                const V = vw(v, lam[i].concat(Lword(hw), invL(lam[i])));
                const V2 = vw(v2, lam[j].concat(Pword(hw), invL(lam[j])));
                relators.push(invWord(t).concat(V, t, invWord(V2)));
            }
            if (ed.kind === 'inversion') {
                // σ² = T_i·(w e₀⁻¹)²·T_i⁻¹ = T_i·φ(e₀)⁻¹e₀⁻¹·T_i⁻¹
                const e0 = epath[j];
                const sq = vw(v, lam[i].concat(invL(Pword(e0)), invL(Lword(e0)), invL(lam[i])));
                relators.push([ed.gen, ed.gen].concat(invWord(sq)));
            }
        }
        const rewrite = (word) => {
            const out = [];
            let i = 0;
            for (const x of word) {
                const j = tab[i][x];
                if (!crosses(x)) out.push(...vw(orbitOf[i], lam[i].concat([x], invL(lam[j]))));
                else {
                    const h = eorb[i], iH = Hs[h].rep, eps = epath[i], jH = tab[iH][w];
                    const g1 = vw(orbitOf[i], lam[i].concat(invL(Lword(eps)), invL(lam[iH])));
                    const g2 = vw(orbitOf[j], lam[j].concat(invL(Pword(eps)), invL(lam[jH])));
                    out.push(...g1, ...tWord[h], ...invWord(g2));
                }
                i = j;
            }
            if (i !== 0) throw new Error('not in the group');
            return freeReduce(out);
        };
        return {
            leaf: false, prime: lv.name ?? String(lv.q), valence: (lv.norm ?? Number(lv.q)) + 1, level, index: n, vertices,
            edges: edges.map((e) => ({ kind: e.kind, from: e.from, to: e.to, gen: e.gen ?? null, edgeIndex: e.index, edgeGens: e.edgeGens })), rewrite,
        };
    }

    /** a finite-index subgroup of the bottom vertex group (PGL₂(ℤ) = ⟨a, b, c⟩, or PGL₂(O)), by Reidemeister–Schreier on its table */
    function leaf(tab, prefix) {
        const nLetters = levels[0].letter, relCount = levels[0].relCount;
        const RS = reidemeisterSchreier({ nLetters, inv, relators: P.relators.slice(0, relCount), table: tab });
        const T = tietze(RS.gens.length, RS.relators, { maxLen: 16, seconds: 2 });
        const local = T.keep.map((k) => {
            const { i, x } = RS.gens[k - 1];
            return reduceL(RS.transversal[i].concat([x], invL(RS.transversal[tab[i][x]])));
        });
        const ids = local.map((sw) => addGen({ kind: 'vertex', elt: reduceL(prefix.concat(sw, invL(prefix))) }));
        const map = (u) => u.map((a) => Math.sign(a) * ids[Math.abs(a) - 1]);
        for (const r of T.relators) relators.push(map(r));
        const rewrite = (word) => {
            const s = RS.rewrite(word);
            return freeReduce(map(s.flatMap((k) => (k > 0 ? T.express(k) : invWord(T.express(-k))))));
        };
        return { leaf: true, index: tab.length, gens: ids, relators: T.relators.length, rewrite };
    }
}

/**
 * Γ ⊇ K (= Γ ∩ Λ, normal, Γ/K = (ℤ/2)^r) from K's graph of groups G (graphOfGroups) and coset
 * representatives us = [{ M }] of a basis of Γ/K, by P. Hall's presentation of the extension: the
 * generators of G and u₁ … u_r; G's relators, u_j·k·u_j⁻¹ = φ_j(k) for every generator k of G,
 * u_j² ∈ K and [u_j, u_l] ∈ K, each right-hand side rewritten in G by kNice(M ∈ K) → word.
 * split(M ∈ Γ) → { js (sorted basis indices), k } with M = u_{j₁} ⋯ u_{j_t}·k, k ∈ K.
 * Returns G's fields with the u's added (kind 'coset') and rewriteM(M ∈ Γ) → word, all checked.
 */
export function hallExtension(G, us, { alg, kNice, split, seconds = 2 }) {
    const A = alg;
    const m = G.gens.length;
    const uGens = us.map((u, j) => ({ name: us.length === 1 ? 'u' : `u_{${j + 1}}`, kind: 'coset', elt: null, M: u.M }));
    const gens = G.gens.concat(uGens);
    const uNum = (j) => m + 1 + j;
    const evalNice = (w) => w.reduce((M, x) => A.mul(M, x > 0 ? gens[x - 1].M : A.adj(gens[-x - 1].M)), A.one);
    const rels = G.relators.slice();
    for (let j = 0; j < us.length; j++) {
        const U = us[j].M, Ui = A.adj(U);
        for (let k = 1; k <= m; k++) rels.push([uNum(j), k, -uNum(j)].concat(invWord(kNice(A.mul(A.mul(U, G.gens[k - 1].M), Ui)))));
        rels.push([uNum(j), uNum(j)].concat(invWord(kNice(A.mul(U, U)))));
        for (let l = j + 1; l < us.length; l++) {
            const V = us[l].M;
            rels.push([uNum(j), uNum(l), -uNum(j), -uNum(l)].concat(invWord(kNice(A.mul(A.mul(A.mul(U, V), Ui), A.adj(V))))));
        }
    }
    const checked = [];
    for (const r of rels) {
        const w = cyclic(freeReduce(r));
        if (!w.length) continue;
        if (!A.isScalar(evalNice(w))) throw new Error('internal: a relator of the extension is not the identity');
        checked.push(w);
    }
    const T = tietze(gens.length, checked, { maxLen: 0, prefer: new Set(gens.map((_, i) => i + 1)), keepPreferred: true, seconds });
    if (T.keep.length !== gens.length) throw new Error('internal: Tietze removed a generator');
    for (const r of T.relators) if (!A.isScalar(evalNice(r))) throw new Error('internal: a tidied relator is not the identity');
    return {
        ...G, gens, relators: T.relators, evalNice,
        rewriteM: (M) => {
            const { js, k } = split(M);
            const out = freeReduce(js.map(uNum).concat(kNice(k)));
            if (!A.projEq(evalNice(out), M)) throw new Error('internal: rewriting changed the element');
            return out;
        },
    };
}

/**
 * A word in the given generators (matrices `given`, in G's frame) for each generator of G, and for
 * each generator kept by the presentation of Γ on its given generators (kept = [{ given: i | null,
 * M }]: the given g_i, known, and the extra h's). In turn:
 *   • a short word by search (presentation.js findWords), or a known one (g.word);
 *   • equations, solved for an unknown occurring once whose other letters all have words:
 *     x_k = wordInKept(M_k) for each generator x_k of G (its word in the kept generators, through
 *     Reidemeister–Schreier), h = rewriteM(M_h) for each h (its Bass–Serre word in G), back[i] = g_i
 *     (g_i as a word in G), gamma[i] = g_i (g_i in the kept generators), and both sets of relators;
 *   • polishing: wherever a letter occurs once in a short equation (or in the first two kinds), the
 *     word the others give it replaces a longer one, while words get shorter (polishSeconds);
 *   • FlashBeam (beam(given, targets, seeds) → words) for G's generators still without a word or with
 *     one longer than shortWord letters: G's generators lie near o. Once on its own pool, once with
 *     the short words found as seeds in it. A word it finds replaces a longer one, and the equations
 *     and polishing run again, so each word is the shortest of the routes.
 * Each word is multiplied out and checked; null where none is found. ops: { mul, inv, key, one,
 * projEq } (findWords). Returns { gens: words for G's generators, kept: words for the kept generators }.
 */
export function wordsInGiven(G, given, back, ops, { kept = [], wordInKept = null, rewriteM = null, gamma = [], keptRelators = [], beam = null, maxLetters = 100000, polishSeconds = 2, shortWord = 12, maxSeeds = 40 } = {}) {
    const N = G.gens.length, K = kept.length;
    // letters 1 … N: G's generators; N+1 … N+K: the kept generators
    const word = new Array(N + K).fill(null);
    kept.forEach((g, a) => { if (g.given !== null) word[N + a] = [g.given + 1]; });
    G.gens.forEach((g, k) => { if (g.word) word[k] = g.word; });
    const matOf = (x) => (x < N ? G.gens[x].M : kept[x - N].M);
    const unknown = () => word.map((w, x) => (w ? -1 : x)).filter((x) => x >= 0);
    const todo = unknown();
    if (todo.length) {
        const short = findWords(given, todo.map(matOf), ops, { wordElements: 40000, wordSeconds: 1 });
        todo.forEach((x, t) => { if (short[t]) word[x] = short[t]; });
    }
    const shift = (w) => w.map((a) => Math.sign(a) * (N + Math.abs(a)));
    const attempt = (f) => { try { return f(); } catch (e) { return null; } };
    const inKept = G.gens.map((g) => (wordInKept ? attempt(() => shift(wordInKept(g.M))) : null));
    const viaG = kept.map((g) => (g.given === null && rewriteM ? attempt(() => rewriteM(g.M)) : null));
    const eqs = [
        ...inKept.map((w, k) => (w ? { w: [-(k + 1)].concat(w), rhs: [] } : null)).filter(Boolean),
        ...viaG.map((w, a) => (w ? { w: [-(N + a + 1)].concat(w), rhs: [] } : null)).filter(Boolean),
        ...back.map((w, i) => ({ w, rhs: [i + 1] })),
        ...gamma.map((w, i) => ({ w: shift(w), rhs: [i + 1] })),
        ...G.relators.map((w) => ({ w, rhs: [] })),
        ...keptRelators.map((w) => ({ w: shift(w), rhs: [] })),
    ];
    const sub = (w) => freeReduce(w.flatMap((x) => (x > 0 ? word[x - 1] : invWord(word[-x - 1]))));
    const solve = () => {
        for (let progress = true; progress;) {
            progress = false;
            for (const { w, rhs } of eqs) {
                const miss = w.filter((x) => !word[Math.abs(x) - 1]);
                if (miss.length !== 1) continue;
                // w = A·m^{±1}·B = rhs (as elements): m^{±1} = A⁻¹·rhs·B⁻¹
                const at = w.findIndex((x) => !word[Math.abs(x) - 1]);
                const A = w.slice(0, at), B = w.slice(at + 1), m = w[at];
                const val = freeReduce(invWord(sub(A)).concat(rhs, invWord(sub(B))));
                if (val.length > maxLetters) continue;
                word[Math.abs(m) - 1] = m > 0 ? val : invWord(val);
                progress = true;
            }
        }
    };
    // shorter words: the one through the kept generators (for G's) or through G (for h's), and then
    // through every short equation in which a letter occurs once, while some word gets shorter
    const shorter = (x, w) => {
        if (!w || !w.every((y) => word[Math.abs(y) - 1])) return false;
        const v = sub(w);
        if (word[x] && v.length >= word[x].length) return false;
        word[x] = v;
        return true;
    };
    const small = eqs.filter((e) => e.w.length <= 64);
    const polish = () => {
        const until = Date.now() + 1000 * polishSeconds;
        for (let round = 0, better = true; better && round < 8 && Date.now() < until; round++) {
            better = false;
            inKept.forEach((w, k) => { if (shorter(k, w)) better = true; });
            viaG.forEach((w, a) => { if (shorter(N + a, w)) better = true; });
            for (const { w, rhs } of small) {
                if (Date.now() > until) break;
                if (!w.every((y) => word[Math.abs(y) - 1])) continue;
                const count = new Map();
                for (const y of w) count.set(Math.abs(y), (count.get(Math.abs(y)) || 0) + 1);
                const parts = w.map((y) => (y > 0 ? word[y - 1] : invWord(word[-y - 1])));
                for (let at = 0; at < w.length; at++) {
                    const m = w[at], x = Math.abs(m) - 1;
                    if (count.get(x + 1) !== 1 || (x >= N && kept[x - N].given !== null)) continue;
                    // w = A·m^{±1}·B = rhs: m^{±1} = A⁻¹·rhs·B⁻¹
                    const val = freeReduce(invWord(freeReduce(parts.slice(0, at).flat())).concat(rhs, invWord(freeReduce(parts.slice(at + 1).flat()))));
                    const v = m > 0 ? val : invWord(val);
                    if (v.length < word[x].length) { word[x] = v; parts[at] = m > 0 ? v : invWord(v); better = true; }
                }
            }
        }
    };
    solve();
    polish();
    // FlashBeam for G's generators without a word or with a long one: first on its own pool (the
    // given generators, the flash and the targets it finds), then for those still missing or long with
    // the short words as seeds too (shorter words on small groups come from the first, on large
    // ones from the second)
    for (const seeded of beam ? [false, true] : []) {
        const targets = G.gens.map((_, k) => k).filter((k) => !word[k] || word[k].length > shortWord);
        if (!targets.length) break;
        const seeds = !seeded ? [] : word.map((w, x) => ({ w, x })).filter(({ w }) => w && w.length && w.length <= shortWord)
            .sort((a, b) => a.w.length - b.w.length).slice(0, maxSeeds).map(({ w, x }) => ({ M: matOf(x), word: w }));
        const found = beam(given, targets.map(matOf), seeds);
        let any = false;
        targets.forEach((x, t) => { if (found[t] && (!word[x] || found[t].length < word[x].length)) { word[x] = found[t]; any = true; } });
        if (any) { solve(); polish(); }
    }
    const evalGiven = (w) => w.reduce((M, x) => ops.mul(M, x > 0 ? given[x - 1] : ops.inv(given[-x - 1])), ops.one);
    word.forEach((w, x) => {
        if (w && !ops.projEq(evalGiven(w), matOf(x))) throw new Error('internal: a word for a generator of the graph of groups is wrong');
    });
    return { gens: word.slice(0, N), kept: word.slice(N) };
}

/**
 * A presentation on generators 1 … K (relators; kept[a].given: the given generator it is, or null;
 * gamma[i]: the given g_i as a word in them) as one on the given generators, from words in them for
 * the others (words[a], ±(i+1)). The given generators not kept come back as generators K+1 … K+D
 * (dropped: their indices) with the relators g_i⁻¹·gamma[i]; each h⁻¹·words[h] is a relator that
 * removes h; then the usual tidying. Returns { keep (numbers 1 … K+D), relators, express(a), dropped }
 * as presentation.js tietze, or null when some h has no word or the relators would pass maxTotal letters.
 */
export function eliminateByWords(K, relators, kept, gamma, words, { maxTotal = 200000, seconds = 3 } = {}) {
    const hs = kept.map((g, a) => (g.given === null ? a : -1)).filter((a) => a >= 0);
    if (!hs.length || hs.some((a) => !words[a])) return null;
    const keptAt = new Map(kept.map((g, a) => [g.given, a + 1]).filter(([i]) => i !== null));
    const dropped = gamma.map((_, i) => i).filter((i) => !keptAt.has(i));
    dropped.forEach((i, j) => keptAt.set(i, K + 1 + j));
    const inGens = (w) => w.map((x) => Math.sign(x) * keptAt.get(Math.abs(x) - 1));
    const extra = hs.map((a) => [-(a + 1)].concat(inGens(words[a])))
        .concat(dropped.map((i, j) => [-(K + 1 + j)].concat(gamma[i])));
    // an upper bound for the letters once each h is replaced by its word
    const len = new Map(hs.map((a) => [a + 1, words[a].length]));
    let total = 0;
    for (const r of relators.concat(extra.slice(hs.length))) for (const x of r) total += len.get(Math.abs(x)) ?? 1;
    if (total > maxTotal) return null;
    const given = new Set([...keptAt.values()]);
    const longest = Math.max(...extra.map((r) => r.length));
    const T1 = tietze(K + dropped.length, relators.concat(extra), { maxLen: longest, growth: Infinity, slack: Infinity, prefer: given, keepPreferred: true, seconds });
    if (T1.keep.some((a) => !given.has(a))) return null;
    const T2 = tietze(T1.keep.length, T1.relators, { maxLen: 40, growth: 1.5, slack: 100, seconds: 2 });
    return {
        keep: T2.keep.map((b) => T1.keep[b - 1]),
        relators: T2.relators,
        express: (a) => freeReduce(T1.express(a).flatMap((b) => (b > 0 ? T2.express(b) : invWord(T2.express(-b))))),
        dropped,
    };
}

/**
 * The presentation on the given generators P (sarithPresentation.js presentationOverQ or
 * bianchiPresentation.js presentationOverBianchi, with P._core.restate) when it keeps extra generators
 * h: again, with the h's words in the given generators from the graph of groups (G.keptWords), kept
 * when it has fewer h's. Marks P.hFrom = 'graph'.
 */
export function restateFromGraph(P, G) {
    if (!P || P.onGiven !== false || !P._core || !P._core.restate || !G || G.error || !G.keptWords) return;
    const hs = (Q) => Q.gens.filter((g) => g.given === null).length;
    if (!G.keptWords.some((w, a) => w && P.gens[a].given === null)) return;
    let Q;
    try { Q = P._core.restate(G.keptWords); } catch (e) { return; }
    if (!Q || hs(Q) >= hs(P)) return;
    Object.assign(P, Q, { hFrom: 'graph' });
}

/** The nested description of graphOfGroups, serializable: hMat(word) gives each vertex's conjugator. */
export function stripTree(node, hMat) {
    if (node.leaf) return { leaf: true, index: node.index, gens: node.gens };
    return {
        leaf: false, prime: node.prime, valence: node.valence, index: node.index,
        vertices: node.vertices.map((v) => ({ index: v.index, h: hMat(v.hWord), sub: stripTree(v.sub, hMat) })),
        edges: node.edges,
    };
}
