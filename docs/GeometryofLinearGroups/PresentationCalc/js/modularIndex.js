/**
 * modularIndex.js — the exact index of a subgroup of PGL₂(ℤ) given by
 * generators, by coset enumeration.
 *
 * PGL₂(ℤ) is the reflection group of the (2, 3, ∞) triangle,
 *     ⟨a, b, c | a², b², c², (ab)², (bc)³⟩,
 * with a = diag(−1, 1) (z ↦ −z̄), b = (0 1; 1 0) (z ↦ 1/z̄) and
 * c = (−1 1; 0 1) (z ↦ 1 − z̄). Then T = ca = (1 1; 0 1) and S = ab = (0 −1; 1 0).
 *
 * Each generator is written in a, b, c by the Euclidean algorithm on its
 * first column, and the word is multiplied out again and compared with the
 * matrix (projectively) before it is used. Todd–Coxeter (HLT with
 * coincidences, as in SO3DecisionAlgorithm/algorithm/arithmetic/cosets.py)
 * then enumerates the cosets. A table that closes is re-verified: every entry
 * defined, the relators closing at every coset, the generators fixing coset 1,
 * the coset graph connected. Then [PGL₂(ℤ) : H] is exactly its size. A
 * table that hits its limits claims nothing.
 */

const babs = (x) => (x < 0n ? -x : x);
const big = (x) => (typeof x === 'bigint' ? x : BigInt(x));

// letters 0, 1, 2 = a, b, c (involutions)
const GEN = [[-1n, 0n, 0n, 1n], [0n, 1n, 1n, 0n], [-1n, 1n, 0n, 1n]];
const RELATORS = [[0, 1, 0, 1], [1, 2, 1, 2, 1, 2]];

const mul = (A, B) => [A[0] * B[0] + A[1] * B[2], A[0] * B[1] + A[1] * B[3], A[2] * B[0] + A[3] * B[2], A[2] * B[1] + A[3] * B[3]];
/** Equal in PGL₂: proportional (here: equal up to sign, both having det ±1). */
const projEq = (A, B) => {
    for (const s of [1n, -1n]) if (A.every((x, i) => x === s * B[i])) return true;
    return false;
};

/** The word in a, b, c (letters 0, 1, 2) for M ∈ GL₂(ℤ), read projectively. Throws if det M ≠ ±1. */
export function coxeterWord(M0) {
    let M = M0.map(big);
    const det = M[0] * M[3] - M[1] * M[2];
    if (det !== 1n && det !== -1n) throw new Error('not in GL₂(ℤ)');
    const word = [];
    if (det === -1n) { word.push(0); M = mul(GEN[0], M); }            // M = a·(aM)
    // now det M = 1: M = T^{k₁} S T^{k₂} S … T^{n}
    const T = (k) => {
        // T = ca, T⁻¹ = ac
        const out = [];
        const n = babs(k);
        for (let i = 0n; i < n; i++) out.push(...(k > 0n ? [2, 0] : [0, 2]));
        return out;
    };
    // |c| strictly decreases (a Euclidean step), so this ends after O(log |c|) steps
    let guard = 0, last = null;
    while (M[2] !== 0n) {
        const c = babs(M[2]);
        if (++guard > 4 && last !== null && c >= last) throw new Error('coxeterWord: no progress');
        last = c;
        const [p, , r] = M;
        // k with |p − k r| < |r|: floor division towards −∞
        let k = p / r;
        if ((p % r !== 0n) && ((p < 0n) !== (r < 0n))) k -= 1n;
        if (k !== 0n) {
            word.push(...T(k));
            M = [M[0] - k * M[2], M[1] - k * M[3], M[2], M[3]];         // T^{−k} M
        }
        // M = S·(S⁻¹M), S⁻¹ ≡ S = ab
        word.push(0, 1);
        M = [-M[2], -M[3], M[0], M[1]];                                    // S M ≡ S⁻¹ M projectively
    }
    // upper triangular with det 1: ±(1 n; 0 1)
    const n = M[0] === 1n ? M[1] : -M[1];
    word.push(...T(n));
    // the check
    let W = [1n, 0n, 0n, 1n];
    for (const x of word) W = mul(W, GEN[x]);
    if (!projEq(W, M0.map(big))) throw new Error('coxeterWord: the word does not give the matrix');
    return word;
}

/** Freely reduce a word in involutions (xx = 1). */
function reduceInv(w) {
    const out = [];
    for (const x of w) { if (out.length && out[out.length - 1] === x) out.pop(); else out.push(x); }
    return out;
}

/**
 * Todd–Coxeter for H = ⟨words⟩ in ⟨a, b, c | a², b², c², (ab)², (bc)³⟩.
 * Returns { index, table, defined } or { limit: 'cosets' | 'time' }.
 */
export function enumerateCosets(subgroupWords, opts = {}) {
    return enumerateInvolutions(3, RELATORS, subgroupWords, opts);
}

/**
 * Todd–Coxeter (HLT with coincidences) for a group generated by W involutions
 * (letters 0 … W−1, each its own inverse) with the given relators.
 */
export function enumerateInvolutions(W, relators, subgroupWords, opts = {}) {
    // Felsch first (it keeps the table near the index); HLT if Felsch runs out
    if (opts.strategy !== 'hlt') {
        const f = enumerateFelsch(W, relators, subgroupWords, opts);
        // HLT (arrays of rows) only as a modest second try
        if (f.index || opts.strategy === 'felsch' || (opts.maxCosets ?? 200000) > 3000000) return f;
    }
    try {
        return enumerateHLT(W, relators, subgroupWords, opts);
    } catch (e) {
        if (e instanceof RangeError) return { limit: 'memory' };
        throw e;
    }
}

/**
 * Felsch's strategy for involutive generators: define the first undefined
 * entry, then push every deduction through every cyclic conjugate of every
 * relator (and its inverse) before defining the next. Coincidences are
 * processed as in HLT. The final table is verified in the same way.
 */
export function enumerateFelsch(W, relators, subgroupWords, { maxCosets = 200000, seconds = 5 } = {}) {
    const deadline = Date.now() + 1000 * seconds;
    let cap = 1024;
    let table = new Int32Array(cap * W).fill(-1);
    let parent = new Int32Array(cap);
    let n = 1;
    parent[0] = 0;
    const find = (c) => { while (parent[c] !== c) { parent[c] = parent[parent[c]]; c = parent[c]; } return c; };
    class Limit extends Error { }
    const grow = () => {
        const cap2 = Math.min(cap * 2, maxCosets + 1);
        if (cap2 <= cap) throw new Limit('cosets');
        const t = new Int32Array(cap2 * W).fill(-1); t.set(table); table = t;
        const pa = new Int32Array(cap2); pa.set(parent); parent = pa;
        cap = cap2;
    };
    const ded = [];
    const set = (c, x, d) => { table[c * W + x] = d; table[d * W + x] = c; ded.push(c * W + x); };
    const define = (c, x) => {
        if (n >= maxCosets) throw new Limit('cosets');
        if (n >= cap) grow();
        const d = n++;
        parent[d] = d;
        for (let y = 0; y < W; y++) table[d * W + y] = -1;
        set(c, x, d);
        return d;
    };
    const coincidence = (a, b) => {
        const queue = [];
        const merge = (u, v) => {
            u = find(u); v = find(v);
            if (u === v) return;
            if (v < u) [u, v] = [v, u];
            parent[v] = u;
            queue.push(v);
        };
        merge(a, b);
        while (queue.length) {
            const g = queue.shift();
            for (let x = 0; x < W; x++) {
                const d = table[g * W + x];
                if (d < 0) continue;
                table[d * W + x] = -1;
                const u = find(g), v = find(d);
                const tu = table[u * W + x], tv = table[v * W + x];
                if (tu >= 0) merge(v, tu);
                else if (tv >= 0) merge(u, tv);
                else set(u, x, v);
            }
        }
    };
    // every cyclic conjugate of every relator and of its inverse, by first letter
    const rots = Array.from({ length: W }, () => []);
    const seenRot = new Set();
    for (const r0 of relators) for (const r of [r0, r0.slice().reverse()]) for (let k = 0; k < r.length; k++) {
        const rr = r.slice(k).concat(r.slice(0, k));
        const key = rr.join(',');
        if (seenRot.has(key)) continue;
        seenRot.add(key);
        rots[rr[0]].push(rr);
    }
    // scan a cyclic word from coset a; deduce at a single gap, merge on a mismatch (no definitions)
    const scan = (a, word) => {
        const m = word.length;
        let f = a, i = 0, b = a, j = m - 1;
        while (i <= j) { const t = table[f * W + word[i]]; if (t < 0) break; f = t; i++; }
        if (i > j) { if (f !== a) coincidence(f, a); return; }
        while (j >= i) { const t = table[b * W + word[j]]; if (t < 0) break; b = t; j--; }
        if (j < i) { coincidence(f, b); return; }
        if (i === j) set(f, word[i], b);
    };
    const process = () => {
        while (ded.length) {
            const e = ded.pop();
            const c = Math.floor(e / W), x = e - c * W;
            if (parent[c] !== c) continue;
            for (const rr of rots[x]) { if (parent[c] !== c) break; scan(c, rr); }
        }
    };
    // the subgroup words at coset 0, with definitions (as HLT's scan-and-fill)
    const scanAndFill = (a, word) => {
        for (;;) {
            const m = word.length;
            let f = a, i = 0, b = a, j = m - 1;
            while (i <= j) { const t = table[f * W + word[i]]; if (t < 0) break; f = t; i++; }
            if (i > j) { if (f !== a) coincidence(f, a); process(); return; }
            while (j >= i) { const t = table[b * W + word[j]]; if (t < 0) break; b = t; j--; }
            if (j < i) { coincidence(f, b); process(); return; }
            if (i === j) { set(f, word[i], b); process(); return; }
            define(f, word[i]);
            process();
            a = find(a);
        }
    };
    const words = subgroupWords.map(reduceInv).filter((w) => w.length);
    try {
        for (const w of words) scanAndFill(find(0), w);
        let steps = 0;
        for (let c = 0; c < n; c++) {
            if (parent[c] !== c) continue;
            for (let x = 0; x < W; x++) {
                if (parent[c] !== c) break;
                if (table[c * W + x] < 0) { define(c, x); process(); }
            }
            if (++steps % 256 === 0 && Date.now() > deadline) throw new Limit('time');
        }
    } catch (e) {
        if (e instanceof Limit) return { limit: e.message, defined: n };
        throw e;
    }
    const live = [];
    for (let c = 0; c < n; c++) if (parent[c] === c) live.push(c);
    const num = new Map(live.map((c, i) => [c, i]));
    const compact = live.map((c) => Array.from({ length: W }, (_, x) => num.get(find(table[c * W + x]))));
    const bad = verifyTable(compact, words, relators, W);
    if (bad) return { limit: `verification: ${bad}`, defined: n };
    return { index: compact.length, table: compact, defined: n };
}

export function enumerateHLT(W, relators, subgroupWords, { maxCosets = 200000, seconds = 5 } = {}) {
    const RELATORS = relators;
    const deadline = Date.now() + 1000 * seconds;
    const table = [new Array(W).fill(-1)];
    const parent = [0];
    const find = (c) => { while (parent[c] !== c) { parent[c] = parent[parent[c]]; c = parent[c]; } return c; };
    class Limit extends Error { }
    const define = (c, x) => {
        if (table.length >= maxCosets) throw new Limit('cosets');
        const d = table.length;
        table.push(new Array(W).fill(-1));
        parent.push(d);
        table[c][x] = d;
        table[d][x] = c;
        return d;
    };
    const coincidence = (a, b) => {
        const queue = [];
        const merge = (u, v) => {
            u = find(u); v = find(v);
            if (u === v) return;
            if (v < u) [u, v] = [v, u];
            parent[v] = u;
            queue.push(v);
        };
        merge(a, b);
        while (queue.length) {
            const g = queue.shift();
            const row = table[g];
            for (let x = 0; x < W; x++) {
                const d = row[x];
                if (d < 0) continue;
                table[d][x] = -1;
                const u = find(g), v = find(d);
                if (table[u][x] >= 0) merge(v, table[u][x]);
                else if (table[v][x] >= 0) merge(u, table[v][x]);
                else { table[u][x] = v; table[v][x] = u; }
            }
        }
    };
    const scanAndFill = (a, word) => {
        const n = word.length;
        let f = a, i = 0, b = a, j = n - 1;
        for (;;) {
            while (i <= j && table[f][word[i]] >= 0) { f = table[f][word[i]]; i++; }
            if (i > j) { if (f !== a) coincidence(f, a); return; }
            while (j >= i && table[b][word[j]] >= 0) { b = table[b][word[j]]; j--; }
            if (j < i) { coincidence(f, b); return; }
            if (i === j) { table[f][word[i]] = b; table[b][word[i]] = f; return; }
            define(f, word[i]);
        }
    };
    const words = subgroupWords.map(reduceInv).filter((w) => w.length);
    try {
        for (const w of words) scanAndFill(0, w);
        let c = 0, steps = 0;
        while (c < table.length) {
            if (parent[c] === c) {
                for (const r of RELATORS) { if (parent[c] !== c) break; scanAndFill(c, r); }
                // the subgroup words are relators of the coset action at coset 0 only; HLT scans them at 0
                if (c === 0) for (const w of words) { if (parent[0] !== 0) break; scanAndFill(0, w); }
                if (parent[c] === c) for (let x = 0; x < W; x++) if (table[c][x] < 0) define(c, x);
            }
            c++;
            if (++steps % 256 === 0 && Date.now() > deadline) throw new Limit('time');
        }
    } catch (e) {
        if (e instanceof Limit) return { limit: e.message, defined: table.length };
        throw e;
    }
    const live = [];
    for (let c = 0; c < table.length; c++) if (parent[c] === c) live.push(c);
    const num = new Map(live.map((c, i) => [c, i]));
    const compact = live.map((c) => table[c].map((d) => num.get(find(d))));
    const bad = verifyTable(compact, words, RELATORS, W);
    if (bad) return { limit: `verification: ${bad}`, defined: table.length };
    return { index: compact.length, table: compact, defined: table.length };
}

function verifyTable(T, words, RELATORS, W) {
    for (const row of T) if (row.some((d) => d === undefined || d < 0)) return 'undefined entry';
    for (let c = 0; c < T.length; c++) for (let x = 0; x < W; x++) if (T[T[c][x]][x] !== c) return 'a generator is not an involution on cosets';
    for (const r of RELATORS) for (let c = 0; c < T.length; c++) {
        let d = c;
        for (const x of r) d = T[d][x];
        if (d !== c) return 'a relator does not close';
    }
    for (const w of words) {
        let d = 0;
        for (const x of w) d = T[d][x];
        if (d !== 0) return 'a subgroup generator does not fix coset 1';
    }
    const seen = new Set([0]), stack = [0];
    while (stack.length) { const c = stack.pop(); for (const d of T[c]) if (!seen.has(d)) { seen.add(d); stack.push(d); } }
    if (seen.size !== T.length) return 'the coset graph is not connected';
    return null;
}

/**
 * [PGL₂(ℤ) : ⟨mats⟩] for integer matrices of determinant ±1 (projectively).
 * Returns { index, words } or { limit } (or { error } if some matrix is not in GL₂(ℤ)).
 */
export function indexInPGL2Z(mats, opts = {}) {
    let words;
    try { words = mats.map(coxeterWord); } catch (e) { return { error: e.message }; }
    const r = enumerateCosets(words, opts);
    return { ...r, words };
}
