// multiquad.js — exact arithmetic in a multiquadratic field K = ℚ(√m₁, …, √m_k).
//
// The spin images of the reflection groups, and the gluing maps of hybrids,
// have entries in such fields: square roots of a few integers. An element is
// the vector of its rational coordinates c_S on the basis √m_S = ∏_{i∈S} √m_i
// (S ⊆ {1, …, k}, a bit mask), and √m_S · √m_T = (∏_{i∈S∩T} m_i) · √m_{S△T}.
//
// The embedding K → ℂ used throughout takes every √m_i to its principal value
// (positive, or i times positive). θ = Σ √m_i is a primitive element (the
// √m_S are linearly independent, so the 2^k sign changes of θ are distinct);
// asPoly writes an element as a polynomial in θ, which is how poincare and the
// Presentation Calculator take a number field: "w root of P(w)".

import { frac, fadd, fsub, fmul, fdiv } from './linalg.js';

const F0 = frac(0n), F1 = frac(1n);
const isZ = (a) => a.n === 0n;
const absB = (x) => (x < 0n ? -x : x);

/** Prime factorization of |n| (BigInt, small): Map(prime → exponent). */
function factorB(n) {
    n = absB(n);
    const out = new Map();
    for (let p = 2n; p * p <= n; p += (p === 2n ? 1n : 2n)) {
        while (n % p === 0n) { out.set(p, (out.get(p) || 0) + 1); n /= p; }
    }
    if (n > 1n) out.set(n, (out.get(n) || 0) + 1);
    return out;
}

/** n = s²·r with r squarefree (sign kept). */
export function squarefreePart(n) {
    n = BigInt(n);
    if (n === 0n) throw new Error('0 has no square root in a field of this kind');
    let r = n < 0n ? -1n : 1n, s = 1n;
    for (const [p, e] of factorB(n)) {
        if (e % 2) r *= p;
        s *= p ** BigInt(e >> 1);
    }
    return { r, s };
}

/** The prime support of a squarefree integer, with −1 as a prime. */
const supportOf = (r) => {
    const set = new Set();
    if (r < 0n) set.add(-1n);
    for (const [p] of factorB(r)) set.add(p);
    return set;
};
const symDiff = (a, b) => { const c = new Set(a); for (const x of b) { if (c.has(x)) c.delete(x); else c.add(x); } return c; };
const maxKey = (s) => { let m = null; for (const x of s) if (m === null || x > m) m = x; return m; };

const cmul = (a, b) => ({ re: a.re * b.re - a.im * b.im, im: a.re * b.im + a.im * b.re });
const popcount = (x) => { let c = 0; while (x) { c += x & 1; x >>= 1; } return c; };

export class MultiQuad {
    /**
     * radicands: integers (or {n, d} fractions) whose square roots K must contain.
     * K is generated by a maximal independent subset of them, mod squares.
     */
    constructor(radicands = []) {
        this.m = [];             // squarefree basis radicands (BigInt)
        this.echelon = [];       // [{ set, mask, pivot }]
        for (const x of radicands) this.adjoin(x);
        this.freeze();
    }

    /** Make sure √x ∈ K (x an integer or a fraction); returns nothing. */
    adjoin(x) {
        const r = this.reduceRadicand(x);
        if (r.r === 1n) return;
        const { rest, mask } = this.express(r.r);
        if (rest.size === 0) return;
        const k = this.m.length;
        this.m.push(r.r);
        const row = { set: rest, mask: mask ^ (1 << k), pivot: maxKey(rest) };
        this.echelon.push(row);
        this.echelon.sort((a, b) => (a.pivot > b.pivot ? -1 : a.pivot < b.pivot ? 1 : 0));
    }

    reduceRadicand(x) {
        if (typeof x === 'object' && x !== null && 'n' in x) {
            // √(n/d) = √(n·d)/d
            return squarefreePart(BigInt(x.n) * BigInt(x.d));
        }
        return squarefreePart(BigInt(x));
    }

    /** Reduce the squarefree r against the basis: r ≡ ∏_{mask} m_i · (rest) mod squares. */
    express(r) {
        let cur = supportOf(r), mask = 0;
        for (const row of this.echelon) {
            if (cur.has(row.pivot)) { cur = symDiff(cur, row.set); mask ^= row.mask; }
        }
        return { rest: cur, mask };
    }

    freeze() {
        this.k = this.m.length;
        this.size = 1 << this.k;
        this.degree = this.size;
        this.vals = this.m.map((m) => (m > 0n ? { re: Math.sqrt(Number(m)), im: 0 } : { re: 0, im: Math.sqrt(Number(-m)) }));
        // basis values √m_S and the multiplication constants ∏_{S∩T} m_i
        this.basisVal = [];
        for (let S = 0; S < this.size; S++) {
            let v = { re: 1, im: 0 };
            for (let i = 0; i < this.k; i++) if (S & (1 << i)) v = cmul(v, this.vals[i]);
            this.basisVal.push(v);
        }
        this.mprod = new Map();
        this._power = null;
    }

    coef(S, T) {
        const key = S * this.size + T;
        let c = this.mprod.get(key);
        if (c === undefined) {
            c = 1n;
            const both = S & T;
            for (let i = 0; i < this.k; i++) if (both & (1 << i)) c *= this.m[i];
            this.mprod.set(key, c);
        }
        return c;
    }

    // ---------------- elements ----------------

    zero() { return new Array(this.size).fill(F0); }
    one() { const z = this.zero(); z[0] = F1; return z; }
    rat(q) { const z = this.zero(); z[0] = typeof q === 'object' && q !== null && 'n' in q ? frac(q.n, q.d) : frac(BigInt(q)); return z; }
    isZero(a) { return a.every(isZ); }
    isRational(a) { return a.every((c, S) => S === 0 || isZ(c)); }
    eq(a, b) { return a.every((c, S) => c.n === b[S].n && c.d === b[S].d); }
    add(a, b) { return a.map((c, S) => fadd(c, b[S])); }
    sub(a, b) { return a.map((c, S) => fsub(c, b[S])); }
    neg(a) { return a.map((c) => frac(-c.n, c.d)); }
    scale(a, q) { const f = typeof q === 'object' && 'n' in q ? q : frac(BigInt(q)); return a.map((c) => fmul(c, f)); }
    mul(a, b) {
        const out = this.zero();
        for (let S = 0; S < this.size; S++) {
            if (isZ(a[S])) continue;
            for (let T = 0; T < this.size; T++) {
                if (isZ(b[T])) continue;
                const U = S ^ T;
                out[U] = fadd(out[U], fmul(fmul(a[S], b[T]), frac(this.coef(S, T))));
            }
        }
        return out;
    }
    /** The matrix of multiplication by a, on the basis √m_S (columns = images). */
    mulMatrix(a) {
        const M = Array.from({ length: this.size }, () => new Array(this.size).fill(F0));
        for (let T = 0; T < this.size; T++) {
            const e = this.zero(); e[T] = F1;
            const p = this.mul(a, e);
            for (let S = 0; S < this.size; S++) M[S][T] = p[S];
        }
        return M;
    }
    inv(a) {
        if (this.isZero(a)) throw new Error('division by zero');
        if (this.isRational(a)) return this.rat(fdiv(F1, a[0]));
        const x = solveFrac(this.mulMatrix(a), this.one());
        if (!x) throw new Error('division by zero');
        return x;
    }
    div(a, b) { return this.mul(a, this.inv(b)); }

    /** The element √x with the principal value (x an integer or {n, d}); x must lie in K's radicand group. */
    sqrt(x) {
        const isFr = typeof x === 'object' && x !== null && 'n' in x;
        const num = isFr ? BigInt(x.n) : BigInt(x), den = isFr ? BigInt(x.d) : 1n;
        if (num === 0n) return this.zero();
        const { r, s } = squarefreePart(num * den);          // √(num/den) = s·√r / den
        const z = this.zero();
        if (r === 1n) { z[0] = frac(s, den); return z; }
        const { rest, mask } = this.express(r);
        if (rest.size) throw new Error(`√${r} is not in the field`);
        // r = λ²·P for P = ∏_{mask} m_i: r·P is a square, λ = √(rP)/|P|
        let P = 1n;
        for (let i = 0; i < this.k; i++) if (mask & (1 << i)) P *= this.m[i];
        const t = squarefreePart(r * P);
        if (t.r !== 1n) throw new Error('internal: radicand reduction');
        let lam = frac(s * t.s, den * (P < 0n ? -P : P));
        // sign: match the principal value of √(num/den)
        const v = this.basisVal[mask];
        const want = num * den > 0n ? { re: 1, im: 0 } : { re: 0, im: 1 };
        if (v.re * want.re + v.im * want.im < 0) lam = frac(-lam.n, lam.d);
        z[mask] = lam;
        return z;
    }

    /** Numeric value under the principal embedding. */
    num(a) {
        let re = 0, im = 0;
        for (let S = 0; S < this.size; S++) {
            if (isZ(a[S])) continue;
            const c = Number(a[S].n) / Number(a[S].d);
            re += c * this.basisVal[S].re; im += c * this.basisVal[S].im;
        }
        return { re, im };
    }

    // ---------------- the primitive element ----------------

    /**
     * θ: an algebraic integer generating K with small discriminant (so ℤ[θ] has
     * small index and the coordinates of matrix entries stay small). For k ≤ 3
     * the coefficients c_S ∈ {0, ±½, ±1} are searched (numerically, through
     * the 2^k conjugates); otherwise θ = Σ √m_i.
     */
    theta() {
        if (this._theta) return this._theta;
        const z = this.zero();
        for (let i = 0; i < this.k; i++) z[1 << i] = F1;
        this._theta = z;
        if (this.k === 0 || this.k > 3) return z;
        const n = this.size;
        const chars = [];                          // χ_ε(S) for each sign pattern ε
        for (let e = 0; e < n; e++) chars.push(Array.from({ length: n }, (_, S) => (popcount(S & e) % 2 ? -1 : 1)));
        const C = [0, 1, -1, 0.5, -0.5];
        const c = new Array(n).fill(0);
        let best = null;
        const conj = new Array(n);
        const visit = () => {
            for (let e = 0; e < n; e++) {
                let re = 0, im = 0;
                for (let S = 1; S < n; S++) if (c[S]) { const s = c[S] * chars[e][S]; re += s * this.basisVal[S].re; im += s * this.basisVal[S].im; }
                conj[e] = { re, im };
            }
            let logDisc = 0;
            for (let a = 0; a < n; a++) for (let b = a + 1; b < n; b++) {
                const d = Math.hypot(conj[a].re - conj[b].re, conj[a].im - conj[b].im);
                if (d < 1e-7) return;
                logDisc += Math.log(d);
            }
            if (best && logDisc > best.logDisc + 1e-9) return;
            // ∏ (x − θ_e): integral?
            let p = [{ re: 1, im: 0 }];
            for (const z0 of conj) {
                const q = new Array(p.length + 1).fill(null).map(() => ({ re: 0, im: 0 }));
                for (let i = 0; i < p.length; i++) {
                    q[i + 1].re += p[i].re; q[i + 1].im += p[i].im;
                    q[i].re -= p[i].re * z0.re - p[i].im * z0.im; q[i].im -= p[i].re * z0.im + p[i].im * z0.re;
                }
                p = q;
            }
            let height = 0;
            for (const x of p) { if (Math.abs(x.re - Math.round(x.re)) > 1e-6 * Math.max(1, Math.abs(x.re)) || Math.abs(x.im) > 1e-6 * Math.max(1, Math.abs(x.re))) return; height = Math.max(height, Math.abs(x.re)); }
            if (height > 1e12) return;
            if (!best || logDisc < best.logDisc - 1e-9 || height < best.height) best = { logDisc, height, c: c.slice() };
        };
        const rec = (S) => {
            if (S === n) { visit(); return; }
            for (const x of C) { c[S] = x; rec(S + 1); }
            c[S] = 0;
        };
        rec(1);
        if (best) {
            this._theta = best.c.map((x) => (x === 0 ? F0 : x === 1 ? F1 : x === -1 ? frac(-1n) : x === 0.5 ? frac(1n, 2n) : frac(-1n, 2n)));
        }
        return this._theta;
    }

    /** Minimal polynomial of θ (BigInt coefficients, low → high, monic), and the power-basis inverse. */
    powerBasis() {
        if (this._power) return this._power;
        const n = this.size;
        const th = this.theta();
        const pows = [this.one()];
        for (let j = 1; j <= n; j++) pows.push(this.mul(pows[j - 1], th));
        // columns θ^0 … θ^{n−1}
        const B = Array.from({ length: n }, (_, S) => Array.from({ length: n }, (_, j) => pows[j][S]));
        const Binv = invertFrac(B);
        if (!Binv) throw new Error('internal: θ is not primitive');
        // θ^n in the power basis gives the minimal polynomial: θ^n = Σ c_j θ^j
        const c = matVecFrac(Binv, pows[n]);
        const poly = c.map((x) => frac(-x.n, x.d));
        poly.push(F1);
        if (poly.some((x) => x.d !== 1n)) throw new Error('internal: minimal polynomial is not integral');
        const thetaVal = this.num(th);
        this._power = { Binv, poly: poly.map((x) => x.n), thetaVal };
        return this._power;
    }

    /** a as a polynomial in θ: rational coefficients, low → high. */
    asPoly(a) {
        if (this.k === 0) return [a[0]];
        const { Binv } = this.powerBasis();
        return matVecFrac(Binv, a);
    }

    /** The minimal polynomial of θ as text in the variable w (LaTeX, for poincare's "w root of"). */
    polyTex(name = 'w') {
        if (this.k === 0) return name;
        const { poly } = this.powerBasis();
        return polyToTex(poly.map((x) => frac(x)), name);
    }

    /** A readable name: ℚ(√2, √−5, i). */
    tex() {
        if (!this.k) return '\\mathbb Q';
        return `\\mathbb Q(${this.m.map((m) => (m === -1n ? 'i' : `\\sqrt{${m}}`)).join(',\\,')})`;
    }

    /** a written on the basis √m_S, as LaTeX (for display). */
    elemTex(a) {
        const parts = [];
        for (let S = 0; S < this.size; S++) {
            const c = a[S];
            if (isZ(c)) continue;
            let rad = 1n, im = false;
            for (let i = 0; i < this.k; i++) if (S & (1 << i)) rad *= this.m[i];
            if (rad < 0n) { im = true; rad = -rad; }
            const radTex = (rad === 1n ? '' : `\\sqrt{${rad}}`) + (im ? 'i' : '');
            parts.push(termTex(c, radTex, parts.length === 0));
        }
        return parts.length ? parts.join('') : '0';
    }
}

// ---------------- text ----------------

function fracTex(c) {
    const n = absB(c.n);
    return c.d === 1n ? `${n}` : `\\tfrac{${n}}{${c.d}}`;
}

/** One term c·x with sign, for x a monomial in LaTeX ('' for the constant term). */
function termTex(c, x, first) {
    const neg = c.n < 0n;
    const one = absB(c.n) === 1n && c.d === 1n;
    const body = x ? (one ? x : `${fracTex(c)}${x}`) : fracTex(c);
    if (first) return (neg ? '-' : '') + body;
    return (neg ? ' - ' : ' + ') + body;
}

/** Σ c_j w^j as LaTeX (high → low), with c_j fractions. */
export function polyToTex(coeffs, name = 'w') {
    const parts = [];
    for (let j = coeffs.length - 1; j >= 0; j--) {
        const c = coeffs[j];
        if (isZ(c)) continue;
        const x = j === 0 ? '' : j === 1 ? name : `${name}^{${j}}`;
        parts.push(termTex(c, x, parts.length === 0));
    }
    return parts.length ? parts.join('') : '0';
}

// ---------------- exact linear algebra over ℚ (fractions) ----------------

function matVecFrac(M, v) {
    return M.map((r) => r.reduce((s, x, j) => fadd(s, fmul(x, v[j])), F0));
}

export function invertFrac(M0) {
    const n = M0.length;
    const A = M0.map((r, i) => [...r.map((x) => frac(x.n, x.d)), ...Array.from({ length: n }, (_, j) => (i === j ? F1 : F0))]);
    for (let c = 0; c < n; c++) {
        let p = c;
        while (p < n && isZ(A[p][c])) p++;
        if (p === n) return null;
        [A[c], A[p]] = [A[p], A[c]];
        const piv = A[c][c];
        A[c] = A[c].map((x) => fdiv(x, piv));
        for (let i = 0; i < n; i++) {
            if (i === c || isZ(A[i][c])) continue;
            const f = A[i][c];
            A[i] = A[i].map((x, j) => fsub(x, fmul(f, A[c][j])));
        }
    }
    return A.map((r) => r.slice(n));
}

function solveFrac(M, b) {
    const Mi = invertFrac(M);
    return Mi ? matVecFrac(Mi, b) : null;
}

// ---------------- 2 × 2 matrices over K ----------------

export const kmat = {
    mul(K, A, B) {
        return [
            K.add(K.mul(A[0], B[0]), K.mul(A[1], B[2])), K.add(K.mul(A[0], B[1]), K.mul(A[1], B[3])),
            K.add(K.mul(A[2], B[0]), K.mul(A[3], B[2])), K.add(K.mul(A[2], B[1]), K.mul(A[3], B[3])),
        ];
    },
    add(K, A, B) { return A.map((x, i) => K.add(x, B[i])); },
    sub(K, A, B) { return A.map((x, i) => K.sub(x, B[i])); },
    scale(K, A, c) { return A.map((x) => K.mul(x, c)); },
    det(K, A) { return K.sub(K.mul(A[0], A[3]), K.mul(A[1], A[2])); },
    trace(K, A) { return K.add(A[0], A[3]); },
};
