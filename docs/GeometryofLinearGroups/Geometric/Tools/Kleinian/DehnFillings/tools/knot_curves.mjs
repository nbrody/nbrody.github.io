// knot_curves.mjs — turn the census Gauss codes into smooth 3D knots and write js/census.js.
//
// Uses the Knot Energy app's Gauss-code layout (planar map + Tutte embedding,
// over/under lifted to ±0.6) and its Möbius-energy relaxation, which never
// lets strands pass through each other, so the knot type and chirality are
// those of the diagram SnapPy exported. tools/check_curves.py then rebuilds a
// PD code from each curve and checks it against SnapPy (Jones polynomial).
//
// Usage:  node tools/knot_curves.mjs   (after python3 tools/make_census.py)

import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';
import * as THREE from '../../vendor/three/three.module.js';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const KE = path.resolve(HERE, '../../../../../../topology/knotTheory/knotEnergy/js');

const ctx = { THREE, window: {}, console, Math, Float64Array, Int32Array, Uint8Array, Array, Map, Set, Error };
vm.createContext(ctx);
for (const f of ['knots.js', 'physics.js']) vm.runInContext(fs.readFileSync(path.join(KE, f), 'utf8') + '\n;globalThis.KnotChain = typeof KnotChain !== "undefined" ? KnotChain : globalThis.KnotChain;', ctx, { filename: f });
const { KnotLib, } = ctx.window;
const KnotChain = ctx.KnotChain;

const KNOT_LENGTH = 30;
function normalize(pts) {
    const N = pts.length;
    let L = 0;
    const c = new THREE.Vector3();
    for (let i = 0; i < N; i++) { L += pts[i].distanceTo(pts[(i + 1) % N]); c.add(pts[i]); }
    c.multiplyScalar(1 / N);
    return pts.map((p) => p.clone().sub(c).multiplyScalar(KNOT_LENGTH / L));
}

/** Resample a closed polygon to n points equally spaced in arc length. */
function resample(pts, n) {
    const N = pts.length, S = [0];
    for (let i = 0; i < N; i++) S.push(S[i] + pts[i].distanceTo(pts[(i + 1) % N]));
    const L = S[N], out = [];
    let k = 0;
    for (let j = 0; j < n; j++) {
        const s = (j / n) * L;
        while (S[k + 1] < s) k++;
        const t = (s - S[k]) / (S[k + 1] - S[k] || 1);
        out.push(pts[k].clone().lerp(pts[(k + 1) % N], t));
    }
    return out;
}

const census = JSON.parse(fs.readFileSync(path.join(HERE, 'census.json'), 'utf8'));
let cache = {};
try { cache = JSON.parse(fs.readFileSync(path.join(HERE, 'curves.json'), 'utf8')); } catch { /* first run */ }
const fresh = process.argv.includes('--fresh');
for (const e of census) {
    if (!e.gauss) continue;
    const hit = cache[e.id];
    if (!fresh && hit && hit.gauss === e.gauss && hit.curve) { e.curve = hit.curve; console.error(`${e.id.padEnd(8)} cached`); continue; }
    const t0 = Date.now();
    const start = KnotLib.fromGaussCode(e.gauss, 26);
    const chain = new KnotChain(normalize(start));
    chain.params.kRepel = 1.6; chain.params.kSpring = 6.0; chain.params.kTube = 8.0;
    chain.setTubeRadius(0.3);
    const steps = 1600 + 150 * e.crossings;
    for (let s = 0; s < steps; s++) chain.step();
    const pts = resample(chain.points, 40 * e.crossings + 80);
    e.curve = pts.map((p) => [+p.x.toFixed(4), +p.y.toFixed(4), +p.z.toFixed(4)]);
    console.error(`${e.id.padEnd(8)} ${steps} steps, ${pts.length} points, energy ${chain.lastEnergy?.toFixed?.(2)}, ${Date.now() - t0} ms`);
}

const banner = `// census.js — generated by tools/make_census.py and tools/knot_curves.mjs from SnapPy ${'3.3'}.
// Do not edit by hand: rerun the two scripts. Each entry is an ideal triangulation with
// SnapPy's maximal tree, peripheral curves, presentation and reference invariants.
`;
fs.writeFileSync(path.join(HERE, '..', 'js', 'census.js'), banner + 'export const CENSUS = ' + JSON.stringify(census) + ';\n');
fs.writeFileSync(path.join(HERE, 'curves.json'), JSON.stringify(Object.fromEntries(census.filter((e) => e.curve).map((e) => [e.id, { gauss: e.gauss, curve: e.curve }]))));
console.error('wrote js/census.js');
