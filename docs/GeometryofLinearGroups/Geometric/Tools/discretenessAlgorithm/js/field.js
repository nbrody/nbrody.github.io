/**
 * field.js — the field of definition of Γ = ⟨g₁, …, g_r⟩ ⊂ PGL₂(ℚ̄) and its places.
 *
 * poincare's reader (expr.js) puts the entries in a tower K of number fields
 * with one chosen embedding K ↪ ℂ. K is often larger than it need be: in PGL₂
 * a matrix is only defined up to a scalar, and the user may have adjoined
 * numbers the entries do not use. So each generator is divided by its first
 * nonzero entry, and
 *
 *     F = ℚ(entries of the normalized generators)
 *
 * is the smallest field with Γ ⊂ PGL₂(F). Discreteness at a place of K is
 * discreteness at the place of F below it (PGL₂(F_v) is closed in PGL₂(K_w)),
 * so the places of F are the ones to test, each once.
 *
 * F is written as ℚ(w) for a primitive element w with a monic integral
 * minimal polynomial f, chosen among the entries and small combinations of
 * them so that f has small coefficients. Then
 *
 *   • the places at ∞ are the roots of f: one per real root, one per pair of
 *     complex conjugate roots (a conjugate group is a mirror image);
 *   • the finite places are the primes 𝔭 of F. Only finitely many can see Γ
 *     unbounded: those dividing a denominator of a coordinate of an entry, or
 *     the norm of a determinant (see `candidateNumbers`).
 *
 * Everything here is exact (Frac / TElem); only the roots of f are floats,
 * and they serve only to name the embeddings.
 */
import { Frac, ExactMat, minimalPolynomial, coordinatesIn, subfieldOf } from '../../Kleinian/poincare/js/exact.js';
import { complexRoots, sortRoots, nearestIndex } from '../../Kleinian/poincare/js/tower.js';

const F0 = new Frac(0n), F1 = new Frac(1n);
const babs = (x) => (x < 0n ? -x : x);
const bgcd = (a, b) => { a = babs(a); b = babs(b); while (b) [a, b] = [b, a % b]; return a; };
const blcm = (a, b) => (a / bgcd(a, b)) * b;

// ---------------- normalized generators ----------------

/** The generator divided by its first nonzero entry (in the order a, b, c, d). */
export function normalizeMat(M) {
    const lead = [M.a, M.b, M.c, M.d].find((x) => !x.isZero());
    const s = lead.inv();
    return new ExactMat(M.a.mul(s), M.b.mul(s), M.c.mul(s), M.d.mul(s), M.anti);
}

// ---------------- the primitive element ----------------

/**
 * Scale a monic rational polynomial (Frac, low → high) to a monic integral
 * one: w = D·θ has minimal polynomial D^n·f(x/D), whose coefficient of x^i is
 * D^{n−i}·c_i. D is the least positive integer making all of these integers.
 */
export function integralize(mp) {
    const n = mp.length - 1;
    let D = 1n;
    // For each prime p in a denominator, D needs p^⌈v_p(den c_i)/(n−i)⌉.
    const dens = mp.slice(0, n).map((c) => c.q).filter((q) => q > 1n);
    const primes = new Set();
    for (let q of dens) {
        for (let p = 2n; p * p <= q; p++) while (q % p === 0n) { primes.add(p); q /= p; }
        if (q > 1n) primes.add(q);
    }
    for (const p of primes) {
        let need = 0;
        mp.slice(0, n).forEach((c, i) => {
            let v = 0, q = c.q;
            while (q % p === 0n) { q /= p; v++; }
            if (v) need = Math.max(need, Math.ceil(v / (n - i)));
        });
        D *= p ** BigInt(need);
    }
    const poly = mp.map((c, i) => {
        const x = c.mul(new Frac(D ** BigInt(n - i)));
        if (x.q !== 1n) throw new Error('internal: integralize');
        return x.p;
    });
    return { D, poly };
}

/** Coordinates over F = ℚ: the rational itself (throws when x is not rational). */
function ratCoords(x) {
    const r = x.rational();
    if (!r) throw new Error('not in the field of definition');
    return [r];
}

/** Scale the four coordinate vectors by one rational so they are coprime integers. */
function clearDenominators(cs) {
    let L = 1n, G = 0n;
    for (const v of cs) for (const c of v) L = blcm(L, c.q);
    for (const v of cs) for (const c of v) G = bgcd(G, c.p * (L / c.q));
    const s = new Frac(L, G || 1n);
    return cs.map((v) => v.map((c) => c.mul(s)));
}

/** Size of an integral polynomial, for choosing a pleasant generator. */
const polyCost = (poly) => poly.reduce((s, c) => s + babs(c).toString(2).length + (c ? 1 : 0), 0);

/**
 * The field generated by the normalized entries, as ℚ(w).
 *
 * Returns { degree, D, theta, poly (BigInt[], monic, low → high), coords(x) },
 * where w = D·θ and coords(x) gives x = Σ a_i w^i (Frac[]).
 */
export function primitiveElement(elems, extra = []) {
    const K = elems.length ? elems[0].K : null;
    const irr = [];
    const keys = new Set();
    for (const x of elems) {
        if (x.rational()) continue;
        const k = x.key();
        if (keys.has(k)) continue;
        keys.add(k);
        irr.push(x);
    }
    if (!irr.length) {
        return { degree: 1, D: 1n, theta: null, poly: [0n, 1n], coords: ratCoords };
    }
    const { degree, primitive } = subfieldOf(irr);
    if (degree === 1) {
        return { degree: 1, D: 1n, theta: null, poly: [0n, 1n], coords: ratCoords };
    }
    let best = null;
    const tryCandidate = (theta) => {
        const mp = minimalPolynomial(theta);
        if (mp.length - 1 !== degree) return;
        const { D, poly } = integralize(mp);
        const cost = polyCost(poly);
        if (!best || cost < best.cost) best = { theta, D, poly, cost };
    };
    for (const x of irr) tryCandidate(x);
    // The numbers the user adjoined (i, √2, a root row …) often generate F
    // with a smaller polynomial than any entry does — when they lie in F.
    if (best) {
        for (const y of extra) {
            if (y.rational()) continue;
            try { coordinatesIn(y, best.theta, degree); } catch (e) { continue; }
            tryCandidate(y);
        }
    }
    if (!best) {
        const few = irr.slice(0, 6);
        const two = K.fromInt(2);
        for (let i = 0; i < few.length && !best; i++) {
            for (let j = i + 1; j < few.length; j++) {
                tryCandidate(few[i].add(few[j]));
                tryCandidate(few[i].sub(few[j]));
                tryCandidate(few[i].add(few[j].mul(two)));
            }
        }
    }
    if (!best && primitive) tryCandidate(primitive);
    if (!best) throw new Error('could not find a primitive element of the field of definition');
    // Centre the roots: w ↦ w + k with k the rounded mean of −(roots), which
    // keeps f monic and integral and shrinks it (decimal inputs especially).
    {
        const n = best.poly.length - 1;
        const k = (best.poly[n - 1] >= 0n ? best.poly[n - 1] + BigInt(n >> 1) : best.poly[n - 1] - BigInt(n >> 1)) / BigInt(n);
        if (k !== 0n) tryCandidate(best.theta.add(K.fromFrac(new Frac(k, best.D))));
    }
    // A quadratic w² + d: divide w by the largest s with s² | d.
    if (degree === 2 && best.poly[1] === 0n) {
        let d = babs(best.poly[0]), s = 1n;
        for (let q = 2n; q * q <= d && q < 100000n; q++) while (d % (q * q) === 0n) { d /= q * q; s *= q; }
        if (s > 1n) tryCandidate(best.theta.mul(K.fromFrac(new Frac(1n, s))));
    }
    const { theta, D, poly } = best;
    const Dpow = [F1];
    for (let i = 1; i < degree; i++) Dpow.push(Dpow[i - 1].mul(new Frac(D)));
    const coords = (x) => coordinatesIn(x, theta, degree).map((a, i) => a.div(Dpow[i]));
    return { degree, D, theta, poly, coords };
}

// ---------------- formatting ----------------

const fracTex = (c) => (c.q === 1n ? `${babs(c.p)}` : `\\frac{${babs(c.p)}}{${c.q}}`);
const fracSrc = (c) => (c.q === 1n ? `${babs(c.p)}` : `${babs(c.p)}/${c.q}`);

/**
 * Σ a_i w^i, highest power first, as
 *   'tex'  LaTeX for MathJax and MathQuill (read back by poincare's expr.js
 *          and by trees' latexToPlain): \frac{1}{2}w^{2} - 3w + 1
 *   'src'  plain text for ringEngine's parser: 1/2*w^2-3*w+1
 */
export function polyInW(coeffs, mode = 'tex', w = 'w') {
    const parts = [];
    for (let i = coeffs.length - 1; i >= 0; i--) {
        const c = coeffs[i];
        if (!c || c.isZero()) continue;
        const neg = c.p < 0n;
        const one = c.p === 1n || c.p === -1n;
        const mono = i === 0 ? '' : i === 1 ? w : mode === 'tex' ? `${w}^{${i}}` : `${w}^${i}`;
        let body;
        if (!mono) body = mode === 'tex' ? fracTex(c) : fracSrc(c);
        else if (one && c.q === 1n) body = mono;
        else body = mode === 'tex' ? `${fracTex(c)}${mono}` : `${fracSrc(c)}*${mono}`;
        if (!parts.length) parts.push(neg ? `-${body}` : body);
        else parts.push(neg ? ` - ${body}` : ` + ${body}`);
    }
    const s = parts.join('') || '0';
    return mode === 'src' ? s.replace(/ /g, '') : s;
}

/** The integral polynomial f(w) (BigInt, low → high) as LaTeX or source. */
export function intPolyString(poly, mode = 'tex', w = 'w') {
    return polyInW(poly.map((c) => new Frac(c)), mode, w);
}

// ---------------- norms ----------------

/** x·y mod f in the power basis (Frac[], length n). */
function mulMod(x, y, f) {
    const n = f.length - 1;
    const r = new Array(2 * n - 1).fill(F0);
    for (let i = 0; i < n; i++) {
        if (x[i].isZero()) continue;
        for (let j = 0; j < n; j++) if (!y[j].isZero()) r[i + j] = r[i + j].add(x[i].mul(y[j]));
    }
    for (let t = 2 * n - 2; t >= n; t--) {
        const c = r[t];
        if (c.isZero()) continue;
        for (let j = 0; j < n; j++) r[t - n + j] = r[t - n + j].sub(c.mul(new Frac(f[j])));
    }
    return r.slice(0, n);
}

/** Determinant of a square Frac matrix (fraction-free enough for small n). */
function detFrac(M) {
    const n = M.length;
    const A = M.map((r) => r.slice());
    let det = F1;
    for (let c = 0; c < n; c++) {
        let piv = c;
        while (piv < n && A[piv][c].isZero()) piv++;
        if (piv === n) return F0;
        if (piv !== c) { [A[c], A[piv]] = [A[piv], A[c]]; det = det.neg(); }
        det = det.mul(A[c][c]);
        const inv = F1.div(A[c][c]);
        for (let r = c + 1; r < n; r++) {
            if (A[r][c].isZero()) continue;
            const f = A[r][c].mul(inv);
            for (let k = c; k < n; k++) A[r][k] = A[r][k].sub(f.mul(A[c][k]));
        }
    }
    return det;
}

/** N_{F/ℚ}(x) for x = Σ x_i w^i, f the monic integral minimal polynomial of w. */
export function normQ(x, f) {
    const n = f.length - 1;
    if (n === 1) return x[0];
    const cols = [];
    const unit = (j) => { const u = new Array(n).fill(F0); u[j] = F1; return u; };
    for (let j = 0; j < n; j++) cols.push(mulMod(x, unit(j), f));
    // matrix of multiplication by x: column j is x·w^j
    const M = Array.from({ length: n }, (_, i) => cols.map((col) => col[i]));
    return detFrac(M);
}

// ---------------- the model ----------------

/**
 * Everything the places need, from poincare's exact context { field, gens }.
 *
 *   degree, poly (f, BigInt[]), polyTex, polySrc
 *   mats: per generator, its entries in F as { coeffs, tex, src }: the
 *         entries as given when they lie in F, else the normalized ones
 *         with denominators cleared (the same element of PGL₂(F))
 *   roots: the embeddings of F (sorted as the root picker shows them)
 *   defaultIndex: the root that the user's embedding of K restricts to
 *   arch: the places at ∞ (one per real root, one per conjugate pair)
 *   numbers: integers whose prime factors include every prime where Γ may
 *            be unbounded (as decimal strings; factored by the worker)
 */
export function fieldModel(exactCtx) {
    const gens = exactCtx.gens.map(normalizeMat);
    const entries = gens.flatMap((M) => [M.a, M.b, M.c, M.d]);
    const K = exactCtx.field;
    const levelGens = [];
    for (let k = 1; k <= (K.height || 0); k++) levelGens.push(K.gen(k));
    const prim = primitiveElement(entries, levelGens);
    const { degree, poly } = prim;
    const mats = exactCtx.gens.map((M, g) => {
        let cs;
        try { cs = [M.a, M.b, M.c, M.d].map((x) => prim.coords(x)); }
        catch (e) { cs = clearDenominators([gens[g].a, gens[g].b, gens[g].c, gens[g].d].map((x) => prim.coords(x))); }
        return cs.map((coeffs) => ({ coeffs, tex: polyInW(coeffs, 'tex'), src: polyInW(coeffs, 'src') }));
    });

    // embeddings
    let roots = [{ re: 0, im: 0 }], defaultIndex = 0;
    if (degree > 1) {
        roots = sortRoots(complexRoots(poly.map((c) => ({ re: Number(c), im: 0 }))));
        const t = prim.theta.embed();
        const D = Number(prim.D);
        defaultIndex = nearestIndex(roots, { re: t.re * D, im: t.im * D });
    }
    const arch = [];
    const scale = Math.max(1, ...roots.map((r) => Math.hypot(r.re, r.im)));
    const used = new Set();
    roots.forEach((r, i) => {
        if (used.has(i)) return;
        if (r.im === 0) {
            used.add(i);
            arch.push({ kind: 'real', rootIndex: i, root: r, conjIndex: i });
            return;
        }
        // the conjugate root
        let j = -1, bd = Infinity;
        roots.forEach((s, k) => {
            if (k === i || used.has(k)) return;
            const d = Math.hypot(s.re - r.re, s.im + r.im);
            if (d < bd) { bd = d; j = k; }
        });
        used.add(i); if (j >= 0) used.add(j);
        // represent the pair by the user's embedding, else by Im > 0
        let rep = i;
        if (j >= 0 && (j === defaultIndex || (i !== defaultIndex && roots[j].im > roots[i].im))) rep = j;
        arch.push({ kind: 'complex', rootIndex: rep, root: roots[rep], conjIndex: rep === i ? j : i });
    });
    arch.forEach((a, k) => {
        a.isDefault = a.rootIndex === defaultIndex || a.conjIndex === defaultIndex;
        a.index = k;
    });
    // the user's embedding first
    arch.sort((x, y) => (y.isDefault - x.isDefault) || (x.index - y.index));
    arch.forEach((a, k) => { a.key = `inf${k + 1}`; a.n = k + 1; });

    // primes where Γ may be unbounded
    const numbers = new Set();
    const add = (b) => { b = babs(b); if (b > 1n) numbers.add(b.toString()); };
    for (const m of mats) {
        for (const e of m) for (const c of e.coeffs) add(c.q);
        const n = poly.length - 1;
        const pad = (x) => { const y = x.slice(); while (y.length < n) y.push(F0); return y; };
        const [a, b, c, d] = m.map((e) => pad(e.coeffs));
        const ad = mulMod(a, d, poly), bc = mulMod(b, c, poly);
        const N = normQ(ad.map((t, i) => t.sub(bc[i])), poly);
        add(N.p); add(N.q);
    }

    return {
        degree, D: prim.D, poly,
        polyTex: degree > 1 ? intPolyString(poly, 'tex') : '',
        polySrc: degree > 1 ? intPolyString(poly, 'src') : '',
        mats, roots, defaultIndex, arch,
        signature: [arch.filter((a) => a.kind === 'real').length, arch.filter((a) => a.kind === 'complex').length],
        numbers: [...numbers],
    };
}

// ---------------- states for the two tools ----------------

/**
 * poincare's input state for the place at ∞ given by root `root` of f: one
 * root row w and the normalized entries as polynomials in w. (For the user's
 * own embedding the page passes the user's state instead.)
 */
export function poincareStateFor(model, root) {
    const mats = model.mats.map((m) => m.map((e) => e.tex));
    const consts = model.degree > 1 ? [{ name: 'w', poly: model.polyTex, near: { re: root.re, im: root.im } }] : [];
    return { mats, anti: mats.map(() => false), consts };
}
