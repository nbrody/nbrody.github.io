const ANGLE_TOL = 0.02;        // radians, for 2π/m matching
const MAX_CYCLE_LEN = 200;
const LINE_TOL = 1e-7;         // Klein distance from a transported point to an edge line
const POINT_TOL = 1e-7;        // Klein distance for "the same point"

// ---------------- Edge extraction ----------------

/**
 * Edges of the domain, from the exact polyhedron.
 * Returns [{id, i, j, samples: Vector3[] (ball), mid: Vector3 (ball), angle, ...}]
 * — (i, j) the ACTIVE face pair, angle the interior dihedral angle.
 */
export function findEdges(walls, poly = null) {
    const P = poly || buildPolyhedron(walls);
    return P.edges.map(e => ({
        ...e,
        samples: edgeSamples(e, 48),
        mid: edgeMidpoint(e)
    }));
}

// ---------------- Cusp helpers ----------------

const VERTEX_MATCH_TOL = 1e-6;   // matching transported ideal vertices (ball)

/**
 * Möbius action of m on a BOUNDARY point of the ball, via the boundary
 * z-coordinate (C ∪ ∞) — NaN-safe at the north pole (∞), unlike pushing a
 * boundary point through applyMatrixToBall.
 */
export function transportBoundary(m, p) {
    const D = p.x * p.x + p.y * p.y + (1 - p.z) * (1 - p.z);
    let img;                                    // Complex, or null = ∞
    if (D < 1e-12) {
        img = Math.sqrt(m.c.normSq()) < 1e-10 ? null : m.a.div(m.c);
    } else {
        // Orientation-reversing m acts as z ↦ (a·z̄+b)/(c·z̄+d)
        const zim = 2 * p.y / D;
        const z = new Complex(2 * p.x / D, m.anti ? -zim : zim);
        const den = m.c.mul(z).add(m.d);
        img = Math.sqrt(den.normSq()) < 1e-10 ? null : m.a.mul(z).add(m.b).div(den);
    }
    if (img === null) return new THREE.Vector3(0, 0, 1);
    return uhsToBall({ x: img.re, y: img.im, t: 0 });
}

/** Boundary point of the ball → its coordinate in C ∪ {∞} (null = ∞). */
function boundaryCoord(p) {
    const D = p.x * p.x + p.y * p.y + (1 - p.z) * (1 - p.z);
    if (D < 1e-12) return null;
    return new Complex(2 * p.x / D, 2 * p.y / D);
}

/** Fixed point of a parabolic m on the ball boundary. */
function parabolicFixedBall(m) {
    if (Math.sqrt(m.c.normSq()) < 1e-9) return new THREE.Vector3(0, 0, 1);
    const z = m.a.sub(m.d).div(m.c.mul(2));
    return uhsToBall({ x: z.re, y: z.im, t: 0 });
}

/**
 * Classify a cusp holonomy element (det normalized to 1). It is a
 * horospherical ISOMETRY iff it is the identity, parabolic, or elliptic —
 * i.e. tr² real in [0,4]. Loxodromic holonomy = incomplete cusp.
 * With an exact context, identity and parabolicity are decided EXACTLY
 * (tr² = 4·det is projectively invariant), and an exact negative overrides
 * a numerically-passing verdict.
 */
function classifyCuspHolonomy(Mnorm, word, exactCheck, exactCtx) {
    const E = exactCheck ? exactCheck(word) : null;
    if (E) {
        if (E.isProjectiveIdentity()) return { ok: true, kind: 'the identity (exact)', type: 'identity' };
        const trE = E.a.add(E.d);
        const four = exactCtx.field.fromFrac(new Frac(4));
        if (trE.mul(trE).equals(E.det().mul(four))) {
            return { ok: true, kind: 'parabolic (exact: tr² = 4·det)', type: 'parabolic' };
        }
    }
    if (distFromIdentityPSL(Mnorm) < 1e-6) {
        return E
            ? { ok: false, kind: 'numerically ≈ I but ≠ I exactly (violates discreteness)' }
            : { ok: true, kind: 'the identity', type: 'identity' };
    }
    const tr = Mnorm.a.add(Mnorm.d);
    const q = tr.mul(tr);
    if (Math.abs(q.im) < 1e-5 && q.re > -1e-5 && q.re < 4 + 1e-5) {
        if (Math.abs(q.re - 4) < 1e-5) {
            return E
                ? { ok: false, kind: 'numerically parabolic but tr² ≠ 4·det exactly' }
                : { ok: true, kind: 'parabolic', type: 'parabolic' };
        }
        return { ok: true, kind: `elliptic (tr² ≈ ${q.re.toFixed(6)})`, type: 'elliptic' };
    }
    return {
        ok: false,
        kind: `loxodromic (tr² ≈ ${q.re.toFixed(4)}${q.im >= 0 ? '+' : '−'}${Math.abs(q.im).toFixed(4)}i)`
    };
}

/**
 * Cusp shape from the translations of a cusp's parabolic holonomy, conjugated
 * so the cusp point is ∞: the lattice they span, Gauss-reduced, and its shape
 * τ₂/τ₁ in the standard fundamental domain (|Re τ| ≤ ½, |τ| ≥ 1).
 */
function cuspShape(point, loops) {
    const z0 = boundaryCoord(point);
    // C sends the cusp point to ∞: z ↦ 1/(z − z0), or the identity if z0 = ∞.
    const C = z0 === null ? Matrix2x2.identity()
        : new Matrix2x2(new Complex(0), new Complex(1), new Complex(1), z0.mul(-1));
    const Ci = C.inv();
    // Holonomy fixing ∞ acts on C by Euclidean motions z ↦ αz + β. For an
    // orbifold cusp the loops include rotations, so close them up (short
    // products) and keep every translation that appears.
    const affine = [];
    for (const { matrix } of loops) {
        if (matrix.anti) continue;
        const Mp = C.mul(matrix).mul(Ci).normalized();
        if (Math.sqrt(Mp.c.normSq()) > 1e-6) continue;          // not fixing ∞ numerically
        affine.push({ al: Mp.a.div(Mp.d), be: Mp.b.div(Mp.d) });
    }
    const compose = (f, g) => ({ al: f.al.mul(g.al), be: f.al.mul(g.be).add(f.be) });
    const invAff = (f) => { const ai = new Complex(1).div(f.al); return { al: ai, be: ai.mul(f.be).mul(-1) }; };
    const gensA = [...affine, ...affine.map(invAff)];
    let layer = gensA.slice();
    const all = gensA.slice();
    for (let depth = 2; depth <= 4 && all.length < 400; depth++) {
        const next = [];
        for (const f of layer) for (const g of gensA) { const h = compose(f, g); next.push(h); all.push(h); }
        layer = next.length > 200 ? next.slice(0, 200) : next;
    }
    const trans = [];
    for (const f of all) {
        if (Math.abs(f.al.re - 1) > 1e-6 || Math.abs(f.al.im) > 1e-6) continue;   // not a translation
        if (Math.sqrt(f.be.normSq()) > 1e-9) trans.push(f.be);
    }
    if (trans.length === 0) return null;
    // Lattice basis from many lattice vectors: the shortest one, then the
    // non-parallel one spanning the smallest parallelogram with it.
    trans.sort((a, b) => a.normSq() - b.normSq());
    const u0 = trans[0];
    let v0 = null, bestArea = Infinity;
    for (const t of trans) {
        const area = Math.abs(u0.re * t.im - u0.im * t.re);
        if (area > 1e-8 * t.normSq() && area < bestArea - 1e-12) { bestArea = area; v0 = t; }
    }
    const basis = v0 ? [u0, v0] : [u0];
    const reduce2 = (u, v) => {
        for (let it = 0; it < 200; it++) {
            if (u.normSq() > v.normSq()) [u, v] = [v, u];
            const mu = Math.round((v.re * u.re + v.im * u.im) / u.normSq());
            if (mu === 0) break;
            v = v.sub(u.mul(mu));
        }
        return u.normSq() <= v.normSq() ? [u, v] : [v, u];
    };
    if (basis.length < 2) return { rank: 1, translations: basis };
    let [u, v] = reduce2(basis[0], basis[1]);
    // Positively oriented basis: if (u, v) is negatively oriented use (v, u).
    let tau = v.div(u);
    if (tau.im < 0) tau = new Complex(1).div(tau);
    // Standard fundamental domain for SL(2,Z).
    for (let it = 0; it < 100; it++) {
        tau = new Complex(tau.re - Math.round(tau.re), tau.im);
        if (tau.normSq() < 1 - 1e-12) tau = new Complex(-1, 0).div(tau);
        else break;
    }
    return { rank: 2, translations: [u, v], shape: tau };
}

// ---------------- Certifier ----------------

/**
 * Run the certificate. `walls` come from computeCanonicalDomain (with
 * pairings assigned); `basepoint` is the Dirichlet basepoint.
 *
 * opts:
 *   poly        — the exact polyhedron of `walls` (computed if absent)
 *   center      — the Dirichlet centre in the walls' frame (default: basepoint)
 *   generators  — [{matrix, word}] the INPUT generators acting in the walls'
 *                 frame (geometric), with their basepoint-frame words; enables
 *                 the membership check (4)
 *   exactGens   — (via exactCtx) exact generators for word evaluation
 *
 * Returns {
 *   ok, status: 'verified' | 'failed' | 'incomplete',
 *   log: string[], entries: [{kind, text, ref?}],
 *   edgeCycles, pairingChecks, hasCusps, cuspResolved, exactUsed,
 *   presentation, membership, cusps, poly, structure
 * }
 */
export function certifyDomain(walls, basepoint, exactCtx = null, opts = {}) {
    const entries = [];
    const emit = (kind, text, ref) => { entries.push(ref ? { kind, text, ref } : { kind, text }); };
    const geoms = walls.map(w => w.geom);
    let ok = true;
    let incomplete = false;

    const finish = (extra) => {
        const log = entries.map(e => e.text);
        return { log, entries, ...extra };
    };

    if (walls.length === 0) {
        emit('info', 'No walls — nothing to certify.');
        return finish({ ok: false, status: 'incomplete', edgeCycles: [], pairingChecks: [], hasCusps: false });
    }

    // Exact-arithmetic layer: when the generators carry exact number-field
    // entries, the ALGEBRAIC conditions (pairing involutions, cycle relations,
    // membership) are re-verified exactly in PGL2(K) from the words. Geometry
    // (edges, dihedral angles, combinatorics) remains floating point either way.
    let exactUsed = false;
    const exactCheck = (word) => {
        if (!exactCtx) return null;
        try {
            exactUsed = true;
            return exactFromWord(word, exactCtx.gens, exactCtx.field);
        } catch (e) {
            emit('warn', `⚠ exact arithmetic failed (${e.message}) — falling back to numeric for this check.`);
            return null;
        }
    };
    if (exactCtx) {
        emit('head', `— Exact mode: relations verified over ${exactCtx.field.describe()}` +
            (exactCtx.field.deg > 1 ? ` (${exactCtx.field.gen} a root of the given minimal polynomial)` : '') + ' —');
    }

    const poly = opts.poly || buildPolyhedron(walls);
    const edges = poly.edges;

    // ---- (0) Cell structure ----
    const structure = checkEuler(poly);
    emit('head', '— Polyhedron —');
    const nIdeal = poly.vertices.filter(v => v.ideal).length;
    const volumeKind = poly.finiteVolume ? 'finite volume' : 'infinite volume (meets the sphere at infinity in open patches)';
    emit('info', `${walls.length} faces, ${edges.length} edges, ${poly.vertices.length} vertices ` +
        `(${nIdeal} on the sphere at infinity); ${volumeKind}.`);
    if (structure.ok) {
        emit('ok', poly.finiteVolume
            ? `✓ cell structure consistent: V − E + F = ${structure.V} − ${structure.E} + ${structure.F} = 2`
            : '✓ cell structure consistent (every face vertex meets two face edges)');
    } else {
        ok = false;
        for (const p of structure.problems.slice(0, 8)) emit('fail', `✗ ${p}`);
    }

    // ---- (1) Face pairing checks ----
    const pairingChecks = [];
    emit('head', `— Face pairing check (${walls.length} walls) —`);
    const vertexOnFace = (k, m) => poly.faces[m].vertices.some(v => poly.vertices[v].k.distanceToSquared(k) < 1e-12);
    for (let i = 0; i < walls.length; i++) {
        const w = walls[i];
        if (!w.pairing) {
            ok = false;
            emit('fail', `✗ wall ${i} (${wordStr(w.word)}): NO pairing transformation found.`, { walls: [i] });
            pairingChecks.push({ i, ok: false });
            continue;
        }
        const j = w.pairing.partner;
        let entryOk = true;
        let msg = '';
        let exactLine = null;
        if (j < 0) {
            entryOk = false;
            msg = 'image does not land on any wall';
        } else {
            // σ should be an involution: partner of partner is i,
            // with pairing(partner) = pairing(i)^{-1}
            const wj = walls[j];
            if (!wj.pairing || wj.pairing.partner !== i) {
                entryOk = false;
                msg = `σ not involutive (σ(${i})=${j} but σ(${j})=${wj.pairing ? wj.pairing.partner : '∅'})`;
            } else {
                const prod = w.pairing.matrix.mul(wj.pairing.matrix);
                const res = distFromIdentityPSL(prod.normalized());
                if (res > 1e-6) {
                    entryOk = false;
                    msg = `s_${j} ≠ s_${i}^{-1} (residual ${res.toExponential(1)})`;
                }
                // The face's finite vertices must map onto the partner face's
                // vertices — the pairing is a bijection of cells, not just of
                // planes.
                if (entryOk) {
                    for (const v of poly.faces[i].vertices) {
                        const V = poly.vertices[v];
                        if (V.ideal) continue;
                        const img = ballToKlein(applyMatrixToBall(w.pairing.matrix, kleinToBall(V.k)));
                        if (!vertexOnFace(img, j)) {
                            entryOk = false;
                            msg = `vertex ${v} of face ${i} does not map to a vertex of face ${j} — the faces are not congruent under s_${i}`;
                            break;
                        }
                    }
                }
                // Exact involution check: s_i·s_j ≡ I projectively in PGL2(K).
                const E = entryOk ? exactCheck([...w.pairing.word, ...wj.pairing.word]) : null;
                if (E) {
                    if (E.isProjectiveIdentity()) {
                        exactLine = `  · exact: s_${i}·s_${j} ≡ I in PGL₂(${exactCtx.field.describe()}) ✓`;
                    } else {
                        entryOk = false;
                        msg = `s_${j} ≠ s_${i}^{-1} EXACTLY (numeric residual passed — near-identity but not identity)`;
                    }
                }
            }
        }
        if (entryOk) {
            emit('ok', `✓ wall ${i} ↔ wall ${j}: s = ${wordStr(w.pairing.word)}, residual ${w.pairing.residual.toExponential(1)}`,
                { walls: i === j ? [i] : [i, j] });
            if (exactLine) emit('ok', exactLine, { walls: [i, j] });
        } else {
            ok = false;
            emit('fail', `✗ wall ${i} (${wordStr(w.word)}): ${msg}`, { walls: j >= 0 ? [i, j] : [i] });
        }
        pairingChecks.push({ i, j, ok: entryOk });
    }

    // ---- (2) Edge cycles ----
    //
    // Leaving the domain through wall a applies its pairing s_a, which carries
    // the edge onto another EDGE of the domain (for a genuine Poincaré
    // polyhedron). The image is located in the exact edge list; the arrival
    // wall must be one of that edge's two active faces, and the walk continues
    // through the other. Dihedral angles are exact from the Minkowski inner
    // product of the covectors.
    emit('head', `— Edge cycle check (${edges.length} edges) —`);
    const edgeCycles = [];
    const visited = new Set();
    const sideKey = (eid, wall) => `${eid}|${wall}`;

    const locateEdge = (y, arrived) => {
        const ky = ballToKlein(y);
        let best = null, bestD = LINE_TOL;
        for (const e of edges) {
            if (e.i !== arrived && e.j !== arrived && !e.extra.includes(arrived)) continue;
            const rel = ky.clone().sub(e.p0);
            const t = rel.dot(e.d);
            const perp = rel.addScaledVector(e.d, -t).length();
            if (perp < bestD && t > e.lo - 1e-9 && t < e.hi + 1e-9) { bestD = perp; best = e; }
        }
        return best;
    };

    for (const e0 of edges) {
        if (visited.has(sideKey(e0.id, e0.i))) continue;
        const span = e0.hi - e0.lo;
        const start1 = kleinToBall(edgePoint(e0, e0.lo + 0.41 * span));
        const start2 = kleinToBall(edgePoint(e0, e0.lo + 0.59 * span));
        let x1 = start1.clone(), x2 = start2.clone();
        let cur = e0, a = e0.i, b = e0.j;
        let P = Matrix2x2.identity();
        let angleSum = 0;
        let words = [];
        let steps = 0;
        let failed = null, degenerate = false;
        const cyclePairs = [];

        while (steps++ < MAX_CYCLE_LEN) {
            visited.add(sideKey(cur.id, a));
            visited.add(sideKey(cur.id, b));
            cyclePairs.push([a, b, cur.id]);
            angleSum += cur.angle;

            const wa = walls[a];
            if (!wa.pairing) { failed = `wall ${a} unpaired`; break; }
            P = wa.pairing.matrix.mul(P).normalized();
            words = [...wa.pairing.word, ...words];
            x1 = applyMatrixToBall(wa.pairing.matrix, x1);
            x2 = applyMatrixToBall(wa.pairing.matrix, x2);
            const arrived = wa.pairing.partner;

            const next = locateEdge(x1, arrived);
            if (!next || locateEdge(x2, arrived) !== next) {
                failed = `s_${a} carries edge (${cur.i},${cur.j}) off the edges of the domain`;
                break;
            }
            let other;
            if (next.i === arrived) other = next.j;
            else if (next.j === arrived) other = next.i;
            else {
                // The arrival wall contains the image line but does not bound
                // the domain there: a near-degenerate configuration.
                failed = `arrival wall ${arrived} is not an active face at edge (${next.i},${next.j})`;
                degenerate = true;
                break;
            }
            // Closed: back at the start edge, about to leave through the start
            // wall, with the tracked points returned (a flip needs a second lap).
            if (next.id === e0.id && other === e0.i &&
                ballToKlein(x1).distanceTo(ballToKlein(start1)) < POINT_TOL &&
                ballToKlein(x2).distanceTo(ballToKlein(start2)) < POINT_TOL) break;
            cur = next; a = other; b = arrived;
        }

        if (!failed && steps >= MAX_CYCLE_LEN) failed = 'cycle did not close';
        const edgeIds = [...new Set(cyclePairs.map(p => p[2]))];

        if (failed) {
            if (degenerate) {
                incomplete = true;
                emit('warn', `⚠ edge (${e0.i},${e0.j}): ${failed} — cycle unresolved numerically.`, { edges: edgeIds });
                edgeCycles.push({ pairs: cyclePairs, edges: edgeIds, ok: false, degenerate: true, reason: failed });
            } else {
                ok = false;
                emit('fail', `✗ edge (${e0.i},${e0.j}): ${failed}`, { edges: edgeIds });
                edgeCycles.push({ pairs: cyclePairs, edges: edgeIds, ok: false, reason: failed });
            }
            continue;
        }

        // Angle condition: angleSum = 2π/m
        const mFloat = 2 * Math.PI / angleSum;
        const m = Math.round(mFloat);
        const angleOk = m >= 1 && Math.abs(angleSum - 2 * Math.PI / m) < ANGLE_TOL;

        // Cycle transformation condition: P^m = ±I
        let Pm = Matrix2x2.identity();
        for (let k = 0; k < Math.max(1, m); k++) Pm = Pm.mul(P);
        const orderRes = distFromIdentityPSL(Pm.normalized());
        let orderOk = orderRes < 1e-5;

        // Exact cycle relation: P^m ≡ I projectively in PGL2(K). The exact
        // verdict overrides the numeric one in either direction.
        let cycleExactLine = null;
        if (angleOk && m >= 1) {
            const EP = exactCheck(words);
            if (EP) {
                const exactHolds = EP.pow(Math.max(1, m)).isProjectiveIdentity();
                if (exactHolds) {
                    orderOk = true;
                    cycleExactLine = `  · exact: (cycle elt)^${m} ≡ I in PGL₂(${exactCtx.field.describe()}) ✓`;
                } else if (orderOk) {
                    orderOk = false;
                    cycleExactLine = `  · exact: (cycle elt)^${m} ≠ I in PGL₂(${exactCtx.field.describe()}) — numeric check was misleading`;
                }
            }
        }

        const desc = `${cyclePairs.length} edges, Σθ = ${(angleSum / Math.PI).toFixed(5)}π ` +
            `(2π/${m}), cycle elt ${wordStr(reduceWord(words))}` +
            (m > 1 ? `, order ${m} residual ${orderRes.toExponential(1)}` : '');
        const cycleIdx = edgeCycles.length;
        if (angleOk && orderOk) {
            emit('ok', `✓ edge cycle at (${e0.i},${e0.j}): ${desc}`, { edges: edgeIds, cycle: cycleIdx });
            if (cycleExactLine) emit('ok', cycleExactLine, { edges: edgeIds, cycle: cycleIdx });
        } else {
            ok = false;
            emit('fail', `✗ edge cycle at (${e0.i},${e0.j}): ${desc} — ` +
                (!angleOk ? `angle sum is not 2π/m` : `cycle element does not have order ${m}`), { edges: edgeIds, cycle: cycleIdx });
            if (cycleExactLine) emit('fail', cycleExactLine, { edges: edgeIds, cycle: cycleIdx });
        }
        edgeCycles.push({ pairs: cyclePairs, edges: edgeIds, ok: angleOk && orderOk, m, angleSum, word: reduceWord(words) });
    }

    // ---- (3) Cusp completeness ----
    // Ideal vertices come exactly from the polyhedron. One that borders a free
    // patch of the sphere at infinity is a rank-1 cusp (it lies on the edge of
    // the ordinary set) and carries no completeness condition; the others are
    // genuine cusp points, glued into cusp cross-sections by the pairings.
    const freeEnds = [];
    for (const fa of poly.freeArcs) {
        for (const [a2, b2] of fa.arcs) {
            for (const t of [a2, b2]) {
                freeEnds.push(fa.center.clone().addScaledVector(fa.u, fa.rho * Math.cos(t))
                    .addScaledVector(fa.v, fa.rho * Math.sin(t)));
            }
        }
    }
    const freeAdjacent = (k) => freeEnds.some(p => p.distanceTo(k) < 1e-6);
    const idealNodes = poly.vertices
        .map((v, idx) => ({ v, idx }))
        .filter(({ v }) => v.ideal && v.walls.length >= 2 && !freeAdjacent(v.k));
    const rank1 = poly.vertices.filter(v => v.ideal && freeAdjacent(v.k)).length;

    const hasParabolic = walls.some(w => w.isParabolic);
    let hasCusps = idealNodes.length > 0 || hasParabolic;
    let cuspResolved = true;
    const cusps = [];
    // A mirror: a face paired with itself by an orientation-reversing map that
    // fixes the face pointwise — the reflection in that face.
    const isMirror = (i) => {
        const w = walls[i];
        if (!w.pairing || w.pairing.partner !== i || !w.pairing.matrix.anti) return false;
        const pts = poly.faces[i].vertices.map(v => poly.vertices[v]).filter(v => !v.ideal).slice(0, 2);
        return pts.every(v => {
            const p = kleinToBall(v.k);
            return applyMatrixToBall(w.pairing.matrix, p).distanceTo(p) < 1e-7;
        });
    };
    if (hasCusps) {
        emit('head', '— Cusp completeness check —');
        if (rank1 > 0) {
            emit('info', `ℹ ${rank1} ideal point(s) border the ordinary set (rank-1 cusps): no completeness condition there.`);
        }
        const mirrorCusps = idealNodes.filter(({ v }) => v.walls.every(isMirror));
        if (idealNodes.length === 0) {
            if (hasParabolic && rank1 === 0) {
                cuspResolved = false;
                emit('warn', '⚠ parabolic faces present but no ideal vertices resolved — completeness NOT checked.');
            }
        } else if (mirrorCusps.length === idealNodes.length) {
            // Every face at these ideal vertices is a mirror. A reflection in a
            // plane through an ideal point preserves each horosphere centred
            // there, so all holonomy acts isometrically: complete automatically.
            emit('ok', `✓ ${idealNodes.length} ideal vertex(es), every face there a mirror: reflections in planes ` +
                'through an ideal point preserve its horospheres, so each cusp is complete.',
                { points: idealNodes.map(n => kleinToBall(n.v.k)) });
        } else {
            try {
                const nodes = idealNodes.map(({ v }) => ({ p: kleinToBall(v.k).normalize(), faces: v.walls.slice() }));
                const findNode = (p) => {
                    for (let i2 = 0; i2 < nodes.length; i2++) {
                        if (nodes[i2].p.distanceToSquared(p) < VERTEX_MATCH_TOL * VERTEX_MATCH_TOL) return i2;
                    }
                    return -1;
                };
                const halfedges = [];
                let unresolved = 0;
                for (let k = 0; k < nodes.length; k++) {
                    for (const F of nodes[k].faces) {
                        const w = walls[F];
                        if (!w.pairing) { unresolved++; continue; }
                        const img = transportBoundary(w.pairing.matrix, nodes[k].p);
                        const j2 = findNode(img);
                        if (j2 < 0) { unresolved++; continue; }
                        halfedges.push({ from: k, face: F, to: j2 });
                    }
                }
                if (unresolved > 0) {
                    cuspResolved = false;
                    emit('warn', `⚠ ${unresolved} ideal-vertex transport(s) did not land on an ideal vertex — cusp check incomplete.`);
                }

                // Spanning forest with transports; each remaining gluing
                // (one per unordered pair) closes a holonomy loop that
                // stabilizes the cusp point — classify each one.
                const treeM = new Array(nodes.length).fill(null);
                const treeW = new Array(nodes.length).fill(null);
                const comp = new Array(nodes.length).fill(-1);
                const usedHE = new Set();
                const heKey = (from, face) => `${from}|${face}`;
                let nComp = 0, nLoops = 0, nBad = 0;
                for (let s0 = 0; s0 < nodes.length; s0++) {
                    if (comp[s0] >= 0) continue;
                    const cid = nComp++;
                    comp[s0] = cid;
                    treeM[s0] = Matrix2x2.identity();
                    treeW[s0] = [];
                    const members = [s0];
                    const queue = [s0];
                    while (queue.length) {
                        const k = queue.shift();
                        for (const h of halfedges) {
                            if (h.from !== k || usedHE.has(heKey(h.from, h.face))) continue;
                            if (comp[h.to] < 0) {
                                usedHE.add(heKey(h.from, h.face));
                                usedHE.add(heKey(h.to, walls[h.face].pairing.partner));
                                comp[h.to] = cid;
                                treeM[h.to] = walls[h.face].pairing.matrix.mul(treeM[k]).normalized();
                                treeW[h.to] = [...walls[h.face].pairing.word, ...treeW[k]];
                                queue.push(h.to);
                                members.push(h.to);
                            }
                        }
                    }
                    const loops = [];
                    for (const h of halfedges) {
                        if (comp[h.from] !== cid || usedHE.has(heKey(h.from, h.face))) continue;
                        usedHE.add(heKey(h.from, h.face));
                        usedHE.add(heKey(h.to, walls[h.face].pairing.partner));
                        nLoops++;
                        const M = treeM[h.to].inv().mul(walls[h.face].pairing.matrix).mul(treeM[h.from]).normalized();
                        const word = [...invertWord(treeW[h.to]), ...walls[h.face].pairing.word, ...treeW[h.from]];
                        const fx = transportBoundary(M, nodes[s0].p);
                        const cref = { points: members.map(i2 => nodes[i2].p) };
                        if (fx.distanceToSquared(nodes[s0].p) > 1e-6) {
                            cuspResolved = false;
                            emit('warn', `⚠ cusp ${cid}: a holonomy loop does not fix the base ideal vertex ` +
                                `(residual ${Math.sqrt(fx.distanceToSquared(nodes[s0].p)).toExponential(1)}) — check unresolved.`, cref);
                            continue;
                        }
                        if (M.anti) {
                            cuspResolved = false;
                            emit('warn', `⚠ cusp ${cid}: holonomy ${wordStr(reduceWord(word))} is orientation-reversing — ` +
                                `classification not yet implemented; check unresolved.`, cref);
                            continue;
                        }
                        const verdict = classifyCuspHolonomy(M, word, exactCtx ? exactCheck : null, exactCtx);
                        loops.push({ matrix: M, word: reduceWord(word), type: verdict.type });
                        if (verdict.ok) {
                            emit('ok', `✓ cusp ${cid}: holonomy ${wordStr(reduceWord(word))} is ${verdict.kind} — horospherical isometry.`, cref);
                        } else {
                            nBad++;
                            ok = false;
                            emit('fail', `✗ cusp ${cid}: holonomy ${wordStr(reduceWord(word))} is ${verdict.kind} — ` +
                                `NOT a horospherical isometry: the domain is INCOMPLETE at this cusp.`, cref);
                        }
                    }
                    const shape = cuspShape(nodes[s0].p, loops);
                    cusps.push({ id: cid, point: nodes[s0].p.clone(), vertices: members.length, loops, shape });
                }
                emit('info', `Cusp summary: ${nodes.length} ideal vertices, ${nComp} cusp(s), ` +
                    `${nLoops} holonomy loop(s) checked${nBad ? `, ${nBad} FAILED` : ''}.`);
                if (nLoops === 0) {
                    cuspResolved = false;
                    emit('warn', '⚠ no holonomy loops found — cusp identifications did not close up; completeness NOT verified.');
                }
            } catch (err) {
                cuspResolved = false;
                emit('warn', `⚠ cusp completeness check errored (${err.message}) — completeness NOT checked.`);
            }
        }
        if (!cuspResolved) incomplete = true;
    }
    if (edges.length === 0 && walls.length > 0) {
        emit('info', 'ℹ No edges (the faces are disjoint — a Schottky-type domain). ' +
            'The pairing check alone suffices in that case (ping-pong).');
    }

    // ---- presentation data (needed by the membership words) ----
    // Generators: one per {face, partner} pair of walls (the partner's pairing
    // is the inverse, so it needs no symbol; a self-paired face contributes the
    // relation s² = 1). Relations: one per edge cycle, (cycle word)^m = 1.
    const genOfWall = new Map();
    const presGens = [];
    for (let i = 0; i < walls.length; i++) {
        if (genOfWall.has(i)) continue;
        const w = walls[i];
        if (!w.pairing || w.pairing.partner < 0) continue;
        const j = w.pairing.partner;
        const idx = presGens.length;
        presGens.push({ sym: `s${idx + 1}`, i, j, word: w.pairing.word });
        genOfWall.set(i, { idx, inv: false });
        if (j !== i) genOfWall.set(j, { idx, inv: true });
    }
    const symbolOf = (wallIdx) => {
        const g = genOfWall.get(wallIdx);
        return g ? (g.inv ? -(g.idx + 1) : g.idx + 1) : 0;
    };

    // ---- (4) Membership of the input generators ----
    const membership = [];
    if (opts.generators && opts.generators.length) {
        emit('head', '— Input generators lie in the group generated by the face pairings —');
        const center = opts.center || basepoint;
        for (let gi = 0; gi < opts.generators.length; gi++) {
            const gen = opts.generators[gi];
            const label = wordStr(gen.word);
            let x = applyMatrixToBall(gen.matrix, center);
            const seq = [];
            let Pm = gen.matrix;
            let capped = true;
            for (let it = 0; it < 500; it++) {
                const k = ballToKlein(x);
                let worst = 1e-9, m = -1;
                for (let j = 0; j < walls.length; j++) {
                    const W = walls[j].cov;
                    const r = (W.x * k.x + W.y * k.y + W.z * k.z - W.w) / Math.hypot(W.x, W.y, W.z);
                    if (r > worst) { worst = r; m = j; }
                }
                if (m < 0) { capped = false; break; }
                if (!walls[m].pairing) break;
                x = applyMatrixToBall(walls[m].pairing.matrix, x);
                Pm = walls[m].pairing.matrix.mul(Pm);
                seq.push(m);
            }
            if (capped) {
                incomplete = true;
                emit('warn', `⚠ generator ${label}: reduction did not reach the domain within 500 steps — membership unresolved.`);
                membership.push({ index: gi, ok: null });
                continue;
            }
            const home = hypDist(x, center) < 1e-6;
            let isId = distFromIdentityPSL(Pm.normalized()) < 1e-6;
            // Word of the reduced element: s_{m_n}⋯s_{m_1}·g must be trivial.
            const word = [];
            for (let s = seq.length - 1; s >= 0; s--) word.push(...walls[seq[s]].pairing.word);
            word.push(...gen.word);
            let exactNote = '';
            if (home && isId) {
                const E = exactCheck(word);
                if (E) {
                    if (E.isProjectiveIdentity()) exactNote = ' (exact)';
                    else { isId = false; exactNote = ' — but NOT exactly the identity'; }
                }
            }
            if (home && isId) {
                // g = s_{m_1}^{-1} ⋯ s_{m_n}^{-1}, and s_m^{-1} is the pairing of m's partner.
                const expr = seq.map(m => symbolOf(walls[m].pairing.partner));
                membership.push({ index: gi, ok: true, walls: seq, expr });
                emit('ok', `✓ ${label} = ${expr.length ? expr.map(symStr).join('·') : 'e'} in the face pairings${exactNote}.`,
                    { walls: [...new Set(seq)] });
            } else {
                ok = false;
                membership.push({ index: gi, ok: false, walls: seq });
                emit('fail', home
                    ? `✗ ${label} folds back to the basepoint as a NON-trivial element fixing it${exactNote} — ` +
                    'a stabilizer element is missing from the domain.'
                    : `✗ ${label} is not in the group generated by the face pairings: it folds into the domain ` +
                    `at distance ${hypDist(x, center).toFixed(4)} from the basepoint. The domain is a fundamental ` +
                    'domain for a proper subgroup — raise the word length, or the input group is not discrete.',
                    { walls: [...new Set(seq)], points: [x] });
            }
        }
    }

    // ---- (5) Presentation (Poincaré polyhedron theorem) ----
    const relators = [];
    const addRelator = (enc, m, src) => {
        // free + cyclic reduction
        let arr = enc.slice();
        let changed = true;
        while (changed) {
            changed = false;
            for (let k = 0; k + 1 < arr.length; k++) {
                if (arr[k] === -arr[k + 1]) { arr.splice(k, 2); changed = true; break; }
            }
            if (!changed && arr.length >= 2 && arr[0] === -arr[arr.length - 1]) {
                arr = arr.slice(1, -1); changed = true;
            }
        }
        if (arr.length === 0) return;
        // canonical key over cyclic rotations of the word and its inverse
        const variants = [];
        const addRots = (a) => {
            for (let r = 0; r < a.length; r++) {
                variants.push(JSON.stringify([...a.slice(r), ...a.slice(0, r), 'm', m]));
            }
        };
        addRots(arr);
        addRots(arr.slice().reverse().map(x => -x));
        variants.sort();
        const key = variants[0];
        if (relators.some(R => R.key === key)) return;
        relators.push({ key, enc: arr, m, src });
    };

    presGens.forEach((g, k) => {
        if (g.i === g.j) addRelator([k + 1], 2, `wall ${g.i} self-paired`);
    });

    let cyclesSkipped = 0;
    for (const ec of edgeCycles) {
        if (!ec.ok || !ec.m || !ec.pairs || ec.pairs.length === 0) { cyclesSkipped++; continue; }
        // The pairing applied at each step is that of the FIRST wall of the
        // pair; P = A_n···A_1, so the left-to-right word is the reverse.
        const seq = ec.pairs.map(p => p[0]).reverse();
        let bad = false;
        const enc = seq.map(a => {
            const s = symbolOf(a);
            if (!s) bad = true;
            return s;
        });
        if (bad) { cyclesSkipped++; continue; }
        addRelator(enc, ec.m, `edge cycle at walls (${ec.pairs[0][0]},${ec.pairs[0][1]})`);
    }

    const symOf = (x) => presGens[Math.abs(x) - 1].sym + (x < 0 ? '⁻¹' : '');
    const relWord = (R) => R.enc.map(symOf).join('·');
    const relStr = (R) => {
        if (R.m === 1) return `${relWord(R)} = 1`;
        if (R.enc.length === 1 && R.enc[0] > 0) return `${symOf(R.enc[0])}^${R.m} = 1`;
        return `(${relWord(R)})^${R.m} = 1`;
    };
    const relBare = (R) => {
        if (R.m === 1) return relWord(R);
        if (R.enc.length === 1 && R.enc[0] > 0) return `${symOf(R.enc[0])}^${R.m}`;
        return `(${relWord(R)})^${R.m}`;
    };

    emit('head', '— Presentation (Poincaré polyhedron theorem) —');
    let presentation = null;
    if (presGens.length === 0) {
        emit('info', 'No paired faces — no presentation available.');
    } else {
        emit('info', 'Generators (face pairings):');
        presGens.forEach((g, k) => {
            emit('info', `  ${g.sym} = ${wordStr(g.word)}   (wall ${g.i}${g.j !== g.i ? ` ↔ ${g.j}` : ', self-paired'})`,
                { walls: g.i === g.j ? [g.i] : [g.i, g.j] });
        });
        if (relators.length) {
            emit('info', 'Relations:');
            for (const R of relators) emit('info', `  ${relStr(R)}   [${R.src}]`);
        } else {
            emit('info', 'Relations: none — the pairings generate freely (ping-pong domain).');
        }
        const presLine = `⟨ ${presGens.map(g => g.sym).join(', ')} | ${relators.map(relBare).join(', ')} ⟩`;
        emit('info', presLine);
        if (cyclesSkipped > 0) {
            emit('warn', `⚠ ${cyclesSkipped} edge cycle(s) unresolved — the relation set may be incomplete.`);
        }
        if (!ok) emit('fail', '(certificate FAILED — this presentation is NOT certified)');
        // LaTeX rendering (bare TeX; the UI wraps and typesets it).
        const relWordTex = (R) => encTex(R.enc, 's');
        const relTex = (R) => {
            if (R.m === 1) return relWordTex(R);
            if (R.enc.length === 1 && R.enc[0] > 0) return `s_{${R.enc[0]}}^{${R.m}}`;
            return `\\left(${relWordTex(R)}\\right)^{${R.m}}`;
        };
        presentation = {
            generators: presGens.map(g => ({ sym: g.sym, word: g.word.slice(), walls: [g.i, g.j] })),
            relators: relators.map(relBare),
            relatorsEnc: relators.map(R => ({ enc: R.enc.slice(), m: R.m })),
            generatorExpressions: membership.map(mb => mb.ok ? mb.expr.slice() : null),
            complete: cyclesSkipped === 0,
            display: presLine,
            latex: {
                generators: presGens.map((g, k) => ({
                    tex: `s_{${k + 1}} = ${formatWordMathJax(g.word)}`,
                    note: g.j !== g.i ? `walls ${g.i} ↔ ${g.j}` : `wall ${g.i} · self-paired`,
                })),
                relators: relators.map(R => ({ tex: `${relTex(R)} = 1`, src: R.src })),
                group: relators.length
                    ? `\\left\\langle\\; ${presGens.map((g, k) => `s_{${k + 1}}`).join(',\\, ')} ` +
                    `\\;\\middle|\\; ${relators.map(relTex).join(',\\;\\; ')} \\;\\right\\rangle`
                    : `\\left\\langle\\; ${presGens.map((g, k) => `s_{${k + 1}}`).join(',\\, ')} \\;\\right\\rangle` +
                    `\\ \\cong\\ F_{${presGens.length}}`,
            },
        };
    }

    let status;
    if (!ok) status = 'failed';
    else if (incomplete) status = 'incomplete';
    else status = 'verified';

    const how = exactUsed
        ? 'relations exact, angles/combinatorics numerical'
        : 'numerically';
    const cuspPhrase = hasCusps && cuspResolved && cusps.length ? ', including cusp completeness' : '';
    emit(ok ? (incomplete ? 'warn' : 'ok') : 'fail', ok
        ? (incomplete
            ? `— All resolvable Poincaré conditions PASS (${how}); some checks unresolved — see ⚠ lines above. —`
            : `— All Poincaré conditions PASS (${how})${cuspPhrase}: the group is discrete with this fundamental domain. —`)
        : '— Certificate FAILED: domain is not verified. The group may be non-discrete, or the search depth too small. —');

    return finish({
        ok, status, edgeCycles, pairingChecks, hasCusps, cuspResolved, exactUsed,
        presentation, membership, cusps, poly, structure
    });
}

function symStr(x) {
    return `s${Math.abs(x)}${x < 0 ? '⁻¹' : ''}`;
}

/** LaTeX for a word of signed symbol indices, compressing runs (s s s → s³). */
export function encTex(enc, letter = 's') {
    const parts = [];
    let i = 0;
    while (i < enc.length) {
        let j = i;
        while (j < enc.length && enc[j] === enc[i]) j++;
        const idx = Math.abs(enc[i]), n = j - i;
        const e = enc[i] > 0 ? n : -n;
        parts.push(e === 1 ? `${letter}_{${idx}}` : `${letter}_{${idx}}^{${e}}`);
        i = j;
    }
    return parts.length ? parts.join('\\,') : '1';
}

function wordStr(word) {
    if (!word || word.length === 0) return 'e';
    const s = word.map(i => {
        const a = Math.abs(i);
        return (i > 0 ? `g${a}` : `g${a}⁻¹`);
    }).join('·');
    return s.length > 120 ? s.slice(0, 120) + `… (length ${word.length})` : s;
}
