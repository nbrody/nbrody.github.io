/**
 * Poincaré polyhedron theorem certifier.
 *
 * Given the walls of a domain with their pairing transformations, we check:
 *
 *  (0) STRUCTURE: the exact polyhedron (polyhedron.js, Klein model) is a
 *      consistent cell: every face vertex meets exactly two face edges, and a
 *      finite-volume domain satisfies V − E + F = 2.
 *  (1) PAIRING: each wall has a pairing s with s(face_i) = face_partner (its
 *      vertices land on the partner face's vertices), and the partner's
 *      pairing is s^{-1} (σ is an involution on faces; a face may be paired
 *      with itself).
 *  (2) EDGE CYCLES: each edge (codim-2 cell) is traced around its cycle via the
 *      pairing maps, matching every image against the exact edge list. The
 *      interior dihedral angles along the cycle must sum to 2π/m for an integer
 *      m ≥ 1, and the cycle transformation must satisfy P^m = ±I.
 *  (3) CUSP COMPLETENESS: at each ideal vertex the faces glue the vertex links
 *      into a similarity surface; the domain is complete at the cusp iff every
 *      holonomy loop (an element stabilizing the ideal point) acts on a
 *      horosphere as a Euclidean ISOMETRY — parabolic, elliptic, or the
 *      identity, never loxodromic. We build the gluing graph of ideal vertices,
 *      take a spanning tree, and classify the holonomy of every remaining loop
 *      (exactly, over the number field, when available).
 *  (4) MEMBERSHIP: the theorem makes the group Γ generated by the pairings
 *      discrete with this fundamental domain. It says nothing about the group
 *      G the user typed in unless G = Γ. Every input generator is therefore run
 *      through Poincaré's reduction algorithm — fold it back into the domain
 *      through the pairings — and must come out as the identity. A generator
 *      that lands elsewhere shows the domain belongs to a proper subgroup.
 *
 * If all hold, Poincaré's theorem implies the input group is discrete with this
 * domain as fundamental polyhedron, and gives a presentation. Combinatorics and
 * dihedral angles are floating point (with explicit residuals); the group
 * relations are exact when an exact context is given.
 */
