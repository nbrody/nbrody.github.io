export function icon(name, size = 16, cls = '') {
  if (!PATHS[name]) return texIcon(name, size, cls);
  const span = document.createElement('span');
  span.className = `icon ${cls}`;
  span.innerHTML = `<svg width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${PATHS[name]}</svg>`;
  return span;
}

// A button: {label, title, iconName, cls ('primary', 'ghost', 'sm', 'icon-only'), onClick, disabled, pressed}.
export function button({label, title, iconName, cls = '', onClick, disabled, pressed, size = 15, type = 'button'} = {}) {
  return h('button', {type, class: `btn ${cls}`, title: title || label, 'aria-label': title || label, disabled,
    'aria-pressed': pressed === undefined ? undefined : String(!!pressed), onclick: onClick},
    iconName ? icon(iconName, size) : null, label && !cls.includes('icon-only') ? h('span', {}, label) : null);
}

// A spinning loader in place of a button's icon while it works.
export async function busy(btn, work) {
  const old = btn.querySelector('.icon');
  const spinner = icon('loader', 15, 'spin');
  if (old) old.replaceWith(spinner); else btn.prepend(spinner);
  btn.disabled = true;
  try { return await work(); }
  finally { btn.disabled = false; if (old) spinner.replaceWith(old); else spinner.remove(); }
}

